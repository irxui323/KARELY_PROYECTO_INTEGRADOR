CREATE OR REPLACE VIEW V_S_CITA_ENMASCARADA AS
SELECT C.ID_CITA,C.FECHA_CITA,C.ESTADO,E.NOMBRE AS ESPECIALIDAD,
       F.HORA_INICIO,F.HORA_FIN,
       CASE WHEN LENGTH(P.NUMERO_DOCUMENTO)>4 THEN
           RPAD('*',LENGTH(P.NUMERO_DOCUMENTO)-2,'*') || SUBSTR(P.NUMERO_DOCUMENTO,-2)
           ELSE '****' END AS DOCUMENTO_ENMASCARADO
FROM CITA C JOIN PACIENTE P ON P.ID_PACIENTE=C.ID_PACIENTE
JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=C.ID_ESPECIALIDAD
JOIN FRANJA_HORARIA F ON F.ID_FRANJA=C.ID_FRANJA;
