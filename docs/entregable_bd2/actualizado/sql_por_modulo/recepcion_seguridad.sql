CREATE OR REPLACE FUNCTION FN_ROL_USUARIO (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE
)
RETURN VARCHAR2
IS
    V_ROL ROL.NOMBRE%TYPE;
BEGIN
    IF P_ID_USUARIO IS NULL
       OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') IS NULL
       OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_USUARIO) THEN
        RAISE_APPLICATION_ERROR(-20200,'La identidad de sesion no coincide.');
    END IF;

    SELECT R.NOMBRE
    INTO V_ROL
    FROM USUARIO U
    JOIN ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.ID_USUARIO = P_ID_USUARIO
      AND U.ESTADO = 'ACTIVO'
      AND R.ESTADO = 'ACTIVO';

    RETURN V_ROL;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20201,'Usuario o rol inexistente o inactivo.');
END FN_ROL_USUARIO;
/

