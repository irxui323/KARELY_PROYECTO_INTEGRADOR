CREATE OR REPLACE VIEW V_S_SEGURIDAD_SESIONES AS
SELECT U.ID_USUARIO,U.USERNAME,U.ESTADO,
       COUNT(S.ID_SESION) AS SESIONES_REGISTRADAS,
       SUM(CASE WHEN S.ESTADO='ACTIVA' THEN 1 ELSE 0 END) AS SESIONES_ACTIVAS
FROM USUARIO U LEFT JOIN SESION_USUARIO S ON S.ID_USUARIO=U.ID_USUARIO
GROUP BY U.ID_USUARIO,U.USERNAME,U.ESTADO;
