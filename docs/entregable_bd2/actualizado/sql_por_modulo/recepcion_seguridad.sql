CREATE OR REPLACE VIEW V_S_USUARIO_ENMASCARADO AS
SELECT ID_USUARIO, USERNAME,
       CASE WHEN INSTR(CORREO, '@') > 2
            THEN SUBSTR(CORREO, 1, 2) || '***' || SUBSTR(CORREO, INSTR(CORREO, '@'))
            ELSE '***' END AS CORREO_ENMASCARADO,
       ESTADO, INTENTOS_FALLIDOS, ULTIMO_ACCESO
  FROM USUARIO;

