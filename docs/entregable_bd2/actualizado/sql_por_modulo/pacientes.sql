CREATE OR REPLACE FUNCTION FN_EDAD_PACIENTE(p_id_paciente NUMBER)
RETURN NUMBER
IS
    v_fecha_nacimiento PACIENTE.FECHA_NACIMIENTO%TYPE;
BEGIN
    SELECT FECHA_NACIMIENTO INTO v_fecha_nacimiento
      FROM PACIENTE WHERE ID_PACIENTE = p_id_paciente;
    RETURN CASE WHEN v_fecha_nacimiento IS NULL THEN NULL
                ELSE TRUNC(MONTHS_BETWEEN(TRUNC(SYSDATE), v_fecha_nacimiento) / 12) END;
EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN NULL;
END;
/

