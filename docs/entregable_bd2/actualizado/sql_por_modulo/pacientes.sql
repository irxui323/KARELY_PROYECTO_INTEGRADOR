CREATE OR REPLACE VIEW V_S_PACIENTE_ENMASCARADO AS
SELECT ID_PACIENTE, TIPO_DOCUMENTO,
       SUBSTR(NUMERO_DOCUMENTO, 1, 2) || '****' || SUBSTR(NUMERO_DOCUMENTO, -2) AS DOCUMENTO_ENMASCARADO,
       NOMBRES, APELLIDOS,
       CASE WHEN INSTR(CORREO, '@') > 2
            THEN SUBSTR(CORREO, 1, 2) || '***' || SUBSTR(CORREO, INSTR(CORREO, '@'))
            ELSE NULL END AS CORREO_ENMASCARADO,
       ESTADO
  FROM PACIENTE;

