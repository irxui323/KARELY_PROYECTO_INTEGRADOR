-- Cuentas activas por rol
SELECT U.USERNAME,R.NOMBRE AS ROL,U.ESTADO
FROM USUARIO U JOIN ROL R ON R.ID_ROL=U.ID_ROL
WHERE U.ESTADO='ACTIVO' ORDER BY R.NOMBRE,U.USERNAME;

-- Control de asistencia del día
SELECT C.ID_CITA,C.FECHA_CITA,
CASE WHEN A.ID_ASISTENCIA IS NULL THEN 'PENDIENTE' ELSE 'PRESENTE' END AS ASISTENCIA
FROM CITA C LEFT JOIN ASISTENCIA A ON A.ID_CITA=C.ID_CITA
WHERE C.FECHA_CITA=TRUNC(SYSDATE);

-- Sesiones por estado
SELECT DECODE(ESTADO,'ACTIVA','En uso','CERRADA','Cerrada','EXPIRADA','Vencida',ESTADO)
AS ESTADO_DESCRIPTIVO,COUNT(*) AS TOTAL
FROM SESION_USUARIO GROUP BY ESTADO;
