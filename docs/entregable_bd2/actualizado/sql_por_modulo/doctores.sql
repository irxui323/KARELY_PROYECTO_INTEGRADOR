CREATE OR REPLACE TRIGGER TR_DOCTOR_ESTADO_VALIDADO
BEFORE INSERT OR UPDATE OF ESTADO_DOCUMENTACION ON DOCTOR
FOR EACH ROW
BEGIN
    IF :NEW.ESTADO_DOCUMENTACION = 'COMPLETO' THEN
        IF FN_DOCUMENTACION_COMPLETA(:NEW.ID_DOCTOR) <> 1 THEN
            RAISE_APPLICATION_ERROR(
                -20001,
                'Se requiere DNI y titulo profesional validados.'
            );
        END IF;
    END IF;
END TR_DOCTOR_ESTADO_VALIDADO;
