CREATE OR REPLACE TRIGGER TR_DOCUMENTO_REVALIDACION
AFTER INSERT OR UPDATE OR DELETE ON DOCUMENTO_DOCTOR
FOR EACH ROW
BEGIN
    IF DELETING THEN
        UPDATE DOCTOR
        SET ESTADO_DOCUMENTACION = 'INCOMPLETO'
        WHERE ID_DOCTOR = :OLD.ID_DOCTOR;
    ELSE
        UPDATE DOCTOR
        SET ESTADO_DOCUMENTACION = 'INCOMPLETO'
        WHERE ID_DOCTOR = :NEW.ID_DOCTOR;

        IF UPDATING AND :OLD.ID_DOCTOR <> :NEW.ID_DOCTOR THEN
            UPDATE DOCTOR
            SET ESTADO_DOCUMENTACION = 'INCOMPLETO'
            WHERE ID_DOCTOR = :OLD.ID_DOCTOR;
        END IF;
    END IF;
END TR_DOCUMENTO_REVALIDACION;
