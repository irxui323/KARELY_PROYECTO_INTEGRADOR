-- Especialidades de cada doctor
SELECT D.ID_DOCTOR, D.NOMBRES, D.APELLIDOS, E.NOMBRE AS ESPECIALIDAD
FROM DOCTOR D JOIN DOCTOR_ESPECIALIDAD DE ON DE.ID_DOCTOR=D.ID_DOCTOR
JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DE.ID_ESPECIALIDAD
WHERE D.ESTADO='ACTIVO' ORDER BY D.APELLIDOS,E.NOMBRE;

-- Cantidad de documentos por doctor
SELECT D.ID_DOCTOR,D.NOMBRES,COUNT(DD.ID_DOCUMENTO) AS DOCUMENTOS
FROM DOCTOR D LEFT JOIN DOCUMENTO_DOCTOR DD ON DD.ID_DOCTOR=D.ID_DOCTOR
GROUP BY D.ID_DOCTOR,D.NOMBRES ORDER BY DOCUMENTOS DESC;

-- Doctores con varias especialidades
SELECT D.ID_DOCTOR,D.NOMBRES,COUNT(*) AS ESPECIALIDADES
FROM DOCTOR D JOIN DOCTOR_ESPECIALIDAD DE ON DE.ID_DOCTOR=D.ID_DOCTOR
GROUP BY D.ID_DOCTOR,D.NOMBRES HAVING COUNT(*)>1;
