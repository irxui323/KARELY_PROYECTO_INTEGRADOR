CREATE OR REPLACE FUNCTION FN_INICIO_TURNO (
    P_FECHA IN DATE,
    P_ID_FRANJA IN FRANJA_HORARIA.ID_FRANJA%TYPE
)
RETURN TIMESTAMP
IS
    V_HORA FRANJA_HORARIA.HORA_INICIO%TYPE;
BEGIN
    SELECT HORA_INICIO
    INTO V_HORA
    FROM FRANJA_HORARIA
    WHERE ID_FRANJA = P_ID_FRANJA
      AND ESTADO = 'ACTIVO';

    RETURN CAST(TRUNC(P_FECHA) AS TIMESTAMP)
        + NUMTODSINTERVAL(
            TO_NUMBER(SUBSTR(V_HORA,1,2)) * 60
            + TO_NUMBER(SUBSTR(V_HORA,4,2)),
            'MINUTE'
        );
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20100, 'Franja horaria no existe o esta inactiva.');
END FN_INICIO_TURNO;
