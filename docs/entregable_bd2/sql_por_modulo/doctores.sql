CREATE OR REPLACE VIEW V_S_HORARIOS_DOCTOR AS
SELECT DD.ID_DOCTOR, DD.FECHA_TURNO, E.NOMBRE AS ESPECIALIDAD,
       F.HORA_INICIO, F.HORA_FIN, DD.ESTADO
FROM DISPONIBILIDAD_DOCTOR DD
JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DD.ID_ESPECIALIDAD
JOIN FRANJA_HORARIA F ON F.ID_FRANJA=DD.ID_FRANJA;
