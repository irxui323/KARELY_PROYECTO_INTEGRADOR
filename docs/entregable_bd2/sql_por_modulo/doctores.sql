CREATE OR REPLACE VIEW V_S_DOCUMENTACION_DOCTOR AS
SELECT D.ID_DOCTOR, D.ESTADO_DOCUMENTACION,
       COUNT(DD.ID_DOCUMENTO) AS DOCUMENTOS,
       SUM(CASE WHEN DD.ESTADO='VALIDADO' THEN 1 ELSE 0 END) AS VALIDADOS
FROM DOCTOR D LEFT JOIN DOCUMENTO_DOCTOR DD ON DD.ID_DOCTOR=D.ID_DOCTOR
GROUP BY D.ID_DOCTOR, D.ESTADO_DOCUMENTACION;

