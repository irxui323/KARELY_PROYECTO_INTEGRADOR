CREATE OR REPLACE FUNCTION FN_DOCUMENTACION_COMPLETA (
    P_ID_DOCTOR IN DOCTOR.ID_DOCTOR%TYPE
)
RETURN NUMBER
IS
    V_CANTIDAD NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_CANTIDAD
    FROM (
        SELECT TIPO_DOCUMENTO, ESTADO, ARCHIVO,
               ROW_NUMBER() OVER (
                   PARTITION BY TIPO_DOCUMENTO
                   ORDER BY ID_DOCUMENTO DESC
               ) AS FILA
        FROM DOCUMENTO_DOCTOR
        WHERE ID_DOCTOR = P_ID_DOCTOR
          AND TIPO_DOCUMENTO IN ('DNI', 'TITULO')
    )
    WHERE FILA = 1
      AND ESTADO = 'VALIDADO'
      AND DBMS_LOB.GETLENGTH(ARCHIVO) > 0;

    IF V_CANTIDAD = 2 THEN
        RETURN 1;
    END IF;

    RETURN 0;
END FN_DOCUMENTACION_COMPLETA;
