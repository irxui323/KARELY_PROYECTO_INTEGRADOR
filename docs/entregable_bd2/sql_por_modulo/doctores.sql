CREATE OR REPLACE PROCEDURE SP_CONSULTAR_HORARIOS_DOCTOR(
    p_id_doctor NUMBER, p_desde DATE, p_hasta DATE, p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
    IF p_desde IS NULL OR p_hasta IS NULL OR TRUNC(p_hasta)<TRUNC(p_desde) THEN
        RAISE_APPLICATION_ERROR(-20972,'Periodo de consulta invalido.');
    END IF;
    OPEN p_resultado FOR SELECT * FROM V_S_HORARIOS_DOCTOR
    WHERE ID_DOCTOR=p_id_doctor AND FECHA_TURNO BETWEEN TRUNC(p_desde) AND TRUNC(p_hasta)
    ORDER BY FECHA_TURNO,HORA_INICIO;
END;
