-- Agenda del día
SELECT C.ID_CITA,F.HORA_INICIO,P.NOMBRES AS PACIENTE,D.NOMBRES AS DOCTOR
FROM CITA C JOIN PACIENTE P ON P.ID_PACIENTE=C.ID_PACIENTE
JOIN DOCTOR D ON D.ID_DOCTOR=C.ID_DOCTOR
JOIN FRANJA_HORARIA F ON F.ID_FRANJA=C.ID_FRANJA
WHERE C.FECHA_CITA=TRUNC(SYSDATE) ORDER BY F.HORA_INICIO;

-- Resumen por fecha
SELECT FECHA_CITA,COUNT(*) AS TOTAL,
SUM(CASE WHEN ESTADO='ATENDIDA' THEN 1 ELSE 0 END) AS ATENDIDAS
FROM CITA GROUP BY FECHA_CITA ORDER BY FECHA_CITA;

-- Citas de importe superior al promedio
SELECT ID_CITA,FECHA_CITA,MONTO_TOTAL FROM CITA
WHERE MONTO_TOTAL>(SELECT AVG(MONTO_TOTAL) FROM CITA)
ORDER BY MONTO_TOTAL DESC;
