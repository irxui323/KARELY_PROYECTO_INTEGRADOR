-- Total pagado por doctor
SELECT D.ID_DOCTOR,D.NOMBRES,SUM(L.MONTO) AS TOTAL_PAGADO
FROM LIQUIDACION L JOIN DOCTOR D ON D.ID_DOCTOR=L.ID_DOCTOR
GROUP BY D.ID_DOCTOR,D.NOMBRES HAVING SUM(L.MONTO)>0;

-- Ingresos mensuales de la gestora
SELECT TO_CHAR(FECHA_CITA,'YYYY-MM') AS MES,CONCEPTO,
SUM(MONTO_INGRESO) AS INGRESO FROM VW_INGRESOS_GESTORA
GROUP BY TO_CHAR(FECHA_CITA,'YYYY-MM'),CONCEPTO ORDER BY MES;

-- Saldo actual por doctor
SELECT ID_DOCTOR,NOMBRES,FN_SALDO_DOCTOR(ID_DOCTOR,TRUNC(SYSDATE)) AS SALDO
FROM DOCTOR WHERE ESTADO='ACTIVO' ORDER BY ID_DOCTOR;
