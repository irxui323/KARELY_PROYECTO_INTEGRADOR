CREATE OR REPLACE PROCEDURE SP_CREAR_USUARIO (
    P_ID_ADMIN      IN  USUARIO.ID_USUARIO%TYPE,
    P_ID_ROL        IN  ROL.ID_ROL%TYPE,
    P_USERNAME      IN  USUARIO.USERNAME%TYPE,
    P_CORREO        IN  USUARIO.CORREO%TYPE,
    P_PASSWORD_HASH IN  USUARIO.PASSWORD_HASH%TYPE,
    P_ID_USUARIO    OUT USUARIO.ID_USUARIO%TYPE
)
IS
    V_CANTIDAD NUMBER;
BEGIN
    P_ID_USUARIO := NULL;
    SAVEPOINT SV_CREAR_USUARIO;

    IF FN_ROL_USUARIO(P_ID_ADMIN) <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20601,'Solo administracion puede crear usuarios.');
    END IF;

    IF TRIM(P_USERNAME) IS NULL OR TRIM(P_CORREO) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20602,'Username y correo son obligatorios.');
    END IF;

    -- Los hashes deben proceder de un componente de autenticacion:
    -- NO enviar ni guardar contrasenas en texto plano.
    IF P_PASSWORD_HASH IS NULL
       OR LENGTH(P_PASSWORD_HASH) < 50
       OR (SUBSTR(P_PASSWORD_HASH,1,10) <> '$argon2id$'
           AND SUBSTR(P_PASSWORD_HASH,1,4) NOT IN ('$2a$','$2b$','$2y$')) THEN
        RAISE_APPLICATION_ERROR(-20603,
            'Se requiere un hash Argon2id o bcrypt valido, generado por el backend.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM ROL
    WHERE ID_ROL = P_ID_ROL AND ESTADO = 'ACTIVO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20604,'El rol indicado no existe o esta inactivo.');
    END IF;

    -- Normalizacion de claves de acceso: evita variantes en nuevos registros.
    INSERT INTO USUARIO (ID_ROL, USERNAME, CORREO, PASSWORD_HASH)
    VALUES (P_ID_ROL, LOWER(TRIM(P_USERNAME)), LOWER(TRIM(P_CORREO)),
            P_PASSWORD_HASH)
    RETURNING ID_USUARIO INTO P_ID_USUARIO;

    INSERT INTO AUDITORIA (
        ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO, ACCION, DETALLE, ORIGEN
    ) VALUES (
        P_ID_ADMIN, 'USUARIO', P_ID_USUARIO, 'CREAR',
        'Usuario creado con rol ID ' || P_ID_ROL, 'USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Usuario creado: ' || P_ID_USUARIO);
    DBMS_OUTPUT.PUT_LINE('COMMIT pendiente.');
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SV_CREAR_USUARIO;
        RAISE_APPLICATION_ERROR(-20605,'Username o correo ya registrado.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_CREAR_USUARIO;
        RAISE;
END SP_CREAR_USUARIO;
/

