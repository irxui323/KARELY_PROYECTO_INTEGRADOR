CREATE OR REPLACE PROCEDURE SP_CERRAR_SESION (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_SESION  IN SESION_USUARIO.ID_SESION%TYPE
)
IS
    V_ROL ROL.NOMBRE%TYPE;
    V_DUENO SESION_USUARIO.ID_USUARIO%TYPE;
    V_ESTADO SESION_USUARIO.ESTADO%TYPE;
BEGIN
    SAVEPOINT SV_CERRAR_SESION;
    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);

    SELECT ID_USUARIO, ESTADO INTO V_DUENO,V_ESTADO
    FROM SESION_USUARIO
    WHERE ID_SESION = P_ID_SESION FOR UPDATE;

    IF V_DUENO <> P_ID_USUARIO AND V_ROL <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20628,'No puede cerrar sesiones de otro usuario.');
    END IF;

    IF V_ESTADO <> 'ACTIVA' THEN
        RAISE_APPLICATION_ERROR(-20629,'La sesion ya esta cerrada o expirada.');
    END IF;

    UPDATE SESION_USUARIO
    SET ESTADO = 'CERRADA',
        FECHA_FIN = CAST(SYSTIMESTAMP AS TIMESTAMP),
        ULTIMA_ACTIVIDAD = CAST(SYSTIMESTAMP AS TIMESTAMP)
    WHERE ID_SESION = P_ID_SESION;

    INSERT INTO AUDITORIA (
        ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,ORIGEN
    ) VALUES (
        P_ID_USUARIO,'SESION_USUARIO',P_ID_SESION,'CERRAR',
        'Sesion cerrada por usuario autorizado','USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Sesion cerrada: ' || P_ID_SESION);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_CERRAR_SESION;
        RAISE_APPLICATION_ERROR(-20630,'La sesion no existe.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_CERRAR_SESION;
        RAISE;
END SP_CERRAR_SESION;
/

