CREATE OR REPLACE PROCEDURE SP_CREAR_RECETA (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA IN CITA.ID_CITA%TYPE,
    P_INDICACIONES IN RECETA.INDICACIONES%TYPE,
    P_ID_RECETA OUT RECETA.ID_RECETA%TYPE
)
IS
    V_ID_DOCTOR CITA.ID_DOCTOR%TYPE;
    V_ESTADO_CITA CITA.ESTADO%TYPE;
    V_ID_ATENCION ATENCION_MEDICA.ID_ATENCION%TYPE;
    V_ESTADO_ATENCION ATENCION_MEDICA.ESTADO%TYPE;
    V_CANTIDAD NUMBER;
BEGIN
    P_ID_RECETA := NULL;
    SAVEPOINT SV_CREAR_RECETA;

    IF NVL(FN_ROL_USUARIO(P_ID_USUARIO),'SIN_ROL') NOT IN ('DOCTOR','ADMINISTRADORA') THEN
        RAISE_APPLICATION_ERROR(-20407,'Solo el doctor puede emitir una receta.');
    END IF;
    IF TRIM(P_INDICACIONES) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20408,'Las indicaciones son obligatorias.');
    END IF;

    SELECT ID_DOCTOR,ESTADO INTO V_ID_DOCTOR,V_ESTADO_CITA
      FROM CITA WHERE ID_CITA = P_ID_CITA FOR UPDATE;
    IF V_ESTADO_CITA <> 'EN_ATENCION' THEN
        RAISE_APPLICATION_ERROR(-20409,'La cita no esta EN_ATENCION.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD FROM DOCTOR
     WHERE ID_DOCTOR=V_ID_DOCTOR AND (ID_USUARIO = P_ID_USUARIO OR FN_ROL_USUARIO(P_ID_USUARIO) = 'ADMINISTRADORA') AND ESTADO='ACTIVO';
    IF V_CANTIDAD <> 1 THEN
        RAISE_APPLICATION_ERROR(-20410,'El usuario no es el doctor asignado.');
    END IF;

    SELECT ID_ATENCION,ESTADO INTO V_ID_ATENCION,V_ESTADO_ATENCION
      FROM ATENCION_MEDICA
     WHERE ID_CITA=P_ID_CITA AND ID_DOCTOR=V_ID_DOCTOR FOR UPDATE;
    IF V_ESTADO_ATENCION <> 'ABIERTA' THEN
        RAISE_APPLICATION_ERROR(-20411,'La atencion ya fue cerrada.');
    END IF;

    INSERT INTO RECETA (ID_ATENCION,INDICACIONES)
    VALUES (V_ID_ATENCION,TRIM(P_INDICACIONES))
    RETURNING ID_RECETA INTO P_ID_RECETA;

    INSERT INTO AUDITORIA (ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,ORIGEN)
    VALUES (P_ID_USUARIO,'RECETA',P_ID_RECETA,'CREAR',
            'Receta registrada en atencion '||V_ID_ATENCION,'USUARIO');

    DBMS_OUTPUT.PUT_LINE('Receta creada: '||P_ID_RECETA);
EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SV_CREAR_RECETA;
        RAISE_APPLICATION_ERROR(-20412,'La atencion ya tiene una receta.');
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_CREAR_RECETA;
        RAISE_APPLICATION_ERROR(-20413,'Cita o atencion medica no encontrada.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_CREAR_RECETA;
        RAISE;
END SP_CREAR_RECETA;
/

