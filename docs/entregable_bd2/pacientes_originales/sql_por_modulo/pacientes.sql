CREATE OR REPLACE TRIGGER TR_AUD_PACIENTE_DATOS
AFTER INSERT OR UPDATE OR DELETE ON PACIENTE
FOR EACH ROW
DECLARE
    v_accion VARCHAR2(20);
    v_detalle VARCHAR2(500);
BEGIN
    IF INSERTING THEN
        v_accion := 'INSERTAR'; v_detalle := 'Paciente creado';
    ELSIF UPDATING THEN
        v_accion := 'ACTUALIZAR'; v_detalle := 'Paciente actualizado';
    ELSE
        v_accion := 'ELIMINAR'; v_detalle := 'Paciente eliminado';
    END IF;
    INSERT INTO AUDITORIA(ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO, ACCION, DETALLE, ORIGEN)
    VALUES (NULL, 'PACIENTE', NVL(:NEW.ID_PACIENTE, :OLD.ID_PACIENTE), v_accion,
        v_detalle || '. Sesion Oracle: ' || SYS_CONTEXT('USERENV', 'SESSION_USER')
        || '. Identificador aplicacion: ' || SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), 'SISTEMA');
END;
/

