CREATE OR REPLACE VIEW V_S_RECETAS_PACIENTE AS
SELECT C.ID_PACIENTE,C.ID_CITA,R.ID_RECETA,R.FECHA_EMISION,
       COUNT(RD.ID_DETALLE) AS TOTAL_MEDICAMENTOS
FROM CITA C JOIN ATENCION_MEDICA A ON A.ID_CITA=C.ID_CITA
JOIN RECETA R ON R.ID_ATENCION=A.ID_ATENCION
LEFT JOIN RECETA_DETALLE RD ON RD.ID_RECETA=R.ID_RECETA
GROUP BY C.ID_PACIENTE,C.ID_CITA,R.ID_RECETA,R.FECHA_EMISION;
