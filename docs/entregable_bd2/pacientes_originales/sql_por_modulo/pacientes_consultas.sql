-- Pacientes sin citas
SELECT P.ID_PACIENTE,P.NOMBRES,P.APELLIDOS
FROM PACIENTE P LEFT JOIN CITA C ON C.ID_PACIENTE=P.ID_PACIENTE
WHERE C.ID_CITA IS NULL;

-- Atenciones cerradas por paciente
SELECT P.ID_PACIENTE,P.NOMBRES,COUNT(A.ID_ATENCION) AS ATENCIONES
FROM ATENCION_MEDICA A JOIN CITA C ON C.ID_CITA=A.ID_CITA
JOIN PACIENTE P ON P.ID_PACIENTE=C.ID_PACIENTE
WHERE A.ESTADO='CERRADA' GROUP BY P.ID_PACIENTE,P.NOMBRES;

-- Cantidad de citas incluyendo pacientes sin reservas
SELECT P.ID_PACIENTE,P.NOMBRES,COUNT(C.ID_CITA) AS CITAS
FROM CITA C RIGHT JOIN PACIENTE P ON P.ID_PACIENTE=C.ID_PACIENTE
GROUP BY P.ID_PACIENTE,P.NOMBRES ORDER BY P.ID_PACIENTE;
