-- Exposicion Karely: procedimientos NUEVOS de consulta.
-- Ejecutar como KARELY_BD2 con F5. No instala datos ni reemplaza SP existentes.
-- AUTHID CURRENT_USER usa los privilegios de quien ejecuta; no se conceden GRANT.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

SELECT OBJECT_NAME, STATUS FROM USER_OBJECTS
WHERE OBJECT_TYPE = 'PROCEDURE' AND OBJECT_NAME IN (
    'SP_EXP_ESPECIALIDADES_DOC',
    'SP_EXP_DOCUMENTOS_DOC',
    'SP_EXP_HORARIOS_DOC',
    'SP_EXP_AGENDA_DIA',
    'SP_EXP_RESUMEN_CITAS',
    'SP_EXP_CAMBIO_CITA',
    'SP_EXP_BUSCAR_PACIENTE',
    'SP_EXP_HISTORIAL_PAC',
    'SP_EXP_DETALLE_RECETA',
    'SP_EXP_COBROS_PERIODO',
    'SP_EXP_PAGOS_DOCTOR',
    'SP_EXP_INGRESOS_GESTORA',
    'SP_EXP_ASISTENCIAS_DIA',
    'SP_EXP_USUARIOS_ESTADO',
    'SP_EXP_SESIONES_USUARIO'
) ORDER BY OBJECT_NAME;

SELECT NAME, LINE, POSITION, TEXT FROM USER_ERRORS
WHERE TYPE = 'PROCEDURE' AND NAME IN (
    'SP_EXP_ESPECIALIDADES_DOC',
    'SP_EXP_DOCUMENTOS_DOC',
    'SP_EXP_HORARIOS_DOC',
    'SP_EXP_AGENDA_DIA',
    'SP_EXP_RESUMEN_CITAS',
    'SP_EXP_CAMBIO_CITA',
    'SP_EXP_BUSCAR_PACIENTE',
    'SP_EXP_HISTORIAL_PAC',
    'SP_EXP_DETALLE_RECETA',
    'SP_EXP_COBROS_PERIODO',
    'SP_EXP_PAGOS_DOCTOR',
    'SP_EXP_INGRESOS_GESTORA',
    'SP_EXP_ASISTENCIAS_DIA',
    'SP_EXP_USUARIOS_ESTADO',
    'SP_EXP_SESIONES_USUARIO'
) ORDER BY NAME, SEQUENCE;

DECLARE
    v_validos NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_validos FROM USER_OBJECTS
    WHERE OBJECT_TYPE = 'PROCEDURE' AND STATUS = 'VALID'
      AND OBJECT_NAME IN (
    'SP_EXP_ESPECIALIDADES_DOC',
    'SP_EXP_DOCUMENTOS_DOC',
    'SP_EXP_HORARIOS_DOC',
    'SP_EXP_AGENDA_DIA',
    'SP_EXP_RESUMEN_CITAS',
    'SP_EXP_CAMBIO_CITA',
    'SP_EXP_BUSCAR_PACIENTE',
    'SP_EXP_HISTORIAL_PAC',
    'SP_EXP_DETALLE_RECETA',
    'SP_EXP_COBROS_PERIODO',
    'SP_EXP_PAGOS_DOCTOR',
    'SP_EXP_INGRESOS_GESTORA',
    'SP_EXP_ASISTENCIAS_DIA',
    'SP_EXP_USUARIOS_ESTADO',
    'SP_EXP_SESIONES_USUARIO'
    );
    IF v_validos <> 15 THEN
        RAISE_APPLICATION_ERROR(-20881, 'Faltan procedimientos validos. Revisar USER_ERRORS.');
    END IF;
    DBMS_OUTPUT.PUT_LINE('CORRECTO: 15 procedimientos validos, 3 por modulo.');
END;
