SELECT c.ID_CITA,c.FECHA_CITA,f.HORA_INICIO,d.NOMBRES||' '||d.APELLIDOS AS DOCTOR,e.NOMBRE AS ESPECIALIDAD,c.ESTADO,c.MONTO_TOTAL
FROM CITA c JOIN PAGO_CITA pc ON pc.ID_PAGO=c.ID_PAGO JOIN DOCTOR d ON d.ID_DOCTOR=c.ID_DOCTOR
JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=c.ID_ESPECIALIDAD JOIN FRANJA_HORARIA f ON f.ID_FRANJA=c.ID_FRANJA
WHERE pc.REFERENCIA_PAGO LIKE 'DEMO-FIN17-%' ORDER BY c.FECHA_CITA,c.ID_CITA;
SELECT * FROM VW_INGRESOS_GESTORA WHERE ID_CITA IN (SELECT c.ID_CITA FROM CITA c JOIN PAGO_CITA pc ON pc.ID_PAGO=c.ID_PAGO WHERE pc.REFERENCIA_PAGO LIKE 'DEMO-FIN17-%');
SELECT ID_DOCTOR,MONTO,NUMERO_OPERACION,NUMERO_BOLETA FROM LIQUIDACION WHERE NUMERO_OPERACION='DEMO-FIN17-PAGO-COMPLETO';
SELECT d.ID_DOCTOR,d.NOMBRES||' '||d.APELLIDOS AS DOCTOR,FN_SALDO_DOCTOR(d.ID_DOCTOR,TRUNC(SYSDATE)) AS SALDO_PENDIENTE
FROM DOCTOR d WHERE EXISTS(SELECT 1 FROM CITA c JOIN PAGO_CITA pc ON pc.ID_PAGO=c.ID_PAGO WHERE c.ID_DOCTOR=d.ID_DOCTOR AND pc.REFERENCIA_PAGO LIKE 'DEMO-FIN17-%');
