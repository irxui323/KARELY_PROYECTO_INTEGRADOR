SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_admin NUMBER;
    v_tesoreria NUMBER;
    v_franja NUMBER;
    v_total NUMBER;
    v_consultorio NUMBER;
    v_paciente NUMBER;
    v_especialidad NUMBER;
    v_precio NUMBER;
    v_pre NUMBER;
    v_pago NUMBER;
    v_cita NUMBER;
    v_atencion NUMBER;
    v_receta NUMBER;
    v_liquidacion NUMBER;
    v_devengo NUMBER;
    v_fecha DATE;
    v_importe_pago NUMBER;
    v_doc_pagado NUMBER;
    v_indice NUMBER:=0;
    v_referencia VARCHAR2(80);
BEGIN
    IF USER<>'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20980,'Usar KARELY_BD2'); END IF;
    SELECT COUNT(*) INTO v_total FROM PAGO_CITA WHERE REFERENCIA_PAGO LIKE 'DEMO-FIN17-%';
    IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20981,'Escenario ya cargado; no se duplicaron datos'); END IF;
    SELECT MIN(u.ID_USUARIO) INTO v_admin FROM USUARIO u JOIN ROL r ON r.ID_ROL=u.ID_ROL
    WHERE u.ESTADO='ACTIVO' AND r.ESTADO='ACTIVO' AND r.NOMBRE='ADMINISTRADORA';
    SELECT MIN(u.ID_USUARIO) INTO v_tesoreria FROM USUARIO u JOIN ROL r ON r.ID_ROL=u.ID_ROL
    WHERE u.ESTADO='ACTIVO' AND r.ESTADO='ACTIVO' AND r.NOMBRE='TESORERA';
    IF v_admin IS NULL OR v_tesoreria IS NULL THEN RAISE_APPLICATION_ERROR(-20982,'Se requiere administradora y tesorera activas'); END IF;
    SELECT MIN(ID_FRANJA) INTO v_franja FROM FRANJA_HORARIA WHERE HORA_INICIO='17:00' AND HORA_FIN='18:00' AND ESTADO='ACTIVO';
    IF v_franja IS NULL THEN RAISE_APPLICATION_ERROR(-20983,'Falta franja activa 17:00 a 18:00'); END IF;
    SELECT COUNT(*) INTO v_total FROM CONSULTORIO WHERE ESTADO='ACTIVO';
    IF v_total<2 THEN RAISE_APPLICATION_ERROR(-20984,'Se necesitan dos consultorios activos'); END IF;
    SELECT COUNT(*) INTO v_total FROM DOCTOR d WHERE d.ESTADO='ACTIVO' AND d.ESTADO_DOCUMENTACION='COMPLETO'
    AND d.ID_USUARIO IS NOT NULL AND EXISTS(SELECT 1 FROM USUARIO u WHERE u.ID_USUARIO=d.ID_USUARIO AND u.ESTADO='ACTIVO')
    AND EXISTS(SELECT 1 FROM DOCTOR_ESPECIALIDAD de JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=de.ID_ESPECIALIDAD
        WHERE de.ID_DOCTOR=d.ID_DOCTOR AND e.ESTADO='ACTIVO' AND e.PRECIO_CONSULTA>0)
    AND NOT EXISTS(SELECT 1 FROM CITA c JOIN FRANJA_HORARIA f ON f.ID_FRANJA=c.ID_FRANJA
        WHERE c.ID_DOCTOR=d.ID_DOCTOR AND c.FECHA_CITA=TRUNC(SYSDATE) AND c.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
        AND f.HORA_INICIO<'18:00' AND f.HORA_FIN>'17:00');
    IF v_total<2 THEN RAISE_APPLICATION_ERROR(-20985,'Se requieren dos doctores habilitados sin cita ocupada hoy de 17 a 18'); END IF;
    SELECT COUNT(*) INTO v_total FROM CITA c JOIN FRANJA_HORARIA f ON f.ID_FRANJA=c.ID_FRANJA
    WHERE c.FECHA_CITA=TRUNC(SYSDATE) AND c.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
    AND f.HORA_INICIO<'18:00' AND f.HORA_FIN>'17:00'
    AND c.ID_CONSULTORIO IN (SELECT ID_CONSULTORIO FROM CONSULTORIO WHERE ESTADO='ACTIVO' ORDER BY ID_CONSULTORIO FETCH FIRST 2 ROWS ONLY);
    IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20986,'Uno de los dos consultorios ya esta ocupado a las 17'); END IF;
    DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_admin));
    FOR i IN 1..4 LOOP
        SELECT COUNT(*) INTO v_total FROM PACIENTE WHERE TIPO_DOCUMENTO='DNI' AND NUMERO_DOCUMENTO=TO_CHAR(97771000+i);
        IF v_total=0 THEN
            INSERT INTO PACIENTE(TIPO_DOCUMENTO,NUMERO_DOCUMENTO,NOMBRES,APELLIDOS,TELEFONO,CORREO,ESTADO,FECHA_NACIMIENTO)
            VALUES('DNI',TO_CHAR(97771000+i),'DEMO Finanzas '||i,'Paciente prueba','90077100'||i,'demo.finanzas'||i||'@example.com','ACTIVO',ADD_MONTHS(TRUNC(SYSDATE),-360));
        END IF;
    END LOOP;
    FOR d IN (
        SELECT d.ID_DOCTOR FROM DOCTOR d WHERE d.ESTADO='ACTIVO' AND d.ESTADO_DOCUMENTACION='COMPLETO'
        AND d.ID_USUARIO IS NOT NULL AND EXISTS(SELECT 1 FROM USUARIO u WHERE u.ID_USUARIO=d.ID_USUARIO AND u.ESTADO='ACTIVO')
        AND EXISTS(SELECT 1 FROM DOCTOR_ESPECIALIDAD de JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=de.ID_ESPECIALIDAD
            WHERE de.ID_DOCTOR=d.ID_DOCTOR AND e.ESTADO='ACTIVO' AND e.PRECIO_CONSULTA>0)
        AND NOT EXISTS(SELECT 1 FROM CITA c JOIN FRANJA_HORARIA f ON f.ID_FRANJA=c.ID_FRANJA
            WHERE c.ID_DOCTOR=d.ID_DOCTOR AND c.FECHA_CITA=TRUNC(SYSDATE) AND c.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
            AND f.HORA_INICIO<'18:00' AND f.HORA_FIN>'17:00')
        ORDER BY d.ID_DOCTOR FETCH FIRST 2 ROWS ONLY
    ) LOOP
        v_indice:=v_indice+1;
        SELECT ID_CONSULTORIO INTO v_consultorio FROM (SELECT ID_CONSULTORIO,ROW_NUMBER() OVER(ORDER BY ID_CONSULTORIO) RN FROM CONSULTORIO WHERE ESTADO='ACTIVO') WHERE RN=v_indice;
        SELECT MIN(e.ID_ESPECIALIDAD) INTO v_especialidad FROM DOCTOR_ESPECIALIDAD de JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=de.ID_ESPECIALIDAD
        WHERE de.ID_DOCTOR=d.ID_DOCTOR AND e.ESTADO='ACTIVO' AND e.PRECIO_CONSULTA>0;
        FOR escenario IN 1..2 LOOP
            v_fecha:=TRUNC(SYSDATE)-CASE WHEN escenario=1 THEN 1 ELSE 0 END;
            IF escenario=2 THEN
                SELECT COALESCE(MAX(ID_ESPECIALIDAD),v_especialidad) INTO v_especialidad FROM DISPONIBILIDAD_DOCTOR
                WHERE ID_DOCTOR=d.ID_DOCTOR AND ID_FRANJA=v_franja AND FECHA_TURNO=v_fecha;
            END IF;
            SELECT PRECIO_CONSULTA INTO v_precio FROM ESPECIALIDAD WHERE ID_ESPECIALIDAD=v_especialidad AND ESTADO='ACTIVO';
            SELECT COUNT(*) INTO v_total FROM DISPONIBILIDAD_DOCTOR WHERE ID_DOCTOR=d.ID_DOCTOR AND ID_FRANJA=v_franja AND FECHA_TURNO=v_fecha;
            IF v_total=0 THEN
                INSERT INTO DISPONIBILIDAD_DOCTOR(ID_DOCTOR,ID_FRANJA,FECHA_TURNO,ID_ESPECIALIDAD)
                VALUES(d.ID_DOCTOR,v_franja,v_fecha,v_especialidad);
            END IF;
            SELECT MIN(ID_PACIENTE) INTO v_paciente FROM PACIENTE WHERE TIPO_DOCUMENTO='DNI' AND NUMERO_DOCUMENTO=TO_CHAR(97771000+v_indice+(escenario-1)*2) AND ESTADO='ACTIVO';
            IF v_paciente IS NULL THEN RAISE_APPLICATION_ERROR(-20987,'Paciente DEMO inactivo'); END IF;
            v_referencia:='DEMO-FIN17-'||v_indice||'-'||escenario;
            INSERT INTO PRE_RESERVA_CITA(ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,ID_FRANJA,FECHA_CITA,MONTO,FECHA_BLOQUEO,FECHA_EXPIRACION,ESTADO)
            VALUES(v_paciente,d.ID_DOCTOR,v_especialidad,v_consultorio,v_franja,v_fecha,v_precio,CAST(v_fecha AS TIMESTAMP)+INTERVAL '16' HOUR,CAST(v_fecha AS TIMESTAMP)+INTERVAL '16' HOUR+INTERVAL '10' MINUTE,'CONFIRMADA')
            RETURNING ID_PRE_RESERVA INTO v_pre;
            INSERT INTO PAGO_CITA(ID_PRE_RESERVA,ID_PACIENTE,MONTO,METODO_PAGO,REFERENCIA_PAGO,FECHA_PAGO)
            VALUES(v_pre,v_paciente,v_precio,'EFECTIVO',v_referencia,CAST(v_fecha AS TIMESTAMP)+INTERVAL '16' HOUR) RETURNING ID_PAGO INTO v_pago;
            INSERT INTO CITA(ID_PRE_RESERVA,ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,ID_FRANJA,ID_PAGO,FECHA_CITA,MONTO_TOTAL,ESTADO)
            VALUES(v_pre,v_paciente,d.ID_DOCTOR,v_especialidad,v_consultorio,v_franja,v_pago,v_fecha,v_precio,CASE WHEN escenario=1 THEN 'ATENDIDA' ELSE 'EN_ATENCION' END)
            RETURNING ID_CITA INTO v_cita;
            INSERT INTO ASISTENCIA(ID_CITA,FECHA_REGISTRO,ESTADO) VALUES(v_cita,CAST(v_fecha AS TIMESTAMP)+INTERVAL '16' HOUR+INTERVAL '45' MINUTE,'PRESENTE');
            IF escenario=1 THEN
                INSERT INTO ATENCION_MEDICA(ID_CITA,ID_DOCTOR,DIAGNOSTICO,OBSERVACIONES,FECHA_INICIO,FECHA_CIERRE,ESTADO)
                VALUES(v_cita,d.ID_DOCTOR,'DEMO: diagnostico ficticio','DEMO: sin valor clinico',CAST(v_fecha AS TIMESTAMP)+INTERVAL '17' HOUR,CAST(v_fecha AS TIMESTAMP)+INTERVAL '18' HOUR,'CERRADA') RETURNING ID_ATENCION INTO v_atencion;
                INSERT INTO RECETA(ID_ATENCION,INDICACIONES,FECHA_EMISION) VALUES(v_atencion,'DEMO: no administrar, solo pruebas',CAST(v_fecha AS TIMESTAMP)+INTERVAL '17' HOUR+INTERVAL '20' MINUTE) RETURNING ID_RECETA INTO v_receta;
                INSERT INTO RECETA_DETALLE(ID_RECETA,MEDICAMENTO,DOSIS,FRECUENCIA,DURACION) VALUES(v_receta,'DEMO ficticio','NO ADMINISTRAR','NO APLICA','NO APLICA');
                INSERT INTO RECIBO_HONORARIO(ID_CITA,NUMERO_RECIBO,MONTO,ID_DOCTOR_EMISOR,FECHA_EMISION,FECHA_ENTREGA,MEDIO_ENTREGA,ID_USUARIO_ENTREGA)
                VALUES(v_cita,v_referencia,v_precio,d.ID_DOCTOR,CAST(v_fecha AS TIMESTAMP)+INTERVAL '17' HOUR+INTERVAL '30' MINUTE,CAST(v_fecha AS TIMESTAMP)+INTERVAL '18' HOUR,'PRESENCIAL',v_admin);
                v_devengo:=FN_MONTO_DOCTOR(v_precio);
                UPDATE CITA SET MONTO_DOCTOR_DEVENGADO=v_devengo,MONTO_GESTORA_DEVENGADO=v_precio-v_devengo WHERE ID_CITA=v_cita;
                IF v_indice=1 THEN v_doc_pagado:=d.ID_DOCTOR;v_importe_pago:=v_devengo; END IF;
            END IF;
        END LOOP;
    END LOOP;
    IF v_importe_pago>0 THEN
        DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_tesoreria));
        SP_PAGAR_DOCTOR(v_tesoreria,v_doc_pagado,TRUNC(SYSDATE)-1,TRUNC(SYSDATE)-1,v_importe_pago,'EFECTIVO','DEMO-FIN17-PAGO-COMPLETO','DEMO-FIN17-BOLETA',v_liquidacion);
    END IF;
    DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_admin));
    INSERT INTO AUDITORIA(ID_USUARIO,TABLA_AFECTADA,ACCION,DETALLE,ORIGEN)
    VALUES(v_admin,'CITA','CARGA_DEMO','DEMO: dos consultas atendidas ayer y dos citas hoy 17:00 con asistencia sintetica; un honorario pagado completo y otro pendiente','SISTEMA');
    COMMIT;
    DBMS_SESSION.CLEAR_IDENTIFIER;
    DBMS_OUTPUT.PUT_LINE('DEMO cargada: 2 atenciones de ayer con ingresos, 1 liquidacion completa y 2 citas de hoy 17:00 EN_ATENCION.');
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    DBMS_SESSION.CLEAR_IDENTIFIER;
    RAISE;
END;
