SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_admin NUMBER;
    v_total NUMBER;
    v_consultorio NUMBER;
    v_paciente NUMBER;
    v_disponibilidad NUMBER;
    v_reserva NUMBER;
    v_cita NUMBER;
    v_especialidad NUMBER;
    v_horarios NUMBER:=0;
    v_citas NUMBER:=0;
    v_dni VARCHAR2(20);
BEGIN
    IF USER <> 'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20971,'Usar KARELY_BD2'); END IF;
    SELECT COUNT(*) INTO v_total FROM USER_TAB_COLUMNS WHERE TABLE_NAME='DISPONIBILIDAD_DOCTOR' AND COLUMN_NAME='ID_ESPECIALIDAD';
    IF v_total<>1 THEN RAISE_APPLICATION_ERROR(-20972,'Aplicar primero migracion disponibilidad-especialidad'); END IF;
    SELECT COUNT(*) INTO v_total FROM CITA;
    IF v_total<>0 THEN RAISE_APPLICATION_ERROR(-20973,'Ejecutar limpieza primero; existen citas'); END IF;
    SELECT COUNT(*) INTO v_total FROM DISPONIBILIDAD_DOCTOR;
    IF v_total<>0 THEN RAISE_APPLICATION_ERROR(-20974,'Ejecutar limpieza primero; existen horarios'); END IF;
    SELECT MIN(u.ID_USUARIO) INTO v_admin FROM USUARIO u JOIN ROL r ON r.ID_ROL=u.ID_ROL
    WHERE u.ESTADO='ACTIVO' AND r.ESTADO='ACTIVO' AND r.NOMBRE='ADMINISTRADORA';
    IF v_admin IS NULL THEN RAISE_APPLICATION_ERROR(-20975,'Falta administradora activa'); END IF;
    SELECT COUNT(*) INTO v_total FROM DOCTOR d WHERE d.ESTADO='ACTIVO' AND d.ESTADO_DOCUMENTACION='COMPLETO'
    AND EXISTS(SELECT 1 FROM DOCTOR_ESPECIALIDAD de JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=de.ID_ESPECIALIDAD WHERE de.ID_DOCTOR=d.ID_DOCTOR AND e.ESTADO='ACTIVO');
    IF v_total=0 THEN RAISE_APPLICATION_ERROR(-20976,'Falta doctor activo, validado y con especialidad'); END IF;
    SELECT MIN(ID_CONSULTORIO) INTO v_consultorio FROM CONSULTORIO WHERE ESTADO='ACTIVO';
    IF v_consultorio IS NULL THEN RAISE_APPLICATION_ERROR(-20977,'Falta consultorio activo'); END IF;
    SELECT COUNT(*) INTO v_total FROM FRANJA_HORARIA WHERE ESTADO='ACTIVO'
    AND HORA_INICIO IN ('08:00','09:00','10:00','11:00','12:00','13:00','14:00','15:00','16:00','17:00')
    AND HORA_FIN=TO_CHAR(TO_DATE(HORA_INICIO,'HH24:MI')+1/24,'HH24:MI');
    IF v_total=0 THEN RAISE_APPLICATION_ERROR(-20978,'Faltan franjas activas de una hora entre 08 y 18'); END IF;
    DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_admin));
    FOR i IN 1..6 LOOP
        v_dni:=TO_CHAR(97770000+i);
        SELECT COUNT(*) INTO v_total FROM PACIENTE WHERE TIPO_DOCUMENTO='DNI' AND NUMERO_DOCUMENTO=v_dni;
        IF v_total=0 THEN
            INSERT INTO PACIENTE(TIPO_DOCUMENTO,NUMERO_DOCUMENTO,NOMBRES,APELLIDOS,TELEFONO,CORREO,DIRECCION,ESTADO,FECHA_NACIMIENTO)
            VALUES('DNI',v_dni,'DEMO Paciente '||i,'Prueba','90077000'||i,'demo.paciente'||i||'@example.com','Direccion de prueba','ACTIVO',ADD_MONTHS(TRUNC(SYSDATE),-360));
        END IF;
    END LOOP;
    FOR d IN (SELECT ID_DOCTOR FROM DOCTOR WHERE ESTADO='ACTIVO' AND ESTADO_DOCUMENTACION='COMPLETO' ORDER BY ID_DOCTOR) LOOP
        SELECT COUNT(*) INTO v_total FROM DOCTOR_ESPECIALIDAD de JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=de.ID_ESPECIALIDAD
        WHERE de.ID_DOCTOR=d.ID_DOCTOR AND e.ESTADO='ACTIVO';
        IF v_total>0 THEN
            FOR dia IN 0..14 LOOP
                FOR f IN (SELECT ID_FRANJA,HORA_INICIO FROM FRANJA_HORARIA WHERE ESTADO='ACTIVO'
                AND HORA_INICIO IN ('08:00','09:00','10:00','11:00','12:00','13:00','14:00','15:00','16:00','17:00')
                AND HORA_FIN=TO_CHAR(TO_DATE(HORA_INICIO,'HH24:MI')+1/24,'HH24:MI') ORDER BY HORA_INICIO) LOOP
                    IF dia>0 OR f.HORA_INICIO>TO_CHAR(SYSDATE+30/1440,'HH24:MI') THEN
                        SELECT ID_ESPECIALIDAD INTO v_especialidad FROM (
                            SELECT de.ID_ESPECIALIDAD,ROW_NUMBER() OVER(ORDER BY de.ID_ESPECIALIDAD) AS RN
                            FROM DOCTOR_ESPECIALIDAD de JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=de.ID_ESPECIALIDAD
                            WHERE de.ID_DOCTOR=d.ID_DOCTOR AND e.ESTADO='ACTIVO'
                        ) WHERE RN=MOD(dia+TO_NUMBER(SUBSTR(f.HORA_INICIO,1,2)),v_total)+1;
                        SP_REGISTRAR_DISPONIBILIDAD(v_admin,d.ID_DOCTOR,TRUNC(SYSDATE)+dia,f.ID_FRANJA,v_especialidad,v_disponibilidad);
                        v_horarios:=v_horarios+1;
                    END IF;
                END LOOP;
            END LOOP;
        END IF;
    END LOOP;
    FOR dia IN 1..4 LOOP
        FOR t IN (SELECT dd.ID_DOCTOR,dd.ID_ESPECIALIDAD,dd.ID_FRANJA FROM DISPONIBILIDAD_DOCTOR dd
        JOIN FRANJA_HORARIA f ON f.ID_FRANJA=dd.ID_FRANJA
        WHERE dd.FECHA_TURNO=TRUNC(SYSDATE)+dia AND dd.ESTADO='ACTIVO'
        ORDER BY dd.ID_DOCTOR,f.HORA_INICIO FETCH FIRST 1 ROW ONLY) LOOP
            SELECT MIN(ID_PACIENTE) INTO v_paciente FROM PACIENTE WHERE ESTADO='ACTIVO' AND NUMERO_DOCUMENTO=TO_CHAR(97770000+dia) AND TIPO_DOCUMENTO='DNI';
            IF v_paciente IS NULL THEN RAISE_APPLICATION_ERROR(-20979,'Paciente DEMO inactivo'); END IF;
            SP_PRE_RESERVAR_CITA(v_admin,v_paciente,t.ID_DOCTOR,t.ID_ESPECIALIDAD,v_consultorio,t.ID_FRANJA,TRUNC(SYSDATE)+dia,v_reserva);
            SP_CONFIRMAR_CITA_PAGADA(v_admin,v_reserva,'EFECTIVO','DEMO-'||RAWTOHEX(SYS_GUID()),v_cita);
            v_citas:=v_citas+1;
        END LOOP;
    END LOOP;
    COMMIT;
    DBMS_SESSION.CLEAR_IDENTIFIER;
    DBMS_OUTPUT.PUT_LINE('Horarios con especialidad: '||v_horarios||'. Citas futuras: '||v_citas);
    DBMS_OUTPUT.PUT_LINE('Sin atenciones cerradas, devengos precargados ni liquidaciones a doctores.');
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    DBMS_SESSION.CLEAR_IDENTIFIER;
    RAISE;
END;
/

SELECT c.ID_CITA,c.FECHA_CITA,d.NOMBRES||' '||d.APELLIDOS AS DOCTOR,e.NOMBRE AS ESPECIALIDAD,f.HORA_INICIO,c.ESTADO
FROM CITA c JOIN DOCTOR d ON d.ID_DOCTOR=c.ID_DOCTOR JOIN ESPECIALIDAD e ON e.ID_ESPECIALIDAD=c.ID_ESPECIALIDAD
JOIN FRANJA_HORARIA f ON f.ID_FRANJA=c.ID_FRANJA ORDER BY c.FECHA_CITA;
SELECT COUNT(*) AS LIQUIDACIONES_A_DOCTORES FROM LIQUIDACION;
SELECT COUNT(*) AS HORARIOS_SIN_ESPECIALIDAD FROM DISPONIBILIDAD_DOCTOR WHERE ID_ESPECIALIDAD IS NULL;
