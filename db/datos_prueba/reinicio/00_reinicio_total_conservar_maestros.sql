-- REINICIO TOTAL PARA UNA NUEVA DEMOSTRACION
-- Conserva: admin01, roles, especialidades, consultorios, franjas y parametros.
-- Elimina: usuarios no administradores, doctores, pacientes y toda operacion.
-- Ejecutar conectado como KARELY_BD2.

SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_admin NUMBER;
    v_liquidacion VARCHAR2(8);
    v_pago VARCHAR2(8);
BEGIN
    IF USER <> 'KARELY_BD2' THEN
        RAISE_APPLICATION_ERROR(-20980, 'Ejecutar conectado como KARELY_BD2.');
    END IF;

    SELECT ID_USUARIO INTO v_admin
    FROM USUARIO U
    JOIN ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.USERNAME = 'admin01'
      AND U.ESTADO = 'ACTIVO'
      AND R.NOMBRE = 'ADMINISTRADORA';

    SELECT STATUS INTO v_liquidacion
    FROM USER_TRIGGERS WHERE TRIGGER_NAME = 'TR_NO_EDITAR_LIQUIDACION';
    SELECT STATUS INTO v_pago
    FROM USER_TRIGGERS WHERE TRIGGER_NAME = 'TR_NO_EDITAR_PAGO_APROBADO';

    IF v_liquidacion = 'ENABLED' THEN
        EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_LIQUIDACION DISABLE';
    END IF;
    IF v_pago = 'ENABLED' THEN
        EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO DISABLE';
    END IF;

    BEGIN
        DELETE FROM NOTIFICACION_SALIENTE;
        DELETE FROM RECETA_DETALLE;
        DELETE FROM RECETA;
        DELETE FROM RECIBO_HONORARIO;
        DELETE FROM ATENCION_MEDICA;
        DELETE FROM ASISTENCIA;
        DELETE FROM REPROGRAMACION_CITA;
        DELETE FROM CITA;
        DELETE FROM PAGO_CITA;
        DELETE FROM PRE_RESERVA_CITA;
        DELETE FROM LIQUIDACION;
        DELETE FROM DISPONIBILIDAD_DOCTOR;

        DELETE FROM DOCUMENTO_DOCTOR;
        DELETE FROM DOCTOR_ESPECIALIDAD;
        DELETE FROM TOKEN_RECUPERACION;
        DELETE FROM SESION_USUARIO;
        DELETE FROM AUDITORIA;
        DELETE FROM DOCTOR;
        DELETE FROM PACIENTE;
        DELETE FROM USUARIO WHERE ID_USUARIO <> v_admin;

        INSERT INTO AUDITORIA (ID_USUARIO, TABLA_AFECTADA, ACCION, DETALLE, ORIGEN)
        VALUES (
            v_admin,
            'SISTEMA',
            'REINICIO_TOTAL',
            'Se eliminaron datos personales y operaciones; se conservaron maestros y admin01.',
            'SISTEMA');

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            IF v_liquidacion = 'ENABLED' THEN
                EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_LIQUIDACION ENABLE';
            END IF;
            IF v_pago = 'ENABLED' THEN
                EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE';
            END IF;
            RAISE;
    END;

    IF v_liquidacion = 'ENABLED' THEN
        EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_LIQUIDACION ENABLE';
    END IF;
    IF v_pago = 'ENABLED' THEN
        EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE';
    END IF;

    DBMS_OUTPUT.PUT_LINE('Reinicio terminado. Se conserva solo admin01 y los catalogos maestros.');
END;
/

SELECT 'USUARIOS' AS TIPO, COUNT(*) AS TOTAL FROM USUARIO
UNION ALL SELECT 'DOCTORES', COUNT(*) FROM DOCTOR
UNION ALL SELECT 'PACIENTES', COUNT(*) FROM PACIENTE
UNION ALL SELECT 'CITAS', COUNT(*) FROM CITA
UNION ALL SELECT 'ESPECIALIDADES', COUNT(*) FROM ESPECIALIDAD
UNION ALL SELECT 'FRANJAS', COUNT(*) FROM FRANJA_HORARIA;
