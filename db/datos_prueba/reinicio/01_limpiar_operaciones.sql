SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

SELECT 'CITAS' AS TIPO,COUNT(*) AS TOTAL FROM CITA
UNION ALL SELECT 'LIQUIDACIONES',COUNT(*) FROM LIQUIDACION
UNION ALL SELECT 'COBROS',COUNT(*) FROM PAGO_CITA
UNION ALL SELECT 'HORARIOS',COUNT(*) FROM DISPONIBILIDAD_DOCTOR;

DECLARE
    v_liquidacion VARCHAR2(8);
    v_pago VARCHAR2(8);
BEGIN
    IF USER <> 'KARELY_BD2' THEN
        RAISE_APPLICATION_ERROR(-20970,'Ejecutar conectado como KARELY_BD2');
    END IF;
    SELECT STATUS INTO v_liquidacion FROM USER_TRIGGERS WHERE TRIGGER_NAME='TR_NO_EDITAR_LIQUIDACION';
    SELECT STATUS INTO v_pago FROM USER_TRIGGERS WHERE TRIGGER_NAME='TR_NO_EDITAR_PAGO_APROBADO';
    IF v_liquidacion='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_LIQUIDACION DISABLE'; END IF;
    IF v_pago='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO DISABLE'; END IF;
    BEGIN
        DELETE FROM NOTIFICACION_SALIENTE;
        DELETE FROM RECETA_DETALLE;
        DELETE FROM RECETA;
        DELETE FROM RECIBO_HONORARIO;
        DELETE FROM ATENCION_MEDICA;
        DELETE FROM ASISTENCIA;
        DELETE FROM REPROGRAMACION_CITA;
        DELETE FROM CITA;
        DELETE FROM PAGO_CITA;
        DELETE FROM PRE_RESERVA_CITA;
        DELETE FROM LIQUIDACION;
        DELETE FROM DISPONIBILIDAD_DOCTOR;
        INSERT INTO AUDITORIA(TABLA_AFECTADA,ACCION,DETALLE,ORIGEN)
        VALUES('CITA','REINICIO_PRUEBAS','Limpieza manual de operaciones y horarios de prueba; usuarios y maestros conservados','SISTEMA');
        COMMIT;
    EXCEPTION WHEN OTHERS THEN
        ROLLBACK;
        IF v_liquidacion='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_LIQUIDACION ENABLE'; END IF;
        IF v_pago='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE'; END IF;
        RAISE;
    END;
    IF v_liquidacion='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_LIQUIDACION ENABLE'; END IF;
    IF v_pago='ENABLED' THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE'; END IF;
    DBMS_OUTPUT.PUT_LINE('Operaciones y horarios eliminados. Usuarios y maestros conservados.');
END;
/

SELECT TRIGGER_NAME,STATUS FROM USER_TRIGGERS
WHERE TRIGGER_NAME IN ('TR_NO_EDITAR_LIQUIDACION','TR_NO_EDITAR_PAGO_APROBADO');
SELECT COUNT(*) AS USUARIOS_CONSERVADOS FROM USUARIO;
