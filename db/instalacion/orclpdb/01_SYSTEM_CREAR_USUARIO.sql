    SELECT COUNT(*) INTO v_n FROM DBA_TABLESPACES
    WHERE TABLESPACE_NAME IN ('TBS_KARELY_BD2','TMP_KARELY_BD2');
    IF v_n > 0 THEN
        RAISE_APPLICATION_ERROR(-20902,'Todavia existe un tablespace Karely. Revisar antes de continuar.');
    END IF;
END;
