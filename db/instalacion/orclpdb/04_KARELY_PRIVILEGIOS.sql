CREATE OR REPLACE VIEW V_S_ORA_MIS_CITAS AS
SELECT C.ID_CITA,C.FECHA_CITA,F.HORA_INICIO,F.HORA_FIN,C.ESTADO,
 P.NOMBRES||' '||P.APELLIDOS AS PACIENTE,E.NOMBRE AS ESPECIALIDAD,
 CO.NOMBRE AS CONSULTORIO
FROM CITA C JOIN DOCTOR D ON D.ID_DOCTOR=C.ID_DOCTOR
JOIN USUARIO U ON U.ID_USUARIO=D.ID_USUARIO
JOIN ROL R ON R.ID_ROL=U.ID_ROL
JOIN PACIENTE P ON P.ID_PACIENTE=C.ID_PACIENTE
JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=C.ID_ESPECIALIDAD
JOIN CONSULTORIO CO ON CO.ID_CONSULTORIO=C.ID_CONSULTORIO
JOIN FRANJA_HORARIA F ON F.ID_FRANJA=C.ID_FRANJA
WHERE U.USERNAME=LOWER(SYS_CONTEXT('USERENV','SESSION_USER'))
AND U.ESTADO='ACTIVO' AND D.ESTADO='ACTIVO' AND R.NOMBRE='DOCTOR' AND R.ESTADO='ACTIVO';

CREATE OR REPLACE VIEW V_S_ORA_MIS_HORARIOS AS
SELECT H.* FROM V_S_HORARIOS_DOCTOR H JOIN DOCTOR D ON D.ID_DOCTOR=H.ID_DOCTOR
JOIN USUARIO U ON U.ID_USUARIO=D.ID_USUARIO JOIN ROL R ON R.ID_ROL=U.ID_ROL
WHERE U.USERNAME=LOWER(SYS_CONTEXT('USERENV','SESSION_USER'))
AND U.ESTADO='ACTIVO' AND D.ESTADO='ACTIVO' AND R.NOMBRE='DOCTOR' AND R.ESTADO='ACTIVO';

CREATE OR REPLACE VIEW V_S_ORA_MIS_ATENCIONES AS
