-- Privada: no se concede EXECUTE a lectores u operadores.
-- SESSION_USER no depende de CLIENT_IDENTIFIER, CURRENT_SCHEMA ni del parametro enviado por el cliente.
CREATE OR REPLACE FUNCTION FN_ORA_ACTOR(p_roles VARCHAR2)
RETURN NUMBER AUTHID DEFINER IS v_id NUMBER;
BEGIN
 SELECT U.ID_USUARIO INTO v_id FROM USUARIO U JOIN ROL R ON R.ID_ROL=U.ID_ROL
 WHERE U.USERNAME=LOWER(SYS_CONTEXT('USERENV','SESSION_USER'))
 AND U.ESTADO='ACTIVO' AND R.ESTADO='ACTIVO'
 AND INSTR(','||p_roles||',', ','||R.NOMBRE||',')>0;
 RETURN v_id;
EXCEPTION WHEN NO_DATA_FOUND THEN
 RAISE_APPLICATION_ERROR(-20985,'Usuario Oracle sin identidad de aplicacion autorizada para esta operacion.');
END;
/

