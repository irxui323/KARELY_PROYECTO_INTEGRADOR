CREATE OR REPLACE PROCEDURE SP_ORA_REGISTRAR_PACIENTE(
 p_tipo VARCHAR2,p_documento VARCHAR2,p_nombres VARCHAR2,p_apellidos VARCHAR2,
 p_nacimiento DATE,p_telefono VARCHAR2,p_correo VARCHAR2,p_direccion VARCHAR2,
 p_paciente OUT NUMBER
) AUTHID DEFINER IS v_actor NUMBER;
BEGIN
 v_actor:=FN_ORA_ACTOR('RECEPCIONISTA,ADMINISTRADORA');
 IF TRIM(p_nombres) IS NULL OR TRIM(p_apellidos) IS NULL OR TRIM(p_documento) IS NULL
 OR TRIM(p_tipo) IS NULL THEN
  RAISE_APPLICATION_ERROR(-20986,'Documento, tipo, nombres y apellidos son obligatorios.');
 END IF;
 IF p_nacimiento>TRUNC(SYSDATE) THEN
  RAISE_APPLICATION_ERROR(-20986,'La fecha de nacimiento no puede ser futura.');
 END IF;
 DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_actor));
 INSERT INTO PACIENTE(TIPO_DOCUMENTO,NUMERO_DOCUMENTO,NOMBRES,APELLIDOS,
 FECHA_NACIMIENTO,TELEFONO,CORREO,DIRECCION,ESTADO)
 VALUES(TRIM(p_tipo),TRIM(p_documento),TRIM(p_nombres),TRIM(p_apellidos),
 TRUNC(p_nacimiento),p_telefono,p_correo,p_direccion,'ACTIVO')
 RETURNING ID_PACIENTE INTO p_paciente;
 DBMS_SESSION.CLEAR_IDENTIFIER;
EXCEPTION WHEN OTHERS THEN DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/
