 DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_actor));
 SP_PAGAR_DOCTOR(v_actor,p_doctor,p_inicio,p_fin,p_monto,p_metodo,
 'OP-'||v_referencia,'BOL-'||v_referencia,p_liquidacion);
