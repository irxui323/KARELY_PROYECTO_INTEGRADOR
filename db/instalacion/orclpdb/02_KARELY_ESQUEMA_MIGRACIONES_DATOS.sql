-- 19.1. PROCEDIMIENTO: REGISTRAR DIAGNOSTICO
-----------------------------------

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_DIAGNOSTICO (
    P_ID_USUARIO    IN USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA       IN CITA.ID_CITA%TYPE,
    P_DIAGNOSTICO   IN CLOB,
    P_OBSERVACIONES IN CLOB DEFAULT NULL
)
IS
    V_ID_DOCTOR CITA.ID_DOCTOR%TYPE;
    V_ESTADO_CITA CITA.ESTADO%TYPE;
    V_ID_ATENCION ATENCION_MEDICA.ID_ATENCION%TYPE;
    V_ESTADO_ATENCION ATENCION_MEDICA.ESTADO%TYPE;
    V_CANTIDAD NUMBER;
BEGIN
    SAVEPOINT SV_DIAGNOSTICO;

    IF NVL(FN_ROL_USUARIO(P_ID_USUARIO),'SIN_ROL') <> 'DOCTOR' THEN
        RAISE_APPLICATION_ERROR(-20401, 'Solo el doctor puede registrar el diagnostico.');
    END IF;

    IF P_DIAGNOSTICO IS NULL
       OR NVL(DBMS_LOB.GETLENGTH(P_DIAGNOSTICO),0) = 0
       OR TRIM(DBMS_LOB.SUBSTR(P_DIAGNOSTICO,4000,1)) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20402, 'El diagnostico no puede estar vacio.');
    END IF;

    SELECT ID_DOCTOR, ESTADO INTO V_ID_DOCTOR,V_ESTADO_CITA
      FROM CITA WHERE ID_CITA = P_ID_CITA FOR UPDATE;

    IF V_ESTADO_CITA <> 'EN_ATENCION' THEN
        RAISE_APPLICATION_ERROR(-20403, 'La cita no esta EN_ATENCION.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD FROM DOCTOR
     WHERE ID_DOCTOR = V_ID_DOCTOR AND ID_USUARIO = P_ID_USUARIO
       AND ESTADO = 'ACTIVO';
    IF V_CANTIDAD <> 1 THEN
        RAISE_APPLICATION_ERROR(-20404, 'El usuario no es el doctor asignado.');
    END IF;

    SELECT ID_ATENCION, ESTADO INTO V_ID_ATENCION,V_ESTADO_ATENCION
      FROM ATENCION_MEDICA
     WHERE ID_CITA = P_ID_CITA AND ID_DOCTOR = V_ID_DOCTOR
     FOR UPDATE;

    IF V_ESTADO_ATENCION <> 'ABIERTA' THEN
        RAISE_APPLICATION_ERROR(-20405, 'La atencion ya fue cerrada.');
    END IF;

    UPDATE ATENCION_MEDICA
       SET DIAGNOSTICO = P_DIAGNOSTICO,
           OBSERVACIONES = P_OBSERVACIONES
     WHERE ID_ATENCION = V_ID_ATENCION;

    INSERT INTO AUDITORIA (ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,ORIGEN)
    VALUES (P_ID_USUARIO,'ATENCION_MEDICA',V_ID_ATENCION,'DIAGNOSTICO',
            'Registro o actualizacion del diagnostico (contenido reservado)','USUARIO');

    DBMS_OUTPUT.PUT_LINE('Diagnostico registrado en atencion ' || V_ID_ATENCION);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_DIAGNOSTICO;
        RAISE_APPLICATION_ERROR(-20406,'Cita o atencion medica no encontrada.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_DIAGNOSTICO;
        RAISE;
END SP_REGISTRAR_DIAGNOSTICO;
