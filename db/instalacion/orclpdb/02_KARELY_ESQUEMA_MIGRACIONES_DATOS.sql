-- 22.3. REGISTRAR RESULTADO DEL ENVIO
-----------------------------------
-- P_EXITO = 'S' SOLO SI el proveedor externo confirmó
-- el envío; no confundir con lectura o entrega final.
CREATE OR REPLACE PROCEDURE SP_REGISTRAR_RESULTADO_ENVIO (
    P_ID_USUARIO       IN USUARIO.ID_USUARIO%TYPE,
    P_ID_NOTIFICACION  IN NOTIFICACION_SALIENTE.ID_NOTIFICACION%TYPE,
    P_INTENTO          IN NOTIFICACION_SALIENTE.INTENTOS%TYPE,
    P_EXITO            IN CHAR,
    P_ERROR            IN VARCHAR2 DEFAULT NULL
)
IS
    V_ROL ROL.NOMBRE%TYPE;
    V_ESTADO NOTIFICACION_SALIENTE.ESTADO%TYPE;
    V_INTENTO_ACTUAL NOTIFICACION_SALIENTE.INTENTOS%TYPE;
    V_ERROR NOTIFICACION_SALIENTE.ULTIMO_ERROR%TYPE;
BEGIN
    SAVEPOINT SV_RESULTADO_ENVIO;

    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);
    IF V_ROL <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20710,
            'Solo administracion puede registrar resultados del correo.');
    END IF;

    IF P_EXITO IS NULL OR P_EXITO NOT IN ('S','N') THEN
        RAISE_APPLICATION_ERROR(-20711, 'P_EXITO debe ser S o N.');
    END IF;

    SELECT ESTADO, INTENTOS
      INTO V_ESTADO, V_INTENTO_ACTUAL
      FROM NOTIFICACION_SALIENTE
     WHERE ID_NOTIFICACION = P_ID_NOTIFICACION
     FOR UPDATE;

    IF V_ESTADO <> 'PENDIENTE' OR
       P_INTENTO IS NULL OR P_INTENTO <> V_INTENTO_ACTUAL OR
       V_INTENTO_ACTUAL = 0 THEN
        RAISE_APPLICATION_ERROR(-20712,
            'El intento ya cambio o fue registrado anteriormente.');
    END IF;

    IF P_EXITO = 'S' THEN
        UPDATE NOTIFICACION_SALIENTE
           SET ESTADO = 'ENVIADA',
               FECHA_ENVIO = CAST(SYSTIMESTAMP AS TIMESTAMP),
               ULTIMO_ERROR = NULL
         WHERE ID_NOTIFICACION = P_ID_NOTIFICACION;
    ELSE
        V_ERROR := SUBSTR(NVL(TRIM(P_ERROR),
                             'El servicio externo no confirmo el envio.'),1,500);
        UPDATE NOTIFICACION_SALIENTE
           SET ESTADO = 'FALLIDA',
               ULTIMO_ERROR = V_ERROR,
               FECHA_PROXIMO_INTENTO = CAST(SYSTIMESTAMP AS TIMESTAMP)
                   + NUMTODSINTERVAL(LEAST(60,POWER(2,P_INTENTO)),'MINUTE')
         WHERE ID_NOTIFICACION = P_ID_NOTIFICACION;
        -- Si INTENTOS = 5 ya no vuelve a seleccionarse.
    END IF;

    INSERT INTO AUDITORIA (
        ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO,
        ACCION, DETALLE, ORIGEN
    ) VALUES (
        P_ID_USUARIO, 'NOTIFICACION_SALIENTE', P_ID_NOTIFICACION,
        'RESULTADO_ENVIO',
        CASE WHEN P_EXITO = 'S' THEN 'Envio externo confirmado'
             ELSE 'Fallo al enviar; intento ' || P_INTENTO END,
        'USUARIO'
    );
    DBMS_OUTPUT.PUT_LINE('Resultado de notificacion registrado.');
    DBMS_OUTPUT.PUT_LINE('Ejecute COMMIT para guardar el resultado.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_RESULTADO_ENVIO;
        RAISE_APPLICATION_ERROR(-20713,'Notificacion no encontrada.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_RESULTADO_ENVIO;
        RAISE;
END SP_REGISTRAR_RESULTADO_ENVIO;
/
SHOW ERRORS PROCEDURE SP_REGISTRAR_RESULTADO_ENVIO;

