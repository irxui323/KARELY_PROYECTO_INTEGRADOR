-- 18.2. PROCEDIMIENTO: REGISTRAR ASISTENCIA
-----------------------------------

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_ASISTENCIA (
    P_ID_USUARIO   IN  USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA      IN  CITA.ID_CITA%TYPE,
    P_ID_ASISTENCIA OUT ASISTENCIA.ID_ASISTENCIA%TYPE
)
IS
    V_ROL          ROL.NOMBRE%TYPE;
    V_PACIENTE     CITA.ID_PACIENTE%TYPE;
    V_FECHA        CITA.FECHA_CITA%TYPE;
    V_FRANJA       CITA.ID_FRANJA%TYPE;
    V_ESTADO       CITA.ESTADO%TYPE;
    V_ID_PAGO      CITA.ID_PAGO%TYPE;
    V_INICIO       TIMESTAMP;
    V_AHORA        TIMESTAMP;
    V_CANTIDAD     NUMBER;
BEGIN
    P_ID_ASISTENCIA := NULL;
    SAVEPOINT SV_REGISTRAR_ASISTENCIA;

    -- La funcion del paso 17 comprueba identidad, usuario y rol activo.
    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);

    IF V_ROL <> 'RECEPCIONISTA' THEN
        RAISE_APPLICATION_ERROR(-20301,
            'Solo recepcion puede registrar la asistencia del paciente.');
    END IF;

    -- El bloqueo evita registrar dos veces la misma asistencia.
    SELECT ID_PACIENTE, FECHA_CITA, ID_FRANJA, ESTADO, ID_PAGO
    INTO V_PACIENTE, V_FECHA, V_FRANJA, V_ESTADO, V_ID_PAGO
    FROM CITA
    WHERE ID_CITA = P_ID_CITA
    FOR UPDATE;

    IF V_ESTADO NOT IN ('PROGRAMADA', 'REPROGRAMADA') THEN
        RAISE_APPLICATION_ERROR(-20302,
            'La cita no esta programada ni reprogramada.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM PACIENTE
    WHERE ID_PACIENTE = V_PACIENTE
      AND ESTADO = 'ACTIVO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20303,
            'No existe un paciente activo asociado a la cita.');
    END IF;

    -- RN09: se verifica que el pago asociado siga aprobado.
    SELECT COUNT(*) INTO V_CANTIDAD
    FROM PAGO_CITA
    WHERE ID_PAGO = V_ID_PAGO
      AND ESTADO = 'APROBADO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20304,
            'La cita no tiene un pago aprobado.');
    END IF;

    -- RES26: asistencia durante los 30 minutos previos al inicio.
    V_INICIO := FN_INICIO_TURNO(V_FECHA, V_FRANJA);
    V_AHORA := CAST(SYSTIMESTAMP AS TIMESTAMP);

    IF V_AHORA < V_INICIO - NUMTODSINTERVAL(30, 'MINUTE')
       OR V_AHORA > V_INICIO THEN
        RAISE_APPLICATION_ERROR(-20305,
            'La asistencia solo se valida en los 30 minutos previos al turno.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM ASISTENCIA
    WHERE ID_CITA = P_ID_CITA;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20306,
            'La asistencia de esta cita ya fue registrada.');
    END IF;

    INSERT INTO ASISTENCIA (ID_CITA, FECHA_REGISTRO, ESTADO)
    VALUES (P_ID_CITA, V_AHORA, 'PRESENTE')
    RETURNING ID_ASISTENCIA INTO P_ID_ASISTENCIA;

    -- RF67: el estado EN_ATENCION habilita la cola del medico.
    -- El registro clinico se abre con SP_INICIAR_ATENCION.
    UPDATE CITA
    SET ESTADO = 'EN_ATENCION'
    WHERE ID_CITA = P_ID_CITA;

    INSERT INTO AUDITORIA (
        ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO,
        ACCION, DETALLE, ESTADO_ANTERIOR, ESTADO_NUEVO, ORIGEN
    ) VALUES (
        P_ID_USUARIO, 'CITA', P_ID_CITA,
        'ASISTENCIA', 'Llegada verificada por recepcion',
        V_ESTADO, 'EN_ATENCION', 'USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Asistencia registrada: ' || P_ID_ASISTENCIA);
    DBMS_OUTPUT.PUT_LINE('Cita: ' || P_ID_CITA || ' - EN_ATENCION');
    DBMS_OUTPUT.PUT_LINE('Realice COMMIT si desea conservar los cambios.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_REGISTRAR_ASISTENCIA;
        RAISE_APPLICATION_ERROR(-20307,
            'La cita indicada no existe.');
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SV_REGISTRAR_ASISTENCIA;
        RAISE_APPLICATION_ERROR(-20308,
            'La asistencia de esta cita ya esta registrada.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_REGISTRAR_ASISTENCIA;
        RAISE;
END SP_REGISTRAR_ASISTENCIA;
/

