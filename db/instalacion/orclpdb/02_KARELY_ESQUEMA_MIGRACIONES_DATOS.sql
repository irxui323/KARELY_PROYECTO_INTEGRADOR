-- 21.2. CAMBIAR ROL DE UN USUARIO
-----------------------------------
CREATE OR REPLACE PROCEDURE SP_CAMBIAR_ROL_USUARIO (
    P_ID_ADMIN   IN USUARIO.ID_USUARIO%TYPE,
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_ROL     IN ROL.ID_ROL%TYPE
)
IS
    V_ID_ADMIN_ROL ROL.ID_ROL%TYPE;
    V_ROL_ANTERIOR USUARIO.ID_ROL%TYPE;
    V_CANTIDAD NUMBER;
BEGIN
    SAVEPOINT SV_CAMBIAR_ROL;

    IF FN_ROL_USUARIO(P_ID_ADMIN) <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20606,'Solo administracion puede cambiar roles.');
    END IF;

    IF P_ID_USUARIO = P_ID_ADMIN THEN
        RAISE_APPLICATION_ERROR(-20607,'No puede cambiar su propio rol.');
    END IF;

    -- El orden de bloqueo protege el ultimo administrador.
    SELECT ID_ROL INTO V_ID_ADMIN_ROL
    FROM ROL WHERE NOMBRE = 'ADMINISTRADORA' FOR UPDATE;

    SELECT ID_ROL INTO V_ROL_ANTERIOR
    FROM USUARIO WHERE ID_USUARIO = P_ID_USUARIO FOR UPDATE;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM ROL WHERE ID_ROL = P_ID_ROL AND ESTADO = 'ACTIVO';
    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20608,'El nuevo rol no esta activo.');
    END IF;

    IF V_ROL_ANTERIOR = P_ID_ROL THEN
        RAISE_APPLICATION_ERROR(-20609,'El usuario ya tiene ese rol.');
    END IF;

    IF V_ROL_ANTERIOR = V_ID_ADMIN_ROL THEN
        SELECT COUNT(*) INTO V_CANTIDAD
        FROM USUARIO
        WHERE ID_ROL = V_ID_ADMIN_ROL AND ESTADO = 'ACTIVO';
        IF V_CANTIDAD <= 1 THEN
            RAISE_APPLICATION_ERROR(-20610,
                'No se puede quitar el ultimo administrador activo.');
        END IF;
    END IF;

    UPDATE USUARIO SET ID_ROL = P_ID_ROL
    WHERE ID_USUARIO = P_ID_USUARIO;

    -- Revocacion de sesiones vigentes al cambiar permisos.
    UPDATE SESION_USUARIO
    SET ESTADO = 'CERRADA', FECHA_FIN = CAST(SYSTIMESTAMP AS TIMESTAMP)
    WHERE ID_USUARIO = P_ID_USUARIO AND ESTADO = 'ACTIVA';

    INSERT INTO AUDITORIA (
        ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,
        ESTADO_ANTERIOR,ESTADO_NUEVO,ORIGEN
    ) VALUES (
        P_ID_ADMIN,'USUARIO',P_ID_USUARIO,'CAMBIO_ROL',
        'Cambio administrativo de rol',
        TO_CHAR(V_ROL_ANTERIOR),TO_CHAR(P_ID_ROL),'USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Rol actualizado y sesiones activas cerradas.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_CAMBIAR_ROL;
        RAISE_APPLICATION_ERROR(-20611,'Usuario o rol administrador no encontrado.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_CAMBIAR_ROL;
        RAISE;
END SP_CAMBIAR_ROL_USUARIO;
/
SHOW ERRORS PROCEDURE SP_CAMBIAR_ROL_USUARIO;

