 id_cita NUMBER NOT NULL UNIQUE REFERENCES CITA(id_cita),
 id_doctor NUMBER NOT NULL REFERENCES DOCTOR(id_doctor),
 diagnostico CLOB,
 observaciones CLOB,
 fecha_inicio TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 fecha_cierre TIMESTAMP,
 estado VARCHAR2(12) DEFAULT 'ABIERTA' NOT NULL CHECK(estado IN ('ABIERTA','CERRADA'))
)
PARTITION BY HASH (id_atencion)
PARTITIONS 4;
CREATE TABLE RECETA (
 id_receta NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
