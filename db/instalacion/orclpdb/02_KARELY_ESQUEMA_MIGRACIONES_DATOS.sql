-- 22.1. ENCOLAR AVISO DE PAGO O RECIBO DE CITA
-----------------------------------
-- El pago al doctor ya encola un aviso PAGO_DOCTOR en el paso 20.
-- Este procedimiento encola UN evento por cita y tipo.
CREATE OR REPLACE PROCEDURE SP_ENCOLAR_NOTIFICACION_CITA (
    P_ID_USUARIO       IN  USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA          IN  CITA.ID_CITA%TYPE,
    P_TIPO             IN  NOTIFICACION_SALIENTE.TIPO%TYPE,
    P_ID_NOTIFICACION  OUT NOTIFICACION_SALIENTE.ID_NOTIFICACION%TYPE
)
IS
    V_ROL ROL.NOMBRE%TYPE;
    V_TIPO NOTIFICACION_SALIENTE.TIPO%TYPE := UPPER(TRIM(P_TIPO));
    V_ID_PACIENTE CITA.ID_PACIENTE%TYPE;
    V_ID_PAGO CITA.ID_PAGO%TYPE;
    V_DESTINATARIO NOTIFICACION_SALIENTE.DESTINATARIO%TYPE;
    V_CODIGO NOTIFICACION_SALIENTE.CODIGO_EVENTO%TYPE;
    V_CANTIDAD NUMBER;
BEGIN
    P_ID_NOTIFICACION := NULL;
    SAVEPOINT SV_ENCOLAR_NOTIFICACION;

    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);
    IF V_ROL NOT IN ('ADMINISTRADORA','RECEPCIONISTA') THEN
        RAISE_APPLICATION_ERROR(-20701,
            'Solo administracion o recepcion pueden encolar avisos.');
    END IF;

    IF V_TIPO IS NULL OR
       V_TIPO NOT IN ('PAGO_CITA','RECIBO_HONORARIO') THEN
        RAISE_APPLICATION_ERROR(-20702,
            'Tipo de notificacion de cita no permitido.');
    END IF;

    -- Bloquear la cita serializa solicitudes simultaneas
    -- de encolado para la misma cita.
    SELECT ID_PACIENTE, ID_PAGO
      INTO V_ID_PACIENTE, V_ID_PAGO
      FROM CITA
     WHERE ID_CITA = P_ID_CITA
     FOR UPDATE;

    SELECT CORREO INTO V_DESTINATARIO
      FROM PACIENTE
     WHERE ID_PACIENTE = V_ID_PACIENTE;

    IF TRIM(V_DESTINATARIO) IS NULL OR
       INSTR(V_DESTINATARIO,'@') <= 1 THEN
        RAISE_APPLICATION_ERROR(-20703,
            'El paciente necesita correo valido para el envio.');
    END IF;

    IF V_TIPO = 'PAGO_CITA' THEN
        SELECT COUNT(*) INTO V_CANTIDAD
          FROM PAGO_CITA PC
         WHERE PC.ID_PAGO = V_ID_PAGO
           AND PC.ESTADO = 'APROBADO';
        IF V_CANTIDAD = 0 THEN
            RAISE_APPLICATION_ERROR(-20704,
                'La cita no tiene un pago aprobado.');
        END IF;
    ELSE
        SELECT COUNT(*) INTO V_CANTIDAD
          FROM RECIBO_HONORARIO
         WHERE ID_CITA = P_ID_CITA
           AND FECHA_ENTREGA IS NOT NULL;
        IF V_CANTIDAD = 0 THEN
            RAISE_APPLICATION_ERROR(-20705,
                'El recibo de honorarios debe estar emitido y entregado.');
        END IF;
    END IF;

    V_CODIGO := V_TIPO || '-' || TO_CHAR(P_ID_CITA);

    SELECT COUNT(*) INTO V_CANTIDAD
      FROM NOTIFICACION_SALIENTE
     WHERE CODIGO_EVENTO = V_CODIGO;
    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20706,
            'Ya existe una notificacion para esta cita y tipo.');
    END IF;

    INSERT INTO NOTIFICACION_SALIENTE (
        TIPO, CANAL, DESTINATARIO, ID_CITA,
        ID_USUARIO_CREACION, CODIGO_EVENTO, ESTADO
    ) VALUES (
        V_TIPO, 'EMAIL', LOWER(TRIM(V_DESTINATARIO)), P_ID_CITA,
        P_ID_USUARIO, V_CODIGO, 'PENDIENTE'
    ) RETURNING ID_NOTIFICACION INTO P_ID_NOTIFICACION;

    INSERT INTO AUDITORIA (
        ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO,
        ACCION, DETALLE, ORIGEN
    ) VALUES (
        P_ID_USUARIO, 'NOTIFICACION_SALIENTE', P_ID_NOTIFICACION,
        'ENCOLAR', 'Notificacion de ' || V_TIPO, 'USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Notificacion encolada: ' || P_ID_NOTIFICACION);
    DBMS_OUTPUT.PUT_LINE('Ejecute COMMIT para guardar los cambios.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_ENCOLAR_NOTIFICACION;
        RAISE_APPLICATION_ERROR(-20707,'Cita o paciente no encontrado.');
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SV_ENCOLAR_NOTIFICACION;
        RAISE_APPLICATION_ERROR(-20708,'Evento de notificacion duplicado.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_ENCOLAR_NOTIFICACION;
        RAISE;
END SP_ENCOLAR_NOTIFICACION_CITA;
