CREATE OR REPLACE PROCEDURE SP_PRE_RESERVAR_CITA (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_PACIENTE IN PACIENTE.ID_PACIENTE%TYPE,
    P_ID_DOCTOR IN DOCTOR.ID_DOCTOR%TYPE,
    P_ID_ESPECIALIDAD IN ESPECIALIDAD.ID_ESPECIALIDAD%TYPE,
    P_ID_CONSULTORIO IN CONSULTORIO.ID_CONSULTORIO%TYPE,
    P_ID_FRANJA IN FRANJA_HORARIA.ID_FRANJA%TYPE,
    P_FECHA IN DATE,
    P_ID_PRE_RESERVA OUT PRE_RESERVA_CITA.ID_PRE_RESERVA%TYPE
)
IS
    V_CANTIDAD NUMBER;
    V_MINUTOS NUMBER;
    V_PRECIO ESPECIALIDAD.PRECIO_CONSULTA%TYPE;
    V_DOCUMENTACION DOCTOR.ESTADO_DOCUMENTACION%TYPE;
    V_ESTADO_CONSULTORIO CONSULTORIO.ESTADO%TYPE;
    V_HORA_INICIO FRANJA_HORARIA.HORA_INICIO%TYPE;
    V_HORA_FIN FRANJA_HORARIA.HORA_FIN%TYPE;
    V_AHORA TIMESTAMP;
BEGIN
    P_ID_PRE_RESERVA := NULL;
    SAVEPOINT SV_PRE_RESERVAR_CITA;

    IF P_ID_USUARIO IS NULL OR
       SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') IS NULL OR
       SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_USUARIO) THEN
        RAISE_APPLICATION_ERROR(-20101, 'Identidad de sesion no coincide.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM USUARIO U
    JOIN ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.ID_USUARIO = P_ID_USUARIO
      AND U.ESTADO = 'ACTIVO'
      AND R.ESTADO = 'ACTIVO'
      AND R.NOMBRE IN ('RECEPCIONISTA','ADMINISTRADORA');

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20102, 'Solo recepcionista o administradora puede pre-reservar.');
    END IF;

    IF P_FECHA IS NULL OR P_FECHA <> TRUNC(P_FECHA) THEN
        RAISE_APPLICATION_ERROR(-20103, 'La fecha debe indicarse sin hora.');
    END IF;

    V_AHORA := CAST(SYSTIMESTAMP AS TIMESTAMP);

    IF FN_INICIO_TURNO(P_FECHA,P_ID_FRANJA) <= V_AHORA THEN
        RAISE_APPLICATION_ERROR(-20104, 'El turno ya inicio o es anterior a hoy.');
    END IF;

    
    SELECT ESTADO_DOCUMENTACION
    INTO V_DOCUMENTACION
    FROM DOCTOR
    WHERE ID_DOCTOR = P_ID_DOCTOR
      AND ESTADO = 'ACTIVO'
    FOR UPDATE;

    IF V_DOCUMENTACION <> 'COMPLETO' THEN
        RAISE_APPLICATION_ERROR(-20105, 'El doctor no tiene documentacion completa.');
    END IF;

    SELECT ESTADO
    INTO V_ESTADO_CONSULTORIO
    FROM CONSULTORIO
    WHERE ID_CONSULTORIO = P_ID_CONSULTORIO
    FOR UPDATE;

    IF V_ESTADO_CONSULTORIO <> 'ACTIVO' THEN
        RAISE_APPLICATION_ERROR(-20106, 'El consultorio no esta activo.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM PACIENTE
    WHERE ID_PACIENTE = P_ID_PACIENTE
      AND ESTADO = 'ACTIVO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20107, 'Paciente inexistente o inactivo.');
    END IF;

    SELECT E.PRECIO_CONSULTA
    INTO V_PRECIO
    FROM ESPECIALIDAD E
    JOIN DOCTOR_ESPECIALIDAD D
      ON D.ID_ESPECIALIDAD = E.ID_ESPECIALIDAD
    WHERE E.ID_ESPECIALIDAD = P_ID_ESPECIALIDAD
      AND D.ID_DOCTOR = P_ID_DOCTOR
      AND E.ESTADO = 'ACTIVO';

    IF V_PRECIO <= 0 THEN
        RAISE_APPLICATION_ERROR(-20108, 'El precio de consulta debe ser positivo.');
    END IF;

    SELECT HORA_INICIO,HORA_FIN
    INTO V_HORA_INICIO,V_HORA_FIN
    FROM FRANJA_HORARIA
    WHERE ID_FRANJA = P_ID_FRANJA
      AND ESTADO = 'ACTIVO';

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM DISPONIBILIDAD_DOCTOR
    WHERE ID_DOCTOR = P_ID_DOCTOR
      AND ID_FRANJA = P_ID_FRANJA
      AND FECHA_TURNO = P_FECHA
      AND ID_ESPECIALIDAD = P_ID_ESPECIALIDAD
      AND ESTADO = 'ACTIVO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20109, 'El doctor no tiene disponibilidad para esa fecha y turno.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM CITA C
    JOIN FRANJA_HORARIA F ON F.ID_FRANJA = C.ID_FRANJA
    WHERE C.FECHA_CITA = P_FECHA
      AND C.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
      AND (C.ID_DOCTOR = P_ID_DOCTOR OR C.ID_CONSULTORIO = P_ID_CONSULTORIO)
      AND F.HORA_INICIO < V_HORA_FIN
      AND V_HORA_INICIO < F.HORA_FIN;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20110, 'Existe una cita activa que se cruza con el doctor o consultorio.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM PRE_RESERVA_CITA P
    JOIN FRANJA_HORARIA F ON F.ID_FRANJA = P.ID_FRANJA
    WHERE P.FECHA_CITA = P_FECHA
      AND P.ESTADO = 'BLOQUEADA'
      AND P.FECHA_EXPIRACION > CAST(SYSTIMESTAMP AS TIMESTAMP)
      AND (P.ID_DOCTOR = P_ID_DOCTOR OR P.ID_CONSULTORIO = P_ID_CONSULTORIO)
      AND F.HORA_INICIO < V_HORA_FIN
      AND V_HORA_INICIO < F.HORA_FIN;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20111, 'El turno esta bloqueado temporalmente.');
    END IF;

    SELECT TO_NUMBER(VALOR)
    INTO V_MINUTOS
    FROM PARAMETRO_SISTEMA
    WHERE NOMBRE = 'BLOQUEO_MINUTOS'
      AND ESTADO = 'ACTIVO';

    IF V_MINUTOS IS NULL
       OR V_MINUTOS < 1
       OR V_MINUTOS > 10
       OR V_MINUTOS <> TRUNC(V_MINUTOS) THEN
        RAISE_APPLICATION_ERROR(-20112, 'BLOQUEO_MINUTOS debe ser entero de 1 a 10.');
    END IF;

    V_AHORA := CAST(SYSTIMESTAMP AS TIMESTAMP);

    INSERT INTO PRE_RESERVA_CITA (
        ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,
        ID_FRANJA,FECHA_CITA,MONTO,FECHA_BLOQUEO,FECHA_EXPIRACION
    ) VALUES (
        P_ID_PACIENTE,P_ID_DOCTOR,P_ID_ESPECIALIDAD,P_ID_CONSULTORIO,
        P_ID_FRANJA,P_FECHA,V_PRECIO,V_AHORA,
        V_AHORA + NUMTODSINTERVAL(V_MINUTOS,'MINUTE')
    ) RETURNING ID_PRE_RESERVA INTO P_ID_PRE_RESERVA;

    DBMS_OUTPUT.PUT_LINE('Pre-reserva creada: ' || P_ID_PRE_RESERVA);
    DBMS_OUTPUT.PUT_LINE('Confirme la transaccion para activar el bloqueo.');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO SV_PRE_RESERVAR_CITA;
        RAISE;
END SP_PRE_RESERVAR_CITA;
