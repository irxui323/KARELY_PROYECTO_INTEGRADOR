CREATE TABLE PRE_RESERVA_CITA (
 id_pre_reserva NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_paciente NUMBER NOT NULL REFERENCES PACIENTE(id_paciente),
 id_doctor NUMBER NOT NULL REFERENCES DOCTOR(id_doctor),
 id_especialidad NUMBER NOT NULL REFERENCES ESPECIALIDAD(id_especialidad),
 id_consultorio NUMBER NOT NULL REFERENCES CONSULTORIO(id_consultorio),
 id_franja NUMBER NOT NULL REFERENCES FRANJA_HORARIA(id_franja),
 fecha_cita DATE NOT NULL CHECK(fecha_cita = TRUNC(fecha_cita)),
 monto NUMBER(12,2) NOT NULL CHECK(monto >= 0),
 fecha_bloqueo TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 fecha_expiracion TIMESTAMP NOT NULL,
 estado VARCHAR2(12) DEFAULT 'BLOQUEADA' NOT NULL CHECK(estado IN ('BLOQUEADA','EXPIRADA','CONFIRMADA')),
 CONSTRAINT ck_pre_reserva_vence CHECK(fecha_expiracion > fecha_bloqueo)
)
PARTITION BY HASH (id_pre_reserva)
PARTITIONS 4;
CREATE TABLE PAGO_CITA (
 id_pago NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_pre_reserva NUMBER NOT NULL REFERENCES PRE_RESERVA_CITA(id_pre_reserva),
 id_paciente NUMBER NOT NULL REFERENCES PACIENTE(id_paciente),
 monto NUMBER(12,2) NOT NULL CHECK(monto > 0),
 metodo_pago VARCHAR2(30) NOT NULL,
 referencia_pago VARCHAR2(120) NOT NULL,
 fecha_pago TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 estado VARCHAR2(12) DEFAULT 'APROBADO' NOT NULL CHECK(estado IN ('APROBADO','RECHAZADO')),
 CONSTRAINT uq_referencia_pago UNIQUE(metodo_pago,referencia_pago)
)
PARTITION BY HASH (id_pago)
PARTITIONS 4;
CREATE TABLE CITA (
 id_cita NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_pre_reserva NUMBER NOT NULL UNIQUE REFERENCES PRE_RESERVA_CITA(id_pre_reserva),
 id_paciente NUMBER NOT NULL REFERENCES PACIENTE(id_paciente),
 id_doctor NUMBER NOT NULL REFERENCES DOCTOR(id_doctor),
 id_especialidad NUMBER NOT NULL REFERENCES ESPECIALIDAD(id_especialidad),
 id_consultorio NUMBER NOT NULL REFERENCES CONSULTORIO(id_consultorio),
 id_franja NUMBER NOT NULL REFERENCES FRANJA_HORARIA(id_franja),
 id_pago NUMBER NOT NULL UNIQUE REFERENCES PAGO_CITA(id_pago),
 fecha_cita DATE NOT NULL CHECK(fecha_cita = TRUNC(fecha_cita)),
 monto_total NUMBER(12,2) NOT NULL CHECK(monto_total >= 0),
 -- Importes monetarios congelados cuando termina la atencion; NO porcentajes.
 monto_doctor_devengado NUMBER(12,2),
 monto_gestora_devengado NUMBER(12,2),
 CONSTRAINT ck_cita_devengo CHECK(
  (monto_doctor_devengado IS NULL AND monto_gestora_devengado IS NULL) OR
  (monto_doctor_devengado >= 0 AND monto_gestora_devengado >= 0 AND
   monto_doctor_devengado + monto_gestora_devengado = monto_total)),
 estado VARCHAR2(20) DEFAULT 'PROGRAMADA'  NOT NULL
 CHECK(estado IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION','ATENDIDA','PERDIDA','CANCELADA')),
 reprogramaciones NUMBER(1) DEFAULT 0 NOT NULL CHECK(reprogramaciones IN (0,1))
)
PARTITION BY HASH (id_cita)
PARTITIONS 4;
-- COMPROBANTE_CITA se excluye: PDF emitido por la aplicacion, sin tabla propia.
CREATE TABLE REPROGRAMACION_CITA (
 id_reprogramacion NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_cita NUMBER NOT NULL UNIQUE REFERENCES CITA(id_cita),
 fecha_original DATE NOT NULL,
 id_franja_original NUMBER NOT NULL REFERENCES FRANJA_HORARIA(id_franja),
 id_consultorio_original NUMBER NOT NULL REFERENCES CONSULTORIO(id_consultorio),
 fecha_nueva DATE NOT NULL,
 id_franja_nueva NUMBER NOT NULL REFERENCES FRANJA_HORARIA(id_franja),
 id_consultorio_nuevo NUMBER NOT NULL REFERENCES CONSULTORIO(id_consultorio),
 motivo VARCHAR2(500) NOT NULL,
 aceptacion_paciente CHAR(1) NOT NULL
   CHECK(aceptacion_paciente='S'),
 fecha_aceptacion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 id_usuario_aceptacion NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
 fecha_registro TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
PARTITION BY HASH (id_reprogramacion)
PARTITIONS 4;
CREATE TABLE ASISTENCIA (
 id_asistencia NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_cita NUMBER NOT NULL UNIQUE REFERENCES CITA(id_cita),
 fecha_registro TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
