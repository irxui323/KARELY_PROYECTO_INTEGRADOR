 fecha_emision TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 indicaciones VARCHAR2(2000) NOT NULL
)
PARTITION BY HASH (id_receta)
PARTITIONS 4;
CREATE TABLE RECETA_DETALLE (
 id_detalle NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_receta NUMBER NOT NULL REFERENCES RECETA(id_receta),
 medicamento VARCHAR2(200) NOT NULL,
 dosis VARCHAR2(100) NOT NULL,
 frecuencia VARCHAR2(100) NOT NULL,
 duracion VARCHAR2(100) NOT NULL,
 observaciones VARCHAR2(500)
)
PARTITION BY HASH (id_detalle)
PARTITIONS 4;
CREATE TABLE RECIBO_HONORARIO (
