CREATE OR REPLACE PROCEDURE SP_AGREGAR_MEDICAMENTO (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_RECETA IN RECETA.ID_RECETA%TYPE,
    P_MEDICAMENTO IN RECETA_DETALLE.MEDICAMENTO%TYPE,
    P_DOSIS IN RECETA_DETALLE.DOSIS%TYPE,
    P_FRECUENCIA IN RECETA_DETALLE.FRECUENCIA%TYPE,
    P_DURACION IN RECETA_DETALLE.DURACION%TYPE,
    P_ID_DETALLE OUT RECETA_DETALLE.ID_DETALLE%TYPE,
    P_OBSERVACIONES IN RECETA_DETALLE.OBSERVACIONES%TYPE DEFAULT NULL
)
IS
    V_ID_ATENCION ATENCION_MEDICA.ID_ATENCION%TYPE;
    V_ID_CITA CITA.ID_CITA%TYPE;
    V_ID_DOCTOR CITA.ID_DOCTOR%TYPE;
    V_ESTADO_CITA CITA.ESTADO%TYPE;
    V_ESTADO_ATENCION ATENCION_MEDICA.ESTADO%TYPE;
    V_CANTIDAD NUMBER;
BEGIN
    P_ID_DETALLE := NULL;
    SAVEPOINT SV_MEDICAMENTO;

    IF NVL(FN_ROL_USUARIO(P_ID_USUARIO),'SIN_ROL') <> 'DOCTOR' THEN
        RAISE_APPLICATION_ERROR(-20414,'Solo el doctor puede agregar medicamentos.');
    END IF;
    IF TRIM(P_MEDICAMENTO) IS NULL OR TRIM(P_DOSIS) IS NULL
       OR TRIM(P_FRECUENCIA) IS NULL OR TRIM(P_DURACION) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20415,'Medicamento, dosis, frecuencia y duracion son obligatorios.');
    END IF;

    SELECT R.ID_ATENCION,A.ID_CITA INTO V_ID_ATENCION,V_ID_CITA
      FROM RECETA R JOIN ATENCION_MEDICA A ON A.ID_ATENCION=R.ID_ATENCION
     WHERE R.ID_RECETA=P_ID_RECETA;

    -- Mismo orden de bloqueo en todos los procedimientos: CITA y ATENCION.
    SELECT ID_DOCTOR,ESTADO INTO V_ID_DOCTOR,V_ESTADO_CITA
      FROM CITA WHERE ID_CITA=V_ID_CITA FOR UPDATE;
    IF V_ESTADO_CITA <> 'EN_ATENCION' THEN
        RAISE_APPLICATION_ERROR(-20416,'La cita no esta EN_ATENCION.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD FROM DOCTOR
     WHERE ID_DOCTOR=V_ID_DOCTOR AND ID_USUARIO=P_ID_USUARIO AND ESTADO='ACTIVO';
    IF V_CANTIDAD <> 1 THEN
        RAISE_APPLICATION_ERROR(-20417,'El usuario no es el doctor asignado.');
    END IF;

    SELECT ESTADO INTO V_ESTADO_ATENCION
      FROM ATENCION_MEDICA
     WHERE ID_ATENCION=V_ID_ATENCION AND ID_CITA=V_ID_CITA
       AND ID_DOCTOR=V_ID_DOCTOR FOR UPDATE;
    IF V_ESTADO_ATENCION <> 'ABIERTA' THEN
        RAISE_APPLICATION_ERROR(-20418,'La atencion ya esta cerrada.');
    END IF;

    INSERT INTO RECETA_DETALLE (
        ID_RECETA,MEDICAMENTO,DOSIS,FRECUENCIA,DURACION,OBSERVACIONES
    ) VALUES (
        P_ID_RECETA,TRIM(P_MEDICAMENTO),TRIM(P_DOSIS),
        TRIM(P_FRECUENCIA),TRIM(P_DURACION),P_OBSERVACIONES
    ) RETURNING ID_DETALLE INTO P_ID_DETALLE;

    INSERT INTO AUDITORIA (ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,ORIGEN)
    VALUES (P_ID_USUARIO,'RECETA_DETALLE',P_ID_DETALLE,'AGREGAR',
            'Detalle registrado para receta '||P_ID_RECETA,'USUARIO');

    DBMS_OUTPUT.PUT_LINE('Medicamento agregado: '||P_ID_DETALLE);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_MEDICAMENTO;
        RAISE_APPLICATION_ERROR(-20419,'Receta, cita o atencion no encontrada.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_MEDICAMENTO;
        RAISE;
END SP_AGREGAR_MEDICAMENTO;
