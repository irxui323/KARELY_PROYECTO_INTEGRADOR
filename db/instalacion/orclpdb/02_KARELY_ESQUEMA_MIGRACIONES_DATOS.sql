CREATE TABLE ROL (
 id_rol NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(40) NOT NULL UNIQUE,
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO'))
)
PARTITION BY HASH (id_rol)
PARTITIONS 2;
CREATE TABLE USUARIO (
 id_usuario NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_rol NUMBER NOT NULL REFERENCES ROL(id_rol),
 username VARCHAR2(60) NOT NULL UNIQUE,
 correo VARCHAR2(150) NOT NULL UNIQUE,
 password_hash VARCHAR2(255) NOT NULL,
 estado VARCHAR2(12) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO','BLOQUEADO')),
 intentos_fallidos NUMBER(3) DEFAULT 0 NOT NULL CHECK(intentos_fallidos >= 0),
 ultimo_acceso TIMESTAMP
)
PARTITION BY HASH (id_usuario)
PARTITIONS 4;
CREATE TABLE SESION_USUARIO (
 id_sesion NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_usuario NUMBER NOT NULL REFERENCES USUARIO(id_usuario),
 fecha_inicio TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 fecha_fin TIMESTAMP,
 ultima_actividad TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 ip_origen VARCHAR2(45),
 estado VARCHAR2(10) DEFAULT 'ACTIVA' NOT NULL CHECK(estado IN ('ACTIVA','CERRADA','EXPIRADA')),
 CONSTRAINT ck_sesion_fechas CHECK(fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
)
PARTITION BY RANGE (FECHA_INICIO)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION P_SES_ANT_2026 VALUES LESS THAN
        (TIMESTAMP '2026-01-01 00:00:00')
        TABLESPACE TBS_KARELY_BD2
);
CREATE TABLE AUDITORIA (
 id_auditoria NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_usuario NUMBER REFERENCES USUARIO(id_usuario),
 tabla_afectada VARCHAR2(40) NOT NULL,
 id_registro NUMBER,
 accion VARCHAR2(20) NOT NULL,
 detalle VARCHAR2(500),
 fecha_operacion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
)
PARTITION BY RANGE (FECHA_OPERACION)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION P_AUD_ANT_2026 VALUES LESS THAN
        (TIMESTAMP '2026-01-01 00:00:00')
        TABLESPACE TBS_KARELY_BD2
);
CREATE TABLE DOCTOR (
 id_doctor NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_usuario NUMBER UNIQUE REFERENCES USUARIO(id_usuario),
 tipo_documento VARCHAR2(12) NOT NULL,
 numero_documento VARCHAR2(20) NOT NULL UNIQUE,
 nombres VARCHAR2(100) NOT NULL,
 apellidos VARCHAR2(100) NOT NULL,
 telefono VARCHAR2(20),
 correo VARCHAR2(150),
 estado_documentacion VARCHAR2(12) DEFAULT 'INCOMPLETO' NOT NULL
   CHECK(estado_documentacion IN ('INCOMPLETO','COMPLETO','RECHAZADO')),
 fecha_alta DATE DEFAULT SYSDATE NOT NULL,
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO'))
)
PARTITION BY HASH (id_doctor)
PARTITIONS 4;
CREATE TABLE DOCUMENTO_DOCTOR (
 id_documento NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_doctor NUMBER NOT NULL REFERENCES DOCTOR(id_doctor),
 tipo_documento VARCHAR2(12) NOT NULL CHECK(tipo_documento IN ('DNI','TITULO','OTRO')),
 nombre_archivo VARCHAR2(255) NOT NULL,
 tipo_mime VARCHAR2(100) NOT NULL,
 archivo BLOB NOT NULL,
 hash VARCHAR2(128),
 estado VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL CHECK(estado IN ('PENDIENTE','VALIDADO','RECHAZADO')),
 fecha_validacion TIMESTAMP,
 usuario_validacion NUMBER REFERENCES USUARIO(id_usuario)
)
PARTITION BY HASH (id_documento)
PARTITIONS 4;
CREATE TABLE ESPECIALIDAD (
 id_especialidad NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(120) NOT NULL UNIQUE,
 precio_consulta NUMBER(12,2) NOT NULL CHECK(precio_consulta >= 0),
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO'))
)
PARTITION BY HASH (id_especialidad)
PARTITIONS 2;
CREATE TABLE DOCTOR_ESPECIALIDAD (
 id_doctor_especialidad NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_doctor NUMBER NOT NULL REFERENCES DOCTOR(id_doctor),
 id_especialidad NUMBER NOT NULL REFERENCES ESPECIALIDAD(id_especialidad),
 CONSTRAINT uq_doctor_especialidad UNIQUE(id_doctor,id_especialidad)
)
PARTITION BY HASH (id_doctor_especialidad)
PARTITIONS 4;
CREATE TABLE PACIENTE (
 id_paciente NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 tipo_documento VARCHAR2(12) NOT NULL,
 numero_documento VARCHAR2(20) NOT NULL,
 nombres VARCHAR2(100) NOT NULL,
 apellidos VARCHAR2(100) NOT NULL,
 fecha_nacimiento DATE,
 telefono VARCHAR2(20),
 correo VARCHAR2(150),
 direccion VARCHAR2(250),
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO')),
 CONSTRAINT uq_paciente_documento UNIQUE(tipo_documento,numero_documento)
)
PARTITION BY HASH (id_paciente)
PARTITIONS 4;
CREATE TABLE CONSULTORIO (
 id_consultorio NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 nombre VARCHAR2(100) NOT NULL UNIQUE,
 ubicacion VARCHAR2(200),
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO'))
)
PARTITION BY HASH (id_consultorio)
PARTITIONS 2;
CREATE TABLE FRANJA_HORARIA (
 id_franja NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 hora_inicio VARCHAR2(5) NOT NULL,
 hora_fin VARCHAR2(5) NOT NULL,
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO')),
 CONSTRAINT ck_franja_formato CHECK (
  REGEXP_LIKE(hora_inicio,'^([01][0-9]|2[0-3]):[0-5][0-9]$') AND
  REGEXP_LIKE(hora_fin,'^([01][0-9]|2[0-3]):[0-5][0-9]$') AND hora_inicio < hora_fin),
 CONSTRAINT uq_franja UNIQUE(hora_inicio,hora_fin)
)
PARTITION BY HASH (id_franja)
PARTITIONS 2;
CREATE TABLE DISPONIBILIDAD_DOCTOR (
 id_disponibilidad NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 id_doctor NUMBER NOT NULL REFERENCES DOCTOR(id_doctor),
 id_franja NUMBER NOT NULL REFERENCES FRANJA_HORARIA(id_franja),
 fecha_turno DATE NOT NULL,
 estado VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK(estado IN ('ACTIVO','INACTIVO')),
 CONSTRAINT ck_disponibilidad_fecha CHECK(fecha_turno = TRUNC(fecha_turno)),
 CONSTRAINT uq_disponibilidad UNIQUE(id_doctor,fecha_turno,id_franja)
)
PARTITION BY HASH (id_disponibilidad)
PARTITIONS 4;

