            'Constancia de entrega a paciente; medio '||SUBSTR(P_MEDIO_ENTREGA,1,30),
            'USUARIO');

    DBMS_OUTPUT.PUT_LINE('Entrega registrada para recibo '||V_ID_RECIBO);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_ENTREGAR_RECIBO;
        RAISE_APPLICATION_ERROR(-20435,'Cita, atencion o recibo no encontrado.');
    WHEN OTHERS THEN
