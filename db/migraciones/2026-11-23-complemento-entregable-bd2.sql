-- 1. FUNCIONES DE CONSULTA
CREATE OR REPLACE FUNCTION FN_EDAD_PACIENTE(p_id_paciente NUMBER)
RETURN NUMBER
IS
    v_fecha_nacimiento PACIENTE.FECHA_NACIMIENTO%TYPE;
BEGIN
    SELECT FECHA_NACIMIENTO INTO v_fecha_nacimiento
      FROM PACIENTE WHERE ID_PACIENTE = p_id_paciente;
    RETURN CASE WHEN v_fecha_nacimiento IS NULL THEN NULL
                ELSE TRUNC(MONTHS_BETWEEN(TRUNC(SYSDATE), v_fecha_nacimiento) / 12) END;
EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN NULL;
END;
/

CREATE OR REPLACE FUNCTION FN_ESTADO_CITA(p_id_cita NUMBER)
RETURN VARCHAR2
IS
    v_estado CITA.ESTADO%TYPE;
BEGIN
    SELECT ESTADO INTO v_estado FROM CITA WHERE ID_CITA = p_id_cita;
    RETURN v_estado;
EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN NULL;
END;
/

CREATE OR REPLACE FUNCTION FN_TOTAL_CITAS_DOCTOR(
    p_id_doctor NUMBER, p_fecha_inicio DATE, p_fecha_fin DATE
) RETURN NUMBER
IS
    v_total NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total
      FROM CITA
     WHERE ID_DOCTOR = p_id_doctor
       AND FECHA_CITA BETWEEN TRUNC(p_fecha_inicio) AND TRUNC(p_fecha_fin);
    RETURN v_total;
END;
/

CREATE OR REPLACE FUNCTION FN_INGRESOS_GESTORA(
    p_fecha_inicio DATE, p_fecha_fin DATE
) RETURN NUMBER
IS
    v_total NUMBER;
BEGIN
    SELECT NVL(SUM(MONTO_INGRESO), 0) INTO v_total
      FROM VW_INGRESOS_GESTORA
     WHERE FECHA_CITA BETWEEN TRUNC(p_fecha_inicio) AND TRUNC(p_fecha_fin);
    RETURN v_total;
END;
/

-- 2. TRIGGERS EXCLUSIVOS DE AUDITORIA
CREATE OR REPLACE TRIGGER TR_AUD_USUARIO_DATOS
AFTER INSERT OR UPDATE OR DELETE ON USUARIO
DECLARE
    v_accion VARCHAR2(20);
BEGIN
    IF INSERTING THEN
        v_accion := 'INSERTAR';
    ELSIF UPDATING THEN
        v_accion := 'ACTUALIZAR';
    ELSE
        v_accion := 'ELIMINAR';
    END IF;
    -- Por sentencia: evita consultar USUARIO mientras se modifica y no guarda hashes.
    INSERT INTO AUDITORIA(TABLA_AFECTADA, ACCION, DETALLE, ORIGEN)
    VALUES ('USUARIO', v_accion,
        'Sentencia sobre USUARIO. Sesion Oracle: ' || SYS_CONTEXT('USERENV', 'SESSION_USER')
        || '. Identificador aplicacion: ' || SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
        'SISTEMA');
END;
/

CREATE OR REPLACE TRIGGER TR_AUD_PACIENTE_DATOS
AFTER INSERT OR UPDATE OR DELETE ON PACIENTE
FOR EACH ROW
DECLARE
    v_accion VARCHAR2(20);
    v_detalle VARCHAR2(500);
BEGIN
    IF INSERTING THEN
        v_accion := 'INSERTAR'; v_detalle := 'Paciente creado';
    ELSIF UPDATING THEN
        v_accion := 'ACTUALIZAR'; v_detalle := 'Paciente actualizado';
    ELSE
        v_accion := 'ELIMINAR'; v_detalle := 'Paciente eliminado';
    END IF;
    INSERT INTO AUDITORIA(ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO, ACCION, DETALLE, ORIGEN)
    VALUES (NULL, 'PACIENTE', NVL(:NEW.ID_PACIENTE, :OLD.ID_PACIENTE), v_accion,
        v_detalle || '. Sesion Oracle: ' || SYS_CONTEXT('USERENV', 'SESSION_USER')
        || '. Identificador aplicacion: ' || SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), 'SISTEMA');
END;
/

-- 3. VISTAS SEGURAS Y DE REPORTE
CREATE OR REPLACE VIEW V_S_USUARIO_ENMASCARADO AS
SELECT ID_USUARIO, USERNAME,
       CASE WHEN INSTR(CORREO, '@') > 2
            THEN SUBSTR(CORREO, 1, 2) || '***' || SUBSTR(CORREO, INSTR(CORREO, '@'))
            ELSE '***' END AS CORREO_ENMASCARADO,
       ESTADO, INTENTOS_FALLIDOS, ULTIMO_ACCESO
  FROM USUARIO;

CREATE OR REPLACE VIEW V_S_PACIENTE_ENMASCARADO AS
SELECT ID_PACIENTE, TIPO_DOCUMENTO,
       SUBSTR(NUMERO_DOCUMENTO, 1, 2) || '****' || SUBSTR(NUMERO_DOCUMENTO, -2) AS DOCUMENTO_ENMASCARADO,
       NOMBRES, APELLIDOS,
       CASE WHEN INSTR(CORREO, '@') > 2
            THEN SUBSTR(CORREO, 1, 2) || '***' || SUBSTR(CORREO, INSTR(CORREO, '@'))
            ELSE NULL END AS CORREO_ENMASCARADO,
       ESTADO
  FROM PACIENTE;

CREATE OR REPLACE VIEW V_S_DOCTOR_ENMASCARADO AS
SELECT ID_DOCTOR, TIPO_DOCUMENTO,
       SUBSTR(NUMERO_DOCUMENTO, 1, 2) || '****' || SUBSTR(NUMERO_DOCUMENTO, -2) AS DOCUMENTO_ENMASCARADO,
       NOMBRES, APELLIDOS,
       CASE WHEN INSTR(CORREO, '@') > 2
            THEN SUBSTR(CORREO, 1, 2) || '***' || SUBSTR(CORREO, INSTR(CORREO, '@'))
            ELSE NULL END AS CORREO_ENMASCARADO,
       ESTADO_DOCUMENTACION, ESTADO
  FROM DOCTOR;

CREATE OR REPLACE VIEW V_M_CITAS_ESPECIALIDAD AS
SELECT E.ID_ESPECIALIDAD, E.NOMBRE AS ESPECIALIDAD, C.ESTADO,
       COUNT(*) AS TOTAL_CITAS, SUM(C.MONTO_TOTAL) AS MONTO_PROGRAMADO
  FROM CITA C JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD = C.ID_ESPECIALIDAD
 GROUP BY E.ID_ESPECIALIDAD, E.NOMBRE, C.ESTADO;

CREATE OR REPLACE VIEW V_M_CITAS_CONSULTORIO AS
SELECT CO.ID_CONSULTORIO, CO.NOMBRE AS CONSULTORIO, C.FECHA_CITA,
       COUNT(*) AS TOTAL_CITAS,
       SUM(CASE WHEN C.ESTADO = 'ATENDIDA' THEN 1 ELSE 0 END) AS TOTAL_ATENDIDAS
  FROM CITA C JOIN CONSULTORIO CO ON CO.ID_CONSULTORIO = C.ID_CONSULTORIO
 GROUP BY CO.ID_CONSULTORIO, CO.NOMBRE, C.FECHA_CITA;

CREATE OR REPLACE VIEW V_M_RECAUDACION_MENSUAL AS
SELECT TO_CHAR(FECHA_PAGO, 'YYYY-MM') AS PERIODO, METODO_PAGO,
       COUNT(*) AS TOTAL_PAGOS, SUM(MONTO) AS MONTO_RECAUDADO
  FROM PAGO_CITA
 WHERE ESTADO = 'APROBADO'
 GROUP BY TO_CHAR(FECHA_PAGO, 'YYYY-MM'), METODO_PAGO;

CREATE OR REPLACE VIEW V_M_PRODUCTIVIDAD_DOCTOR AS
SELECT D.ID_DOCTOR, D.NOMBRES || ' ' || D.APELLIDOS AS DOCTOR,
       COUNT(C.ID_CITA) AS TOTAL_CITAS,
       SUM(CASE WHEN C.ESTADO = 'ATENDIDA' THEN 1 ELSE 0 END) AS TOTAL_ATENDIDAS,
       NVL(SUM(CASE WHEN C.ESTADO = 'ATENDIDA' THEN C.MONTO_DOCTOR_DEVENGADO ELSE 0 END), 0) AS MONTO_DEVENGADO
  FROM DOCTOR D LEFT JOIN CITA C ON C.ID_DOCTOR = D.ID_DOCTOR
 GROUP BY D.ID_DOCTOR, D.NOMBRES, D.APELLIDOS;

CREATE OR REPLACE VIEW V_M_PAGOS_DOCTOR_MENSUAL AS
SELECT TO_CHAR(FECHA_PAGO, 'YYYY-MM') AS PERIODO, D.ID_DOCTOR,
       D.NOMBRES || ' ' || D.APELLIDOS AS DOCTOR,
       COUNT(*) AS TOTAL_PAGOS, SUM(L.MONTO) AS MONTO_PAGADO
  FROM LIQUIDACION L JOIN DOCTOR D ON D.ID_DOCTOR = L.ID_DOCTOR
 GROUP BY TO_CHAR(FECHA_PAGO, 'YYYY-MM'), D.ID_DOCTOR, D.NOMBRES, D.APELLIDOS;

CREATE OR REPLACE VIEW V_M_AUDITORIA_OPERATIVA AS
SELECT A.FECHA_OPERACION, A.TABLA_AFECTADA, A.ACCION, A.ORIGEN,
       U.USERNAME AS USUARIO, A.DETALLE
  FROM AUDITORIA A LEFT JOIN USUARIO U ON U.ID_USUARIO = A.ID_USUARIO;

