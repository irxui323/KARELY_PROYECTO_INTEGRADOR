SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

SELECT OBJECT_TYPE, COUNT(*) AS TOTAL, SUM(CASE WHEN STATUS='INVALID' THEN 1 ELSE 0 END) AS INVALIDOS
FROM USER_OBJECTS WHERE OBJECT_TYPE IN ('FUNCTION','PROCEDURE','TRIGGER','VIEW')
GROUP BY OBJECT_TYPE ORDER BY OBJECT_TYPE;

SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS ORDER BY NAME, SEQUENCE;

SELECT * FROM V_S_USUARIO_ENMASCARADO FETCH FIRST 5 ROWS ONLY;
SELECT * FROM V_S_PACIENTE_ENMASCARADO FETCH FIRST 5 ROWS ONLY;
SELECT * FROM V_S_DOCTOR_ENMASCARADO FETCH FIRST 5 ROWS ONLY;

SELECT ID_PACIENTE, FN_EDAD_PACIENTE(ID_PACIENTE) AS EDAD
FROM PACIENTE FETCH FIRST 5 ROWS ONLY;
SELECT ID_CITA, ESTADO, FN_ESTADO_CITA(ID_CITA) AS ESTADO_FUNCION
FROM CITA FETCH FIRST 5 ROWS ONLY;
SELECT ID_DOCTOR, FN_TOTAL_CITAS_DOCTOR(ID_DOCTOR, TRUNC(SYSDATE)-30, TRUNC(SYSDATE)) AS CITAS_30_DIAS
FROM DOCTOR FETCH FIRST 5 ROWS ONLY;
SELECT FN_INGRESOS_GESTORA(TRUNC(SYSDATE)-30, TRUNC(SYSDATE)) AS INGRESOS_30_DIAS FROM DUAL;

SELECT TRIGGER_NAME, STATUS, TRIGGER_TYPE FROM USER_TRIGGERS
WHERE TRIGGER_NAME IN ('TR_AUD_USUARIO_DATOS','TR_AUD_PACIENTE_DATOS');

