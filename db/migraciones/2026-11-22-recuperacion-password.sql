SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

DECLARE
    v_total NUMBER;
BEGIN
    IF USER <> 'KARELY_BD2' THEN
        RAISE_APPLICATION_ERROR(-20920, 'Conectarse como KARELY_BD2 para ampliar el esquema');
    END IF;
    SELECT COUNT(*) INTO v_total FROM USER_TABLES WHERE TABLE_NAME='TOKEN_RECUPERACION';
    IF v_total=0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE TOKEN_RECUPERACION (
                TOKEN_HASH VARCHAR2(64) PRIMARY KEY,
                ID_USUARIO NUMBER NOT NULL REFERENCES USUARIO(ID_USUARIO),
                CORREO VARCHAR2(150) NOT NULL,
                VERSION_CREDENCIAL VARCHAR2(64) NOT NULL,
                FECHA_CREACION TIMESTAMP NOT NULL,
                FECHA_EXPIRACION TIMESTAMP NOT NULL,
                FECHA_USO TIMESTAMP,
                CONSTRAINT CK_TOKEN_REC_FECHAS CHECK(FECHA_EXPIRACION > FECHA_CREACION)
            )
        ]';
        EXECUTE IMMEDIATE 'CREATE INDEX IX_TOKEN_REC_USUARIO ON TOKEN_RECUPERACION(ID_USUARIO)';
        DBMS_OUTPUT.PUT_LINE('Tabla TOKEN_RECUPERACION creada');
    ELSE
        DBMS_OUTPUT.PUT_LINE('TOKEN_RECUPERACION ya existe; no se recrearon objetos');
    END IF;
END;
/

SELECT TABLE_NAME FROM USER_TABLES WHERE TABLE_NAME='TOKEN_RECUPERACION';
SELECT COLUMN_NAME,DATA_TYPE,NULLABLE FROM USER_TAB_COLUMNS
WHERE TABLE_NAME='TOKEN_RECUPERACION' ORDER BY COLUMN_ID;
