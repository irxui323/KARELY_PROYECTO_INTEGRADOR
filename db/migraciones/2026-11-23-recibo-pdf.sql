SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_cantidad NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cantidad FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'RECIBO_HONORARIO' AND COLUMN_NAME = 'ARCHIVO_PDF';
    IF v_cantidad = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE RECIBO_HONORARIO ADD ARCHIVO_PDF BLOB';
    END IF;
    SELECT COUNT(*) INTO v_cantidad FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'RECIBO_HONORARIO' AND COLUMN_NAME = 'CORREO_ENVIO';
    IF v_cantidad = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE RECIBO_HONORARIO ADD CORREO_ENVIO VARCHAR2(150)';
    END IF;
END;
/

SELECT COLUMN_NAME, DATA_TYPE FROM USER_TAB_COLUMNS
 WHERE TABLE_NAME = 'RECIBO_HONORARIO'
 AND COLUMN_NAME IN ('ARCHIVO_PDF', 'CORREO_ENVIO');
