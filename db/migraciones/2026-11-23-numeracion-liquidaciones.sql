-- Correlativo único para operación y boleta de pagos a médicos.
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM USER_SEQUENCES
     WHERE SEQUENCE_NAME = 'SQ_LIQUIDACION_REFERENCIA';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE SEQUENCE SQ_LIQUIDACION_REFERENCIA START WITH 1 INCREMENT BY 1 NOCACHE';
    END IF;
END;
/

PROMPT Secuencia de liquidaciones preparada.
