-- Ejecutar con F5 como KARELY_BD2. Solo realiza consultas; no modifica filas.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
BEGIN
  IF USER <> 'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20994,'Ejecutar como KARELY_BD2.'); END IF;
END;
/

PROMPT === Estado de procedimientos, funciones, triggers y vistas ===
WITH REQUERIDOS AS (
  SELECT 'PROCEDURE' TIPO, 'SP_VALIDAR_DOCUMENTACION' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_REGISTRAR_DISPONIBILIDAD' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_CONSULTAR_HORARIOS_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_DOCUMENTACION_COMPLETA' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_TOTAL_ESPECIALIDADES' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_DOCUMENTO_REVALIDACION' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_DOCTOR_ESTADO_VALIDADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_DOCTOR_ESTADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_DOCTOR_ENMASCARADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_DOCUMENTACION_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_HORARIOS_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_ESPECIALIDADES_DOC' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_DOCUMENTOS_DOC' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_HORARIOS_DOC' NOMBRE FROM DUAL
)
SELECT R.TIPO,R.NOMBRE,NVL(O.STATUS,'FALTA') STATUS
FROM REQUERIDOS R LEFT JOIN USER_OBJECTS O
ON O.OBJECT_TYPE=R.TIPO AND O.OBJECT_NAME=R.NOMBRE
ORDER BY R.TIPO,R.NOMBRE;

PROMPT === Funciones del modulo ===
DECLARE
  v_id NUMBER; v_franja NUMBER; v_liq NUMBER;
BEGIN
  SELECT MIN(ID_DOCTOR) INTO v_id FROM DOCTOR;
  DBMS_OUTPUT.PUT_LINE('FN_DOCUMENTACION_COMPLETA='||FN_DOCUMENTACION_COMPLETA(v_id));
  DBMS_OUTPUT.PUT_LINE('FN_TOTAL_ESPECIALIDADES='||FN_TOTAL_ESPECIALIDADES(v_id));
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('PENDIENTE: faltan filas para evaluar alguna funcion.');
WHEN OTHERS THEN DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/

