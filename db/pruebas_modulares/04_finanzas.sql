PROMPT === Estado de procedimientos, funciones, triggers y vistas ===
WITH REQUERIDOS AS (
  SELECT 'PROCEDURE' TIPO, 'SP_PAGAR_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_GENERAR_LIQUIDACION' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EMITIR_RECIBO' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_MONTO_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_SALDO_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_PAGO_CITA' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_LIQUIDACION' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'VW_PAGOS_CITA' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'VW_INGRESOS_GESTORA' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'VW_SALDOS_LIQUIDACIONES' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_PAGO_ENMASCARADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_COBROS_PERIODO' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_PAGOS_DOCTOR' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_INGRESOS_GESTORA' NOMBRE FROM DUAL
)
SELECT R.TIPO,R.NOMBRE,NVL(O.STATUS,'FALTA') STATUS
FROM REQUERIDOS R LEFT JOIN USER_OBJECTS O
ON O.OBJECT_TYPE=R.TIPO AND O.OBJECT_NAME=R.NOMBRE
ORDER BY R.TIPO,R.NOMBRE;

PROMPT === Funciones del modulo ===
DECLARE
  v_id NUMBER; v_franja NUMBER; v_liq NUMBER;
BEGIN
  SELECT MIN(ID_DOCTOR) INTO v_id FROM DOCTOR;
  DBMS_OUTPUT.PUT_LINE('FN_MONTO_DOCTOR(100)='||FN_MONTO_DOCTOR(100));
  DBMS_OUTPUT.PUT_LINE('FN_SALDO_DOCTOR='||FN_SALDO_DOCTOR(v_id));
  SELECT MIN(ID_LIQUIDACION) INTO v_liq FROM LIQUIDACION;
  IF v_liq IS NOT NULL THEN DBMS_OUTPUT.PUT_LINE('FN_SALDO_LIQUIDACION='||FN_SALDO_LIQUIDACION(v_liq)); END IF;
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('PENDIENTE: faltan filas para evaluar alguna funcion.');
WHEN OTHERS THEN DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/

