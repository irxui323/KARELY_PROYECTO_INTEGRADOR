PROMPT === Estado de procedimientos, funciones, triggers y vistas ===
WITH REQUERIDOS AS (
  SELECT 'PROCEDURE' TIPO, 'SP_PRE_RESERVAR_CITA' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_CONFIRMAR_CITA_PAGADA' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_REPROGRAMAR_CITA' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_INICIO_TURNO' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_ESTADO_CITA' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_CITA_ESTADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_REPROGRAMACION' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_M_CITAS_ESPECIALIDAD' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_M_CITAS_CONSULTORIO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_CITA_ENMASCARADA' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_AGENDA_DIA' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_RESUMEN_CITAS' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_CAMBIO_CITA' NOMBRE FROM DUAL
)
SELECT R.TIPO,R.NOMBRE,NVL(O.STATUS,'FALTA') STATUS
FROM REQUERIDOS R LEFT JOIN USER_OBJECTS O
ON O.OBJECT_TYPE=R.TIPO AND O.OBJECT_NAME=R.NOMBRE
ORDER BY R.TIPO,R.NOMBRE;

PROMPT === Funciones del modulo ===
DECLARE
  v_id NUMBER; v_franja NUMBER; v_liq NUMBER;
BEGIN
  SELECT MIN(ID_CITA) INTO v_id FROM CITA;
  DBMS_OUTPUT.PUT_LINE('FN_ESTADO_CITA='||NVL(FN_ESTADO_CITA(v_id),'(sin citas)'));
  SELECT MIN(ID_FRANJA) INTO v_franja FROM FRANJA_HORARIA WHERE ESTADO='ACTIVO';
  DBMS_OUTPUT.PUT_LINE('FN_INICIO_TURNO='||TO_CHAR(FN_INICIO_TURNO(TRUNC(SYSDATE),v_franja),'YYYY-MM-DD HH24:MI'));
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('PENDIENTE: faltan filas para evaluar alguna funcion.');
WHEN OTHERS THEN DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/

