PROMPT === Estado de procedimientos, funciones, triggers y vistas ===
WITH REQUERIDOS AS (
  SELECT 'PROCEDURE' TIPO, 'SP_REGISTRAR_ASISTENCIA' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_CREAR_USUARIO' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_CERRAR_SESION' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_ROL_USUARIO' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_SESIONES_ACTIVAS_USUARIO' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_USUARIO_DATOS' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_SESION_ESTADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_ASISTENCIA_REGISTRO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_USUARIO_ENMASCARADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_RECEPCION_ASISTENCIA' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_SEGURIDAD_SESIONES' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_ASISTENCIAS_DIA' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_USUARIOS_ESTADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_SESIONES_USUARIO' NOMBRE FROM DUAL
)
SELECT R.TIPO,R.NOMBRE,NVL(O.STATUS,'FALTA') STATUS
FROM REQUERIDOS R LEFT JOIN USER_OBJECTS O
ON O.OBJECT_TYPE=R.TIPO AND O.OBJECT_NAME=R.NOMBRE
ORDER BY R.TIPO,R.NOMBRE;

PROMPT === Funciones del modulo ===
DECLARE
  v_id NUMBER; v_franja NUMBER; v_liq NUMBER;
BEGIN
  SELECT MIN(ID_USUARIO) INTO v_id FROM USUARIO;
  DBMS_OUTPUT.PUT_LINE('FN_SESIONES_ACTIVAS_USUARIO='||FN_SESIONES_ACTIVAS_USUARIO(v_id));
  DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_id));
  DBMS_OUTPUT.PUT_LINE('FN_ROL_USUARIO='||FN_ROL_USUARIO(v_id));
  DBMS_SESSION.CLEAR_IDENTIFIER;
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('PENDIENTE: faltan filas para evaluar alguna funcion.');
WHEN OTHERS THEN DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/

