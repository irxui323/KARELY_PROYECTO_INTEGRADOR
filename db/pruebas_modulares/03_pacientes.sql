PROMPT === Estado de procedimientos, funciones, triggers y vistas ===
WITH REQUERIDOS AS (
  SELECT 'PROCEDURE' TIPO, 'SP_INICIAR_ATENCION' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_REGISTRAR_DIAGNOSTICO' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_CREAR_RECETA' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_EDAD_PACIENTE' NOMBRE FROM DUAL
  UNION ALL SELECT 'FUNCTION' TIPO, 'FN_TOTAL_ATENCIONES_PACIENTE' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_PACIENTE_DATOS' NOMBRE FROM DUAL
  UNION ALL SELECT 'TRIGGER' TIPO, 'TR_AUD_ATENCION_ESTADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_PACIENTE_ENMASCARADO' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_HISTORIAL_PACIENTE' NOMBRE FROM DUAL
  UNION ALL SELECT 'VIEW' TIPO, 'V_S_RECETAS_PACIENTE' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_BUSCAR_PACIENTE' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_HISTORIAL_PAC' NOMBRE FROM DUAL
  UNION ALL SELECT 'PROCEDURE' TIPO, 'SP_EXP_DETALLE_RECETA' NOMBRE FROM DUAL
)
SELECT R.TIPO,R.NOMBRE,NVL(O.STATUS,'FALTA') STATUS
FROM REQUERIDOS R LEFT JOIN USER_OBJECTS O
ON O.OBJECT_TYPE=R.TIPO AND O.OBJECT_NAME=R.NOMBRE
ORDER BY R.TIPO,R.NOMBRE;

PROMPT === Funciones del modulo ===
DECLARE
  v_id NUMBER; v_franja NUMBER; v_liq NUMBER;
BEGIN
  SELECT MIN(ID_PACIENTE) INTO v_id FROM PACIENTE;
  DBMS_OUTPUT.PUT_LINE('FN_EDAD_PACIENTE='||NVL(TO_CHAR(FN_EDAD_PACIENTE(v_id)),'(sin pacientes)'));
  DBMS_OUTPUT.PUT_LINE('FN_TOTAL_ATENCIONES_PACIENTE='||FN_TOTAL_ATENCIONES_PACIENTE(v_id));
EXCEPTION WHEN NO_DATA_FOUND THEN DBMS_OUTPUT.PUT_LINE('PENDIENTE: faltan filas para evaluar alguna funcion.');
WHEN OTHERS THEN DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/

