-- Conectar como "recepcion.centro". No conservara la asistencia de prueba.
SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 v_cita NUMBER; v_asistencia NUMBER; v_total NUMBER;
BEGIN
 SAVEPOINT prueba_asistencia;
 IF SYS_CONTEXT('USERENV','SESSION_USER')<>'recepcion.centro' THEN
  RAISE_APPLICATION_ERROR(-20994,'Probar como recepcion.centro.'); END IF;
 SELECT MIN(ID_CITA) INTO v_cita FROM KARELY_BD2.VW_AGENDA_CITAS
 WHERE ESTADO_CITA IN ('PROGRAMADA','REPROGRAMADA') AND ASISTENCIA_REGISTRADA='NO'
 AND CAST(SYSTIMESTAMP AS TIMESTAMP)
 BETWEEN TO_TIMESTAMP(TO_CHAR(FECHA_CITA,'YYYY-MM-DD')||' '||HORA_INICIO,'YYYY-MM-DD HH24:MI')-INTERVAL '30' MINUTE
 AND TO_TIMESTAMP(TO_CHAR(FECHA_CITA,'YYYY-MM-DD')||' '||HORA_INICIO,'YYYY-MM-DD HH24:MI');
 IF v_cita IS NULL THEN
  DBMS_OUTPUT.PUT_LINE('PENDIENTE: no hay cita dentro de los 30 minutos previos a su turno.');
 ELSE
  KARELY_BD2.SP_ORA_ASISTENCIA(v_cita,v_asistencia);
  SELECT COUNT(*) INTO v_total FROM KARELY_BD2.V_S_RECEPCION_ASISTENCIA
  WHERE ID_CITA=v_cita AND ASISTENCIA='PRESENTE' AND ESTADO_CITA='EN_ATENCION';
  IF v_asistencia IS NULL OR v_total<>1 THEN
   RAISE_APPLICATION_ERROR(-20995,'Asistencia no verificada.'); END IF;
  DBMS_OUTPUT.PUT_LINE('CORRECTO: asistencia autorizada y cambio a EN_ATENCION.');
 END IF;
 ROLLBACK TO prueba_asistencia;
 DBMS_OUTPUT.PUT_LINE('Cambios de asistencia revertidos.');
EXCEPTION WHEN OTHERS THEN ROLLBACK TO prueba_asistencia; RAISE;
END;
/

