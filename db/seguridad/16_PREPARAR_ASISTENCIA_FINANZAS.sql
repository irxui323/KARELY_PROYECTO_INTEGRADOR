-- KARELY_BD2. Backend detenido. Preferir una copia de pruebas.
-- CREA Y CONFIRMA dos escenarios tecnicos. Limpiar con 17 al terminar.
-- No ejecutar 17 hasta terminar 10 (tesoreria) y 12 (asistencia).
SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 v_admin NUMBER; v_doc_fin NUMBER; v_doc_asist NUMBER; v_especialidad NUMBER;
 v_fecha_fin DATE; v_inicio DATE; v_fin DATE; v_franja NUMBER; v_consultorio NUMBER;
 v_paciente NUMBER; v_reserva NUMBER; v_pago NUMBER; v_cita NUMBER;
 v_precio NUMBER; v_devengo NUMBER; v_total NUMBER;
 v_cita_fin NUMBER; v_cita_asist NUMBER;
 PROCEDURE cargar(p_tipo NUMBER,p_doctor NUMBER,p_especialidad NUMBER,p_fecha DATE,
                   p_consultorio NUMBER,p_franja NUMBER,p_precio NUMBER) IS
 BEGIN
  INSERT INTO PACIENTE(TIPO_DOCUMENTO,NUMERO_DOCUMENTO,NOMBRES,APELLIDOS,ESTADO)
  VALUES('OTRO','QA-PEND-'||p_tipo,'Validacion tecnica','Temporal pendientes','ACTIVO')
  RETURNING ID_PACIENTE INTO v_paciente;
  INSERT INTO PRE_RESERVA_CITA(ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,
   ID_FRANJA,FECHA_CITA,MONTO,FECHA_EXPIRACION,ESTADO)
  VALUES(v_paciente,p_doctor,p_especialidad,p_consultorio,p_franja,p_fecha,p_precio,
   SYSTIMESTAMP+INTERVAL '10' MINUTE,'CONFIRMADA')
  RETURNING ID_PRE_RESERVA INTO v_reserva;
  INSERT INTO PAGO_CITA(ID_PRE_RESERVA,ID_PACIENTE,MONTO,METODO_PAGO,REFERENCIA_PAGO,ESTADO)
  VALUES(v_reserva,v_paciente,p_precio,'EFECTIVO',
   CASE WHEN p_tipo=1 THEN 'QA-PEND-FINANZAS' ELSE 'QA-PEND-ASISTENCIA' END,'APROBADO')
  RETURNING ID_PAGO INTO v_pago;
  INSERT INTO CITA(ID_PRE_RESERVA,ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,
   ID_FRANJA,ID_PAGO,FECHA_CITA,MONTO_TOTAL,ESTADO)
  VALUES(v_reserva,v_paciente,p_doctor,p_especialidad,p_consultorio,
   p_franja,v_pago,p_fecha,p_precio,CASE WHEN p_tipo=1 THEN 'ATENDIDA' ELSE 'PROGRAMADA' END)
  RETURNING ID_CITA INTO v_cita;
  IF p_tipo=1 THEN
   INSERT INTO ASISTENCIA(ID_CITA,ESTADO) VALUES(v_cita,'PRESENTE');
   INSERT INTO ATENCION_MEDICA(ID_CITA,ID_DOCTOR,ESTADO,FECHA_INICIO,FECHA_CIERRE)
   VALUES(v_cita,p_doctor,'CERRADA',CAST(p_fecha AS TIMESTAMP),CAST(p_fecha AS TIMESTAMP));
   v_devengo:=FN_MONTO_DOCTOR(p_precio);
   IF v_devengo<=0 THEN RAISE_APPLICATION_ERROR(-20994,'Se requiere comision positiva para el doctor.'); END IF;
   UPDATE CITA SET MONTO_DOCTOR_DEVENGADO=v_devengo,
    MONTO_GESTORA_DEVENGADO=p_precio-v_devengo WHERE ID_CITA=v_cita;
   v_cita_fin:=v_cita;
  ELSE v_cita_asist:=v_cita;
  END IF;
 END;
BEGIN
 IF USER<>'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20994,'Conectarse como KARELY_BD2.'); END IF;
 SELECT COUNT(*) INTO v_total FROM PAGO_CITA WHERE REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA');
 IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20994,'El escenario ya existe. Limpiar con 17 antes de repetir 16.'); END IF;
 SELECT U.ID_USUARIO INTO v_admin FROM USUARIO U JOIN ROL R ON R.ID_ROL=U.ID_ROL
 WHERE U.USERNAME='admin01' AND U.ESTADO='ACTIVO' AND R.NOMBRE='ADMINISTRADORA';
 -- La vista de saldos existente parte de LIQUIDACION: seleccionar un doctor con un pago historico.
 BEGIN
  SELECT X.ID_DOCTOR,X.FECHA_CORTE INTO v_doc_fin,v_fecha_fin
  FROM (SELECT L.ID_DOCTOR,MAX(L.PERIODO_FIN) AS FECHA_CORTE
        FROM LIQUIDACION L GROUP BY L.ID_DOCTOR) X
  JOIN DOCTOR D ON D.ID_DOCTOR=X.ID_DOCTOR
  WHERE D.ESTADO='ACTIVO' AND X.FECHA_CORTE<=TRUNC(SYSDATE)
  AND FN_SALDO_DOCTOR(X.ID_DOCTOR,X.FECHA_CORTE)>=0
  AND EXISTS(SELECT 1 FROM DOCTOR_ESPECIALIDAD DE JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DE.ID_ESPECIALIDAD
             WHERE DE.ID_DOCTOR=D.ID_DOCTOR AND E.ESTADO='ACTIVO' AND E.PRECIO_CONSULTA>0)
  ORDER BY X.ID_DOCTOR FETCH FIRST 1 ROW ONLY;
 EXCEPTION WHEN NO_DATA_FOUND THEN
  RAISE_APPLICATION_ERROR(-20994,'Se necesita un doctor activo con liquidacion historica y saldo no negativo al corte.');
 END;
 DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_admin));
 SELECT MIN(DE.ID_ESPECIALIDAD) INTO v_especialidad FROM DOCTOR_ESPECIALIDAD DE
 JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DE.ID_ESPECIALIDAD
 WHERE DE.ID_DOCTOR=v_doc_fin AND E.ESTADO='ACTIVO' AND E.PRECIO_CONSULTA>0;
 SELECT PRECIO_CONSULTA INTO v_precio FROM ESPECIALIDAD WHERE ID_ESPECIALIDAD=v_especialidad;
 SELECT MIN(ID_CONSULTORIO) INTO v_consultorio FROM CONSULTORIO WHERE ESTADO='ACTIVO';
 SELECT MIN(ID_FRANJA) INTO v_franja FROM FRANJA_HORARIA WHERE ESTADO='ACTIVO';
 IF v_consultorio IS NULL OR v_franja IS NULL THEN RAISE_APPLICATION_ERROR(-20994,'Faltan consultorios o franjas activas.'); END IF;
 cargar(1,v_doc_fin,v_especialidad,v_fecha_fin,v_consultorio,v_franja,v_precio);
 -- Asistencia: turno dentro de unos 20 minutos, incluso al cruzar medianoche.
 v_inicio:=TO_DATE(TO_CHAR(SYSDATE+20/1440,'YYYY-MM-DD HH24:MI'),'YYYY-MM-DD HH24:MI');
 IF TO_CHAR(v_inicio,'HH24:MI')='23:59' THEN v_inicio:=TRUNC(v_inicio)+1; END IF;
 v_fin:=LEAST(v_inicio+20/1440,TRUNC(v_inicio)+1439/1440);
 SELECT MIN(ID_FRANJA) INTO v_franja FROM FRANJA_HORARIA
 WHERE HORA_INICIO=TO_CHAR(v_inicio,'HH24:MI') AND HORA_FIN=TO_CHAR(v_fin,'HH24:MI') AND ESTADO='ACTIVO';
 IF v_franja IS NULL THEN
  INSERT INTO FRANJA_HORARIA(HORA_INICIO,HORA_FIN,ESTADO)
  VALUES(TO_CHAR(v_inicio,'HH24:MI'),TO_CHAR(v_fin,'HH24:MI'),'ACTIVO')
  RETURNING ID_FRANJA INTO v_franja;
 END IF;
 BEGIN
  SELECT D.ID_DOCTOR,CO.ID_CONSULTORIO INTO v_doc_asist,v_consultorio
  FROM DOCTOR D CROSS JOIN CONSULTORIO CO
  WHERE D.ESTADO='ACTIVO' AND D.ESTADO_DOCUMENTACION='COMPLETO' AND CO.ESTADO='ACTIVO'
  AND EXISTS(SELECT 1 FROM DOCTOR_ESPECIALIDAD DE JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DE.ID_ESPECIALIDAD
             WHERE DE.ID_DOCTOR=D.ID_DOCTOR AND E.ESTADO='ACTIVO' AND E.PRECIO_CONSULTA>0)
  AND NOT EXISTS(SELECT 1 FROM CITA C JOIN FRANJA_HORARIA F ON F.ID_FRANJA=C.ID_FRANJA
    WHERE C.FECHA_CITA=TRUNC(v_inicio) AND C.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
    AND (C.ID_DOCTOR=D.ID_DOCTOR OR C.ID_CONSULTORIO=CO.ID_CONSULTORIO)
    AND F.HORA_INICIO<TO_CHAR(v_fin,'HH24:MI') AND F.HORA_FIN>TO_CHAR(v_inicio,'HH24:MI'))
  ORDER BY D.ID_DOCTOR,CO.ID_CONSULTORIO FETCH FIRST 1 ROW ONLY;
 EXCEPTION WHEN NO_DATA_FOUND THEN
  RAISE_APPLICATION_ERROR(-20994,'No hay doctor y consultorio libres para el turno de asistencia.');
 END;
 SELECT MIN(DE.ID_ESPECIALIDAD) INTO v_especialidad FROM DOCTOR_ESPECIALIDAD DE
 JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DE.ID_ESPECIALIDAD
 WHERE DE.ID_DOCTOR=v_doc_asist AND E.ESTADO='ACTIVO' AND E.PRECIO_CONSULTA>0;
 SELECT PRECIO_CONSULTA INTO v_precio FROM ESPECIALIDAD WHERE ID_ESPECIALIDAD=v_especialidad;
 cargar(2,v_doc_asist,v_especialidad,TRUNC(v_inicio),v_consultorio,v_franja,v_precio);
 COMMIT;
 DBMS_SESSION.CLEAR_IDENTIFIER;
 DBMS_OUTPUT.PUT_LINE('Escenario de finanzas: cita '||v_cita_fin);
 DBMS_OUTPUT.PUT_LINE('Escenario de asistencia: cita '||v_cita_asist||', turno '||TO_CHAR(v_inicio,'DD/MM/YYYY HH24:MI'));
 DBMS_OUTPUT.PUT_LINE('Ejecutar AHORA el 12 como recepcion.centro y luego el 10 como tesoreria.centro.');
 DBMS_OUTPUT.PUT_LINE('Los datos tecnicos permanecen hasta ejecutar 17 como KARELY_BD2.');
EXCEPTION WHEN OTHERS THEN ROLLBACK; DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/
-- La carga directa de la atencion cerrada prepara el saldo, no prueba el cierre clinico.
-- No crea liquidaciones ni envia correos.

