SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

-- Ejecutar como "auditor.karely" y luego "desarrollo.karely".
DECLARE
 v_usuario VARCHAR2(128):=SYS_CONTEXT('USERENV','SESSION_USER');
 v_denegado BOOLEAN:=FALSE;
BEGIN
 SAVEPOINT prueba_denegacion;
 IF v_usuario NOT IN ('auditor.karely','desarrollo.karely') THEN
  RAISE_APPLICATION_ERROR(-20994,'Probar como auditor o desarrollo.'); END IF;
 BEGIN
  EXECUTE IMMEDIATE 'UPDATE KARELY_BD2.PACIENTE SET ESTADO=ESTADO WHERE 1=0';
 EXCEPTION WHEN OTHERS THEN
  IF SQLCODE IN (-942,-1031) THEN v_denegado:=TRUE; ELSE RAISE; END IF;
 END;
 IF NOT v_denegado THEN RAISE_APPLICATION_ERROR(-20995,'FALLO: permiso UPDATE inesperado.'); END IF;
 DBMS_OUTPUT.PUT_LINE('CORRECTO: UPDATE directo denegado.');
 v_denegado:=FALSE;
 BEGIN
  EXECUTE IMMEDIATE 'DELETE FROM KARELY_BD2.PACIENTE WHERE 1=0';
 EXCEPTION WHEN OTHERS THEN
  IF SQLCODE IN (-942,-1031) THEN v_denegado:=TRUE; ELSE RAISE; END IF;
 END;
 IF NOT v_denegado THEN RAISE_APPLICATION_ERROR(-20995,'FALLO: permiso DELETE inesperado.'); END IF;
 DBMS_OUTPUT.PUT_LINE('CORRECTO: DELETE directo denegado.');
 ROLLBACK TO prueba_denegacion;
EXCEPTION WHEN OTHERS THEN
 ROLLBACK TO prueba_denegacion; RAISE;
END;
/

