-- KARELY_BD2. Backend detenido y sin otras sesiones de escritura.
-- Elimina exclusivamente los dos escenarios de 16.
-- Restaura el estado previo del trigger que protege pagos aprobados.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 v_n NUMBER; v_estado VARCHAR2(8); v_desactivado BOOLEAN:=FALSE;
BEGIN
 IF USER<>'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20994,'Conectarse como KARELY_BD2.'); END IF;
 SELECT COUNT(*) INTO v_n FROM PAGO_CITA PC JOIN PACIENTE P ON P.ID_PACIENTE=PC.ID_PACIENTE
 JOIN CITA C ON C.ID_PAGO=PC.ID_PAGO
 WHERE (PC.REFERENCIA_PAGO='QA-PEND-FINANZAS' AND P.NUMERO_DOCUMENTO='QA-PEND-1'
     OR PC.REFERENCIA_PAGO='QA-PEND-ASISTENCIA' AND P.NUMERO_DOCUMENTO='QA-PEND-2')
 AND P.NOMBRES='Validacion tecnica' AND P.APELLIDOS='Temporal pendientes';
 IF v_n<>2 THEN RAISE_APPLICATION_ERROR(-20994,'No coincide el escenario completo. No se elimino nada.'); END IF;
 SELECT COUNT(*) INTO v_n FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
 WHERE PC.REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA')
 AND (
   (PC.REFERENCIA_PAGO='QA-PEND-ASISTENCIA' AND
     (C.ESTADO<>'PROGRAMADA' OR EXISTS(SELECT 1 FROM ASISTENCIA A WHERE A.ID_CITA=C.ID_CITA)
      OR EXISTS(SELECT 1 FROM ATENCION_MEDICA A WHERE A.ID_CITA=C.ID_CITA)))
   OR (PC.REFERENCIA_PAGO='QA-PEND-FINANZAS' AND
      (C.ESTADO<>'ATENDIDA' OR NOT EXISTS(SELECT 1 FROM ATENCION_MEDICA A
         WHERE A.ID_CITA=C.ID_CITA AND A.ESTADO='CERRADA' AND A.DIAGNOSTICO IS NULL AND A.OBSERVACIONES IS NULL)))
   OR EXISTS(SELECT 1 FROM RECIBO_HONORARIO R WHERE R.ID_CITA=C.ID_CITA)
   OR EXISTS(SELECT 1 FROM ATENCION_MEDICA A JOIN RECETA R ON R.ID_ATENCION=A.ID_ATENCION WHERE A.ID_CITA=C.ID_CITA)
   OR EXISTS(SELECT 1 FROM REPROGRAMACION_CITA R WHERE R.ID_CITA=C.ID_CITA)
 );
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20994,'Hay cambios persistidos en el escenario. Revisar antes de limpiar.'); END IF;
 SELECT STATUS INTO v_estado FROM USER_TRIGGERS WHERE TRIGGER_NAME='TR_NO_EDITAR_PAGO_APROBADO';
 IF v_estado='ENABLED' THEN
  EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO DISABLE'; v_desactivado:=TRUE;
 END IF;
 DELETE FROM NOTIFICACION_SALIENTE WHERE ID_CITA IN (
  SELECT C.ID_CITA FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
  WHERE PC.REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA'));
 DELETE FROM ATENCION_MEDICA WHERE ID_CITA IN (
  SELECT C.ID_CITA FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
  WHERE PC.REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA'));
 DELETE FROM ASISTENCIA WHERE ID_CITA IN (
  SELECT C.ID_CITA FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
  WHERE PC.REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA'));
 DELETE FROM CITA WHERE ID_PAGO IN (
  SELECT ID_PAGO FROM PAGO_CITA WHERE REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA'));
 DELETE FROM PAGO_CITA WHERE REFERENCIA_PAGO IN ('QA-PEND-FINANZAS','QA-PEND-ASISTENCIA');
 DELETE FROM PRE_RESERVA_CITA PR WHERE ID_PACIENTE IN (
  SELECT ID_PACIENTE FROM PACIENTE WHERE NUMERO_DOCUMENTO IN ('QA-PEND-1','QA-PEND-2')
  AND NOMBRES='Validacion tecnica' AND APELLIDOS='Temporal pendientes')
 AND NOT EXISTS(SELECT 1 FROM PAGO_CITA PC WHERE PC.ID_PRE_RESERVA=PR.ID_PRE_RESERVA);
 DELETE FROM PACIENTE WHERE NUMERO_DOCUMENTO IN ('QA-PEND-1','QA-PEND-2')
 AND NOMBRES='Validacion tecnica' AND APELLIDOS='Temporal pendientes';
 COMMIT;
 IF v_desactivado THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE'; v_desactivado:=FALSE; END IF;
 DBMS_OUTPUT.PUT_LINE('Escenarios financieros y de asistencia eliminados; auditoria y franja conservadas.');
EXCEPTION WHEN OTHERS THEN
 ROLLBACK;
 IF v_desactivado THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE'; END IF;
 RAISE;
END;
/

