-- KARELY_BD2. Escenario TECNICO para 09 y 13: crea dos pacientes y dos citas abiertas.
-- Preferir copia de pruebas. Detener el backend durante preparacion, prueba y limpieza.
-- COMMIT necesario para consultar desde las conexiones Oracle del doctor.
SET DEFINE OFF
SET SERVEROUTPUT ON
PROMPT PREPARAR_CITAS_V3_TURNOS_LIBRES
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 v_admin NUMBER; v_doctor NUMBER; v_especialidad NUMBER; v_consultorio NUMBER;
 v_franja NUMBER; v_paciente NUMBER; v_reserva NUMBER; v_pago NUMBER; v_cita NUMBER;
 v_precio NUMBER; v_total NUMBER;
 v_cita_propia NUMBER; v_cita_ajena NUMBER;
BEGIN
 IF USER<>'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20994,'Conectarse como KARELY_BD2.'); END IF;
 SELECT COUNT(*) INTO v_total FROM PAGO_CITA WHERE REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA');
 IF v_total>0 THEN RAISE_APPLICATION_ERROR(-20994,'Ya existe este escenario. Consultar sus citas o limpiar con 15.'); END IF;
 SELECT U.ID_USUARIO INTO v_admin FROM USUARIO U JOIN ROL R ON R.ID_ROL=U.ID_ROL
 WHERE U.USERNAME='admin01' AND U.ESTADO='ACTIVO' AND R.NOMBRE='ADMINISTRADORA';
 DBMS_SESSION.SET_IDENTIFIER(TO_CHAR(v_admin));
 FOR i IN 1..2 LOOP
  IF i=1 THEN
   SELECT D.ID_DOCTOR INTO v_doctor FROM DOCTOR D JOIN USUARIO U ON U.ID_USUARIO=D.ID_USUARIO
   WHERE U.USERNAME='dr.marcos.salas' AND D.ESTADO='ACTIVO' AND U.ESTADO='ACTIVO';
  ELSE
   SELECT MIN(D.ID_DOCTOR) INTO v_doctor FROM DOCTOR D JOIN USUARIO U ON U.ID_USUARIO=D.ID_USUARIO
   WHERE U.USERNAME<>'dr.marcos.salas' AND D.ESTADO='ACTIVO' AND U.ESTADO='ACTIVO';
  END IF;
  IF v_doctor IS NULL THEN RAISE_APPLICATION_ERROR(-20994,'Se necesitan Marcos y otro doctor activo.'); END IF;
  -- Buscar nuevamente en cada iteracion: incluye la primera cita aun sin COMMIT.
  BEGIN
   SELECT CO.ID_CONSULTORIO,F.ID_FRANJA INTO v_consultorio,v_franja
   FROM CONSULTORIO CO CROSS JOIN FRANJA_HORARIA F
   WHERE CO.ESTADO='ACTIVO' AND F.ESTADO='ACTIVO'
   AND NOT EXISTS (
    SELECT 1 FROM CITA C WHERE C.FECHA_CITA=TRUNC(SYSDATE)
    AND C.ID_FRANJA=F.ID_FRANJA
    AND C.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
    AND (C.ID_CONSULTORIO=CO.ID_CONSULTORIO OR C.ID_DOCTOR=v_doctor)
   )
   ORDER BY F.HORA_INICIO,CO.ID_CONSULTORIO,F.ID_FRANJA
   FETCH FIRST 1 ROW ONLY;
  EXCEPTION WHEN NO_DATA_FOUND THEN
   RAISE_APPLICATION_ERROR(-20994,'No hay consultorio y turno libres hoy para el doctor '||v_doctor);
  END;
  SELECT MIN(DE.ID_ESPECIALIDAD) INTO v_especialidad FROM DOCTOR_ESPECIALIDAD DE
  JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DE.ID_ESPECIALIDAD
  WHERE DE.ID_DOCTOR=v_doctor AND E.ESTADO='ACTIVO' AND E.PRECIO_CONSULTA>0;
  IF v_especialidad IS NULL THEN RAISE_APPLICATION_ERROR(-20994,'El doctor requiere especialidad activa con precio positivo.'); END IF;
  SELECT PRECIO_CONSULTA INTO v_precio FROM ESPECIALIDAD WHERE ID_ESPECIALIDAD=v_especialidad;
  INSERT INTO PACIENTE(TIPO_DOCUMENTO,NUMERO_DOCUMENTO,NOMBRES,APELLIDOS,ESTADO)
  VALUES('OTRO','QA-ROLES-'||i,'Validacion tecnica','Temporal roles','ACTIVO')
  RETURNING ID_PACIENTE INTO v_paciente;
  INSERT INTO PRE_RESERVA_CITA(ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,ID_FRANJA,
   FECHA_CITA,MONTO,FECHA_EXPIRACION,ESTADO)
  VALUES(v_paciente,v_doctor,v_especialidad,v_consultorio,v_franja,TRUNC(SYSDATE),v_precio,
   SYSTIMESTAMP+INTERVAL '10' MINUTE,'CONFIRMADA') RETURNING ID_PRE_RESERVA INTO v_reserva;
  INSERT INTO PAGO_CITA(ID_PRE_RESERVA,ID_PACIENTE,MONTO,METODO_PAGO,REFERENCIA_PAGO,ESTADO)
  VALUES(v_reserva,v_paciente,v_precio,'EFECTIVO',
   CASE WHEN i=1 THEN 'QA-ROLES-PROPIA' ELSE 'QA-ROLES-AJENA' END,'APROBADO')
  RETURNING ID_PAGO INTO v_pago;
  INSERT INTO CITA(ID_PRE_RESERVA,ID_PACIENTE,ID_DOCTOR,ID_ESPECIALIDAD,ID_CONSULTORIO,ID_FRANJA,
   ID_PAGO,FECHA_CITA,MONTO_TOTAL,ESTADO)
  VALUES(v_reserva,v_paciente,v_doctor,v_especialidad,v_consultorio,v_franja,v_pago,
   TRUNC(SYSDATE),v_precio,'EN_ATENCION') RETURNING ID_CITA INTO v_cita;
  INSERT INTO ASISTENCIA(ID_CITA,ESTADO) VALUES(v_cita,'PRESENTE');
  INSERT INTO ATENCION_MEDICA(ID_CITA,ID_DOCTOR,ESTADO) VALUES(v_cita,v_doctor,'ABIERTA');
  IF i=1 THEN v_cita_propia:=v_cita; ELSE v_cita_ajena:=v_cita; END IF;
 END LOOP;
 COMMIT;
 DBMS_SESSION.CLEAR_IDENTIFIER;
 DBMS_OUTPUT.PUT_LINE('CITA PROPIA PARA EL 09: '||v_cita_propia);
 DBMS_OUTPUT.PUT_LINE('CITA AJENA: INTRODUCIR ESTE ID EN EL 13: '||v_cita_ajena);
 DBMS_OUTPUT.PUT_LINE('Ejecutar 09 y 13 como dr.marcos.salas. Despues limpiar con 15.');
EXCEPTION WHEN OTHERS THEN ROLLBACK; DBMS_SESSION.CLEAR_IDENTIFIER; RAISE;
END;
/
