-- SYSTEM, misma PDB que KARELY_BD2. Ejecutar completo con F5.
-- Usuarios nuevos: claves Oracle independientes de las claves del login web.
SET SERVEROUTPUT ON
SET DEFINE ON
SET VERIFY OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 v_n NUMBER;
BEGIN
 IF SYS_CONTEXT('USERENV','CON_NAME')='CDB$ROOT' THEN
  RAISE_APPLICATION_ERROR(-20980,'Conectarse a la PDB del proyecto.');
 END IF;
 SELECT COUNT(*) INTO v_n FROM DBA_USERS WHERE USERNAME='KARELY_BD2';
 IF v_n<>1 THEN RAISE_APPLICATION_ERROR(-20981,'No existe KARELY_BD2 en esta PDB.'); END IF;
 SELECT COUNT(*) INTO v_n FROM DBA_USERS WHERE USERNAME IN ('admin01','dr.marcos.salas','recepcion.centro','tesoreria.centro','auditor.karely','desarrollo.karely');
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20982,'Ya existe una cuenta de este instalador. Revisar DBA_USERS antes de continuar.'); END IF;
 SELECT COUNT(*) INTO v_n FROM DBA_ROLES WHERE ROLE IN ('KARELY_R_ADMIN','KARELY_R_DOCTOR','KARELY_R_RECEPCION','KARELY_R_TESORERIA','KARELY_R_AUDITOR','KARELY_R_DESARROLLO');
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20983,'Ya existe un rol de este instalador. Revisar DBA_ROLES.'); END IF;
END;
/
CREATE ROLE KARELY_R_ADMIN;
GRANT CREATE SESSION TO KARELY_R_ADMIN;
CREATE ROLE KARELY_R_DOCTOR;
GRANT CREATE SESSION TO KARELY_R_DOCTOR;
CREATE ROLE KARELY_R_RECEPCION;
