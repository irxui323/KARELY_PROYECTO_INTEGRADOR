DECLARE v_n NUMBER;
BEGIN
 IF SYS_CONTEXT('USERENV','CON_NAME')='CDB$ROOT' THEN
  RAISE_APPLICATION_ERROR(-20980,'Conectarse a la PDB del proyecto.');
 END IF;
 SELECT COUNT(*) INTO v_n FROM DBA_VIEWS WHERE OWNER='KARELY_BD2'
 AND VIEW_NAME IN ('V_S_RD_DOCTOR','V_S_RD_CITA','V_S_RD_PACIENTE','V_S_RD_PAGO','V_S_RD_USUARIO');
 IF v_n<>5 THEN RAISE_APPLICATION_ERROR(-20988,'Ejecutar primero el archivo 02 como KARELY_BD2.'); END IF;
END;
/

DECLARE v_n NUMBER;
BEGIN
 SELECT COUNT(*) INTO v_n FROM REDACTION_POLICIES
 WHERE OBJECT_OWNER='KARELY_BD2' AND OBJECT_NAME='V_S_RD_DOCTOR';
 IF v_n=0 THEN
  DBMS_REDACT.ADD_POLICY(
   object_schema=>'KARELY_BD2',object_name=>'V_S_RD_DOCTOR',
   policy_name=>'DMSK_KARELY_DOCTOR',column_name=>'CORREO',
   function_type=>DBMS_REDACT.FULL,
   expression=>'SYS_CONTEXT(''SYS_SESSION_ROLES'',''KARELY_R_ADMIN'') = ''FALSE'' AND SYS_CONTEXT(''USERENV'',''SESSION_USER'') <> ''KARELY_BD2'''
  );
 ELSE
  SELECT COUNT(*) INTO v_n FROM REDACTION_POLICIES
  WHERE OBJECT_OWNER='KARELY_BD2' AND OBJECT_NAME='V_S_RD_DOCTOR'
  AND POLICY_NAME='DMSK_KARELY_DOCTOR' AND ENABLE='YES';
  IF v_n<>1 THEN RAISE_APPLICATION_ERROR(-20989,'Politica existente distinta o desactivada en V_S_RD_DOCTOR. Revisar antes de continuar.'); END IF;
 END IF;
END;
