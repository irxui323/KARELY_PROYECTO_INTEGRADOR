-- KARELY_BD2. Detener backend y otras sesiones que escriban durante la limpieza.
-- Elimina SOLO el escenario QA-ROLES creado por 14.
-- Deshabilita brevemente el trigger de inmutabilidad de pagos y restaura su estado.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
DECLARE
 v_estado VARCHAR2(8); v_desactivado BOOLEAN:=FALSE; v_n NUMBER;
BEGIN
 IF USER<>'KARELY_BD2' THEN RAISE_APPLICATION_ERROR(-20994,'Conectarse como KARELY_BD2.'); END IF;
 SELECT COUNT(*) INTO v_n FROM PAGO_CITA PC JOIN PACIENTE P ON P.ID_PACIENTE=PC.ID_PACIENTE
 WHERE PC.REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA')
 AND P.NUMERO_DOCUMENTO IN ('QA-ROLES-1','QA-ROLES-2')
 AND P.NOMBRES='Validacion tecnica' AND P.APELLIDOS='Temporal roles';
 IF v_n<>2 THEN RAISE_APPLICATION_ERROR(-20994,'No coincide el escenario completo de dos pagos. No se borro nada.'); END IF;
 SELECT COUNT(*) INTO v_n FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
 JOIN ATENCION_MEDICA A ON A.ID_CITA=C.ID_CITA
 WHERE PC.REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA')
 AND (C.ESTADO<>'EN_ATENCION' OR A.ESTADO<>'ABIERTA' OR A.DIAGNOSTICO IS NOT NULL
 OR A.OBSERVACIONES IS NOT NULL
 OR EXISTS(SELECT 1 FROM RECETA R WHERE R.ID_ATENCION=A.ID_ATENCION)
 OR EXISTS(SELECT 1 FROM RECIBO_HONORARIO RH WHERE RH.ID_CITA=C.ID_CITA));
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20994,'El escenario tiene cambios persistidos. Revisarlos antes de limpiar.'); END IF;
 SELECT STATUS INTO v_estado FROM USER_TRIGGERS WHERE TRIGGER_NAME='TR_NO_EDITAR_PAGO_APROBADO';
 IF v_estado='ENABLED' THEN
  EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO DISABLE';
  v_desactivado:=TRUE;
 END IF;
 DELETE FROM NOTIFICACION_SALIENTE WHERE ID_CITA IN (
  SELECT C.ID_CITA FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
  WHERE PC.REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA'));
 DELETE FROM ATENCION_MEDICA WHERE ID_CITA IN (
  SELECT C.ID_CITA FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
  WHERE PC.REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA'));
 DELETE FROM ASISTENCIA WHERE ID_CITA IN (
  SELECT C.ID_CITA FROM CITA C JOIN PAGO_CITA PC ON PC.ID_PAGO=C.ID_PAGO
  WHERE PC.REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA'));
 DELETE FROM CITA WHERE ID_PAGO IN (
  SELECT ID_PAGO FROM PAGO_CITA WHERE REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA'));
 DELETE FROM PAGO_CITA WHERE REFERENCIA_PAGO IN ('QA-ROLES-PROPIA','QA-ROLES-AJENA');
 DELETE FROM PRE_RESERVA_CITA PR WHERE ID_PACIENTE IN (
  SELECT ID_PACIENTE FROM PACIENTE WHERE NUMERO_DOCUMENTO IN ('QA-ROLES-1','QA-ROLES-2')
  AND NOMBRES='Validacion tecnica' AND APELLIDOS='Temporal roles')
 AND NOT EXISTS (SELECT 1 FROM PAGO_CITA PC WHERE PC.ID_PRE_RESERVA=PR.ID_PRE_RESERVA);
 DELETE FROM PACIENTE WHERE NUMERO_DOCUMENTO IN ('QA-ROLES-1','QA-ROLES-2')
 AND NOMBRES='Validacion tecnica' AND APELLIDOS='Temporal roles';
 COMMIT;
 IF v_desactivado THEN
  EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE'; v_desactivado:=FALSE;
 END IF;
 DBMS_OUTPUT.PUT_LINE('Escenario eliminado. Auditoria y franja horaria conservadas.');
EXCEPTION WHEN OTHERS THEN
 ROLLBACK;
 IF v_desactivado THEN EXECUTE IMMEDIATE 'ALTER TRIGGER TR_NO_EDITAR_PAGO_APROBADO ENABLE'; END IF;
 RAISE;
END;
/

