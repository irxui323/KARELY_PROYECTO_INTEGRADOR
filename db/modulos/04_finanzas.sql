-- Procedimientos: SP_PAGAR_DOCTOR, SP_GENERAR_LIQUIDACION, SP_EMITIR_RECIBO.
-- Funciones: FN_MONTO_DOCTOR, FN_SALDO_DOCTOR (tambien FN_SALDO_LIQUIDACION).
-- Triggers: TR_AUD_PAGO_CITA, TR_AUD_LIQUIDACION (tambien protecciones de inmutabilidad).
-- Vistas: VW_PAGOS_CITA, VW_INGRESOS_GESTORA, VW_SALDOS_LIQUIDACIONES.
-- Particionamiento: LIQUIDACION (HASH).
CREATE OR REPLACE VIEW V_S_PAGO_ENMASCARADO AS
SELECT PC.ID_PAGO,PC.FECHA_PAGO,PC.MONTO,PC.METODO_PAGO,PC.ESTADO,
       CASE WHEN LENGTH(P.NUMERO_DOCUMENTO)>4 THEN
           RPAD('*',LENGTH(P.NUMERO_DOCUMENTO)-2,'*') || SUBSTR(P.NUMERO_DOCUMENTO,-2)
           ELSE '****' END AS DOCUMENTO_ENMASCARADO,
       CASE WHEN PC.REFERENCIA_PAGO IS NOT NULL THEN '***' END AS REFERENCIA_ENMASCARADA
FROM PAGO_CITA PC JOIN PACIENTE P ON P.ID_PACIENTE=PC.ID_PACIENTE;

