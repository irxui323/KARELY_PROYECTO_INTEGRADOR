-- Funciones: FN_EDAD_PACIENTE, FN_TOTAL_ATENCIONES_PACIENTE.
-- Triggers: TR_AUD_PACIENTE_DATOS, TR_AUD_ATENCION_ESTADO.
-- Particionamiento: PACIENTE (HASH). Enmascaramiento: V_S_PACIENTE_ENMASCARADO.
CREATE OR REPLACE FUNCTION FN_TOTAL_ATENCIONES_PACIENTE(p_id_paciente NUMBER)
RETURN NUMBER IS v_total NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total FROM ATENCION_MEDICA A
    JOIN CITA C ON C.ID_CITA=A.ID_CITA
    WHERE C.ID_PACIENTE=p_id_paciente AND A.ESTADO='CERRADA';
    RETURN v_total;
END;
/
CREATE OR REPLACE VIEW V_S_HISTORIAL_PACIENTE AS
SELECT C.ID_PACIENTE,C.ID_CITA,C.FECHA_CITA,E.NOMBRE AS ESPECIALIDAD,
       A.FECHA_INICIO,A.FECHA_CIERRE,A.ESTADO AS ESTADO_ATENCION
FROM CITA C JOIN ATENCION_MEDICA A ON A.ID_CITA=C.ID_CITA
JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=C.ID_ESPECIALIDAD;

CREATE OR REPLACE VIEW V_S_RECETAS_PACIENTE AS
SELECT C.ID_PACIENTE,C.ID_CITA,R.ID_RECETA,R.FECHA_EMISION,
       COUNT(RD.ID_DETALLE) AS TOTAL_MEDICAMENTOS
FROM CITA C JOIN ATENCION_MEDICA A ON A.ID_CITA=C.ID_CITA
JOIN RECETA R ON R.ID_ATENCION=A.ID_ATENCION
LEFT JOIN RECETA_DETALLE RD ON RD.ID_RECETA=R.ID_RECETA
GROUP BY C.ID_PACIENTE,C.ID_CITA,R.ID_RECETA,R.FECHA_EMISION;

CREATE OR REPLACE TRIGGER TR_AUD_ATENCION_ESTADO
AFTER UPDATE OF ESTADO ON ATENCION_MEDICA
BEGIN
    INSERT INTO AUDITORIA(TABLA_AFECTADA, ACCION, DETALLE, ORIGEN)
    VALUES ('ATENCION_MEDICA', 'MODIFICAR',
        'Cambio registrado. Sesion Oracle: ' || SYS_CONTEXT('USERENV','SESSION_USER')
        || '. Actor aplicacion: ' || SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'), 'SISTEMA');
END;
