SELECT R.MODULO,R.TIPO,COUNT(*) AS ESPERADOS,
       SUM(CASE WHEN O.STATUS='VALID' THEN 1 ELSE 0 END) AS VALIDOS,
       CASE WHEN SUM(CASE WHEN O.STATUS='VALID' THEN 1 ELSE 0 END)=COUNT(*)
       THEN 'CUMPLE' ELSE 'REVISAR' END AS RESULTADO
FROM REQUERIDOS R LEFT JOIN USER_OBJECTS O ON O.OBJECT_NAME=R.NOMBRE AND O.OBJECT_TYPE=R.TIPO
GROUP BY R.MODULO,R.TIPO ORDER BY R.MODULO,R.TIPO;

