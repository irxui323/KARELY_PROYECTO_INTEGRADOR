-- Procedimientos: SP_REGISTRAR_ASISTENCIA, SP_CREAR_USUARIO, SP_CERRAR_SESION.
-- Funciones: FN_ROL_USUARIO, FN_SESIONES_ACTIVAS_USUARIO.
-- Triggers: TR_AUD_USUARIO_DATOS, TR_AUD_SESION_ESTADO.
-- Particionamiento: SESION_USUARIO (RANGE/INTERVAL).
-- Enmascaramiento: V_S_USUARIO_ENMASCARADO.
CREATE OR REPLACE FUNCTION FN_SESIONES_ACTIVAS_USUARIO(p_id_usuario NUMBER)
RETURN NUMBER IS v_total NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total FROM SESION_USUARIO
    WHERE ID_USUARIO=p_id_usuario AND ESTADO='ACTIVA';
    RETURN v_total;
END;
/
CREATE OR REPLACE VIEW V_S_RECEPCION_ASISTENCIA AS
SELECT C.ID_CITA,C.FECHA_CITA,F.HORA_INICIO,C.ESTADO AS ESTADO_CITA,
       CASE WHEN A.ID_ASISTENCIA IS NULL THEN 'PENDIENTE' ELSE 'PRESENTE' END AS ASISTENCIA,
       A.FECHA_REGISTRO
FROM CITA C JOIN FRANJA_HORARIA F ON F.ID_FRANJA=C.ID_FRANJA
LEFT JOIN ASISTENCIA A ON A.ID_CITA=C.ID_CITA;

CREATE OR REPLACE VIEW V_S_SEGURIDAD_SESIONES AS
SELECT U.ID_USUARIO,U.USERNAME,U.ESTADO,
       COUNT(S.ID_SESION) AS SESIONES_REGISTRADAS,
       SUM(CASE WHEN S.ESTADO='ACTIVA' THEN 1 ELSE 0 END) AS SESIONES_ACTIVAS
FROM USUARIO U LEFT JOIN SESION_USUARIO S ON S.ID_USUARIO=U.ID_USUARIO
GROUP BY U.ID_USUARIO,U.USERNAME,U.ESTADO;

CREATE OR REPLACE TRIGGER TR_AUD_SESION_ESTADO
AFTER UPDATE OF ESTADO ON SESION_USUARIO
BEGIN
    INSERT INTO AUDITORIA(TABLA_AFECTADA, ACCION, DETALLE, ORIGEN)
    VALUES ('SESION_USUARIO', 'MODIFICAR',
        'Cambio registrado. Sesion Oracle: ' || SYS_CONTEXT('USERENV','SESSION_USER')
        || '. Actor aplicacion: ' || SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'), 'SISTEMA');
END;
/

