-- Existentes: SP_VALIDAR_DOCUMENTACION, SP_REGISTRAR_DISPONIBILIDAD.
-- Funciones: FN_DOCUMENTACION_COMPLETA + FN_TOTAL_ESPECIALIDADES.
-- Triggers: TR_DOCUMENTO_REVALIDACION, TR_DOCTOR_ESTADO_VALIDADO.
-- Particionamiento: DOCTOR (HASH). Enmascaramiento: V_S_DOCTOR_ENMASCARADO.
CREATE OR REPLACE FUNCTION FN_TOTAL_ESPECIALIDADES(p_id_doctor NUMBER)
RETURN NUMBER IS v_total NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total FROM DOCTOR_ESPECIALIDAD WHERE ID_DOCTOR=p_id_doctor;
    RETURN v_total;
END;
/
CREATE OR REPLACE VIEW V_S_DOCUMENTACION_DOCTOR AS
SELECT D.ID_DOCTOR, D.ESTADO_DOCUMENTACION,
       COUNT(DD.ID_DOCUMENTO) AS DOCUMENTOS,
       SUM(CASE WHEN DD.ESTADO='VALIDADO' THEN 1 ELSE 0 END) AS VALIDADOS
FROM DOCTOR D LEFT JOIN DOCUMENTO_DOCTOR DD ON DD.ID_DOCTOR=D.ID_DOCTOR
GROUP BY D.ID_DOCTOR, D.ESTADO_DOCUMENTACION;

CREATE OR REPLACE VIEW V_S_HORARIOS_DOCTOR AS
SELECT DD.ID_DOCTOR, DD.FECHA_TURNO, E.NOMBRE AS ESPECIALIDAD,
       F.HORA_INICIO, F.HORA_FIN, DD.ESTADO
FROM DISPONIBILIDAD_DOCTOR DD
JOIN ESPECIALIDAD E ON E.ID_ESPECIALIDAD=DD.ID_ESPECIALIDAD
JOIN FRANJA_HORARIA F ON F.ID_FRANJA=DD.ID_FRANJA;

CREATE OR REPLACE PROCEDURE SP_CONSULTAR_HORARIOS_DOCTOR(
    p_id_doctor NUMBER, p_desde DATE, p_hasta DATE, p_resultado OUT SYS_REFCURSOR
) IS
BEGIN
    IF p_desde IS NULL OR p_hasta IS NULL OR TRUNC(p_hasta)<TRUNC(p_desde) THEN
        RAISE_APPLICATION_ERROR(-20972,'Periodo de consulta invalido.');
    END IF;
    OPEN p_resultado FOR SELECT * FROM V_S_HORARIOS_DOCTOR
    WHERE ID_DOCTOR=p_id_doctor AND FECHA_TURNO BETWEEN TRUNC(p_desde) AND TRUNC(p_hasta)
    ORDER BY FECHA_TURNO,HORA_INICIO;
END;
/
CREATE OR REPLACE TRIGGER TR_AUD_DOCTOR_ESTADO
AFTER UPDATE OF ESTADO, ESTADO_DOCUMENTACION ON DOCTOR
BEGIN
    INSERT INTO AUDITORIA(TABLA_AFECTADA, ACCION, DETALLE, ORIGEN)
    VALUES ('DOCTOR', 'MODIFICAR',
        'Cambio registrado. Sesion Oracle: ' || SYS_CONTEXT('USERENV','SESSION_USER')
        || '. Actor aplicacion: ' || SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER'), 'SISTEMA');
END;
