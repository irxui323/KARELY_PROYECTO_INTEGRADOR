-- 21.4. MODIFICAR PARAMETRO DEL NEGOCIO
-----------------------------------
-- Cuando cambia una comision se ajusta automaticamente
-- su contraparte para conservar la suma en 100.
-- AUDITORIA conserva el antes/despues; no hay HISTORIAL_PARAMETRO.
CREATE OR REPLACE PROCEDURE SP_CAMBIAR_PARAMETRO (
    P_ID_ADMIN    IN USUARIO.ID_USUARIO%TYPE,
    P_NOMBRE      IN PARAMETRO_SISTEMA.NOMBRE%TYPE,
    P_VALOR_NUEVO IN PARAMETRO_SISTEMA.VALOR%TYPE
)
IS
    V_NOMBRE PARAMETRO_SISTEMA.NOMBRE%TYPE := UPPER(TRIM(P_NOMBRE));
    V_TEXTO VARCHAR2(1000) := TRIM(P_VALOR_NUEVO);
    V_NUMERO NUMBER;
    V_OTRO_NUMERO NUMBER;
    V_ID_1 PARAMETRO_SISTEMA.ID_PARAMETRO%TYPE;
    V_ID_2 PARAMETRO_SISTEMA.ID_PARAMETRO%TYPE;
    V_ANTERIOR_1 PARAMETRO_SISTEMA.VALOR%TYPE;
    V_ANTERIOR_2 PARAMETRO_SISTEMA.VALOR%TYPE;
    V_ESTADO_1 PARAMETRO_SISTEMA.ESTADO%TYPE;
    V_ESTADO_2 PARAMETRO_SISTEMA.ESTADO%TYPE;
    V_NUEVO_1 PARAMETRO_SISTEMA.VALOR%TYPE;
    V_NUEVO_2 PARAMETRO_SISTEMA.VALOR%TYPE;
BEGIN
    SAVEPOINT SV_CAMBIAR_PARAMETRO;

    IF P_ID_ADMIN IS NULL OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') IS NULL
       OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_ADMIN) THEN
        RAISE_APPLICATION_ERROR(-20628,'Identidad de sesion no coincide.');
    END IF;
    IF FN_ROL_USUARIO(P_ID_ADMIN) <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20618,
            'Solo administracion puede modificar parametros.');
    END IF;

    IF V_NOMBRE NOT IN ('COMISION_DOCTOR','COMISION_GESTORA',
                         'BLOQUEO_MINUTOS','SESION_MINUTOS')
       OR V_NOMBRE IS NULL THEN
        RAISE_APPLICATION_ERROR(-20619,'Parametro no autorizado.');
    END IF;

    IF V_NOMBRE IN ('COMISION_DOCTOR','COMISION_GESTORA') THEN
        IF V_TEXTO IS NULL OR NOT REGEXP_LIKE(
            V_TEXTO,'^([0-9]{1,2}|100)(\.[0-9]{1,2})?$') THEN
            RAISE_APPLICATION_ERROR(-20620,
                'La comision debe estar entre 0 y 100, con hasta 2 decimales.');
        END IF;

        V_NUMERO := TO_NUMBER(V_TEXTO,'999D99',
            'NLS_NUMERIC_CHARACTERS = ''.,''');
        IF V_NUMERO < 0 OR V_NUMERO > 100 THEN
            RAISE_APPLICATION_ERROR(-20620,'Comision fuera del rango 0 a 100.');
        END IF;

        -- Ambos parametros se bloquean SIEMPRE en el mismo orden.
        SELECT ID_PARAMETRO,VALOR,ESTADO
        INTO V_ID_1,V_ANTERIOR_1,V_ESTADO_1
        FROM PARAMETRO_SISTEMA
        WHERE NOMBRE = 'COMISION_DOCTOR' FOR UPDATE;

        SELECT ID_PARAMETRO,VALOR,ESTADO
        INTO V_ID_2,V_ANTERIOR_2,V_ESTADO_2
        FROM PARAMETRO_SISTEMA
        WHERE NOMBRE = 'COMISION_GESTORA' FOR UPDATE;

        IF V_ESTADO_1 <> 'ACTIVO' OR V_ESTADO_2 <> 'ACTIVO' THEN
            RAISE_APPLICATION_ERROR(-20621,'Comisiones inactivas.');
        END IF;

        IF V_NOMBRE = 'COMISION_DOCTOR' THEN
            V_NUEVO_1 := TO_CHAR(V_NUMERO,'FM990D00',
                'NLS_NUMERIC_CHARACTERS = ''.,''');
            V_OTRO_NUMERO := 100 - V_NUMERO;
            V_NUEVO_2 := TO_CHAR(V_OTRO_NUMERO,'FM990D00',
                'NLS_NUMERIC_CHARACTERS = ''.,''');
        ELSE
            V_NUEVO_2 := TO_CHAR(V_NUMERO,'FM990D00',
                'NLS_NUMERIC_CHARACTERS = ''.,''');
            V_OTRO_NUMERO := 100 - V_NUMERO;
            V_NUEVO_1 := TO_CHAR(V_OTRO_NUMERO,'FM990D00',
                'NLS_NUMERIC_CHARACTERS = ''.,''');
        END IF;

        IF TO_NUMBER(V_ANTERIOR_1,'999D99',
              'NLS_NUMERIC_CHARACTERS = ''.,''') =
           TO_NUMBER(V_NUEVO_1,'999D99',
              'NLS_NUMERIC_CHARACTERS = ''.,''') AND
           TO_NUMBER(V_ANTERIOR_2,'999D99',
              'NLS_NUMERIC_CHARACTERS = ''.,''') =
           TO_NUMBER(V_NUEVO_2,'999D99',
              'NLS_NUMERIC_CHARACTERS = ''.,''') THEN
            RAISE_APPLICATION_ERROR(-20622,'No hay cambio en las comisiones.');
        END IF;

        UPDATE PARAMETRO_SISTEMA SET VALOR = V_NUEVO_1
        WHERE ID_PARAMETRO = V_ID_1;
        UPDATE PARAMETRO_SISTEMA SET VALOR = V_NUEVO_2
        WHERE ID_PARAMETRO = V_ID_2;
    ELSE
        -- Configuracion de expiracion de reservas y sesiones.
        IF V_TEXTO IS NULL OR NOT REGEXP_LIKE(V_TEXTO,'^[0-9]{1,3}$') THEN
            RAISE_APPLICATION_ERROR(-20623,'Debe ingresar minutos enteros.');
        END IF;

        V_NUMERO := TO_NUMBER(V_TEXTO);
        IF (V_NOMBRE = 'BLOQUEO_MINUTOS' AND
                (V_NUMERO < 1 OR V_NUMERO > 10)) OR
           (V_NOMBRE = 'SESION_MINUTOS' AND
                (V_NUMERO < 1 OR V_NUMERO > 240)) THEN
            RAISE_APPLICATION_ERROR(-20624,'Minutos fuera del rango permitido.');
        END IF;

        SELECT ID_PARAMETRO,VALOR,ESTADO
        INTO V_ID_1,V_ANTERIOR_1,V_ESTADO_1
        FROM PARAMETRO_SISTEMA
        WHERE NOMBRE = V_NOMBRE FOR UPDATE;

        IF V_ESTADO_1 <> 'ACTIVO' THEN
            RAISE_APPLICATION_ERROR(-20625,'Parametro inactivo.');
        END IF;

        V_NUEVO_1 := TO_CHAR(V_NUMERO);
        IF V_ANTERIOR_1 = V_NUEVO_1 THEN
            RAISE_APPLICATION_ERROR(-20626,'El parametro ya tiene ese valor.');
        END IF;

        UPDATE PARAMETRO_SISTEMA
        SET VALOR = V_NUEVO_1
        WHERE ID_PARAMETRO = V_ID_1;
    END IF;

    DBMS_OUTPUT.PUT_LINE('Parametro actualizado: ' || V_NOMBRE);
    DBMS_OUTPUT.PUT_LINE('COMMIT pendiente.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_CAMBIAR_PARAMETRO;
        RAISE_APPLICATION_ERROR(-20627,'Falta un parametro configurado.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_CAMBIAR_PARAMETRO;
        RAISE;
END SP_CAMBIAR_PARAMETRO;
/
SHOW ERRORS PROCEDURE SP_CAMBIAR_PARAMETRO;

