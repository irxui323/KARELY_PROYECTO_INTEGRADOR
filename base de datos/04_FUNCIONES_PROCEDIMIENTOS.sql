CREATE OR REPLACE PROCEDURE SP_CERRAR_SESION (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_SESION  IN SESION_USUARIO.ID_SESION%TYPE
)
IS
    V_ROL ROL.NOMBRE%TYPE;
    V_DUENO SESION_USUARIO.ID_USUARIO%TYPE;
    V_ESTADO SESION_USUARIO.ESTADO%TYPE;
BEGIN
    SAVEPOINT SV_CERRAR_SESION;
