-- 21.3. ACTIVAR, INACTIVAR O BLOQUEAR
-----------------------------------
CREATE OR REPLACE PROCEDURE SP_CAMBIAR_ESTADO_USUARIO (
    P_ID_ADMIN    IN USUARIO.ID_USUARIO%TYPE,
    P_ID_USUARIO  IN USUARIO.ID_USUARIO%TYPE,
    P_ESTADO      IN USUARIO.ESTADO%TYPE
)
IS
    V_ID_ADMIN_ROL ROL.ID_ROL%TYPE;
    V_ROL USUARIO.ID_ROL%TYPE;
    V_ESTADO_ANTERIOR USUARIO.ESTADO%TYPE;
    V_CANTIDAD NUMBER;
    V_NUEVO_ESTADO USUARIO.ESTADO%TYPE := UPPER(TRIM(P_ESTADO));
BEGIN
    SAVEPOINT SV_ESTADO_USUARIO;

    IF FN_ROL_USUARIO(P_ID_ADMIN) <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20612,'Solo administracion puede cambiar estados.');
    END IF;

    IF V_NUEVO_ESTADO IS NULL OR V_NUEVO_ESTADO NOT IN
       ('ACTIVO','INACTIVO','BLOQUEADO') THEN
        RAISE_APPLICATION_ERROR(-20613,'Estado no permitido.');
    END IF;

    IF P_ID_ADMIN = P_ID_USUARIO THEN
        RAISE_APPLICATION_ERROR(-20614,'No puede cambiar su propio estado.');
    END IF;

    SELECT ID_ROL INTO V_ID_ADMIN_ROL
    FROM ROL WHERE NOMBRE = 'ADMINISTRADORA' FOR UPDATE;

    SELECT ID_ROL, ESTADO INTO V_ROL, V_ESTADO_ANTERIOR
    FROM USUARIO WHERE ID_USUARIO = P_ID_USUARIO FOR UPDATE;

    IF V_ESTADO_ANTERIOR = V_NUEVO_ESTADO THEN
        RAISE_APPLICATION_ERROR(-20615,'El usuario ya tiene ese estado.');
    END IF;

    IF V_ROL = V_ID_ADMIN_ROL AND V_ESTADO_ANTERIOR = 'ACTIVO'
       AND V_NUEVO_ESTADO <> 'ACTIVO' THEN
        SELECT COUNT(*) INTO V_CANTIDAD
        FROM USUARIO
        WHERE ID_ROL = V_ID_ADMIN_ROL AND ESTADO = 'ACTIVO';
        IF V_CANTIDAD <= 1 THEN
            RAISE_APPLICATION_ERROR(-20616,
                'No se puede desactivar el ultimo administrador activo.');
        END IF;
    END IF;

    UPDATE USUARIO
    SET ESTADO = V_NUEVO_ESTADO,
        INTENTOS_FALLIDOS = CASE WHEN V_NUEVO_ESTADO = 'ACTIVO'
                                 THEN 0 ELSE INTENTOS_FALLIDOS END
    WHERE ID_USUARIO = P_ID_USUARIO;

    -- Solo sesiones todavia activas; historial conservado.
    UPDATE SESION_USUARIO
    SET ESTADO = 'CERRADA', FECHA_FIN = CAST(SYSTIMESTAMP AS TIMESTAMP)
    WHERE ID_USUARIO = P_ID_USUARIO AND ESTADO = 'ACTIVA';

    INSERT INTO AUDITORIA (
        ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,
        ESTADO_ANTERIOR,ESTADO_NUEVO,ORIGEN
    ) VALUES (
        P_ID_ADMIN,'USUARIO',P_ID_USUARIO,'CAMBIO_ESTADO',
        'Cambio administrativo de estado',
        V_ESTADO_ANTERIOR,V_NUEVO_ESTADO,'USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Estado actualizado: ' || V_NUEVO_ESTADO);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_ESTADO_USUARIO;
        RAISE_APPLICATION_ERROR(-20617,'Usuario o rol administrador no encontrado.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_ESTADO_USUARIO;
        RAISE;
END SP_CAMBIAR_ESTADO_USUARIO;
/
