-- 22.5. PROCEDIMIENTO DE MANTENIMIENTO MANUAL
-----------------------------------
-- Solo este procedimiento hace COMMIT; esta disenado
-- para uso manual controlado, no como parte
-- de una transaccion normal de reservas o atenciones.
CREATE OR REPLACE PROCEDURE SP_TAREA_MANTENIMIENTO
IS
    V_RESERVAS NUMBER;
    V_SESIONES NUMBER;
    V_PERDIDAS NUMBER;
BEGIN
    SP_EXPIRAR_PRE_RESERVAS(V_RESERVAS);
    SP_EXPIRAR_SESIONES(V_SESIONES);
    SP_MARCAR_CITAS_PERDIDAS(V_PERDIDAS);

    IF V_RESERVAS > 0 OR V_SESIONES > 0 OR V_PERDIDAS > 0 THEN
        INSERT INTO AUDITORIA (
            TABLA_AFECTADA, ACCION, DETALLE, ORIGEN
        ) VALUES (
            'AUDITORIA', 'MANTENIMIENTO',
            'Reservas: ' || V_RESERVAS || ', sesiones: ' ||
            V_SESIONES || ', citas perdidas: ' || V_PERDIDAS,
            'SISTEMA'
        );
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END SP_TAREA_MANTENIMIENTO;
/
SHOW ERRORS PROCEDURE SP_TAREA_MANTENIMIENTO;

