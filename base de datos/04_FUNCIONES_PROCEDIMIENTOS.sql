-- 18.3. PROCEDIMIENTO: INICIAR ATENCION MEDICA
-----------------------------------

CREATE OR REPLACE PROCEDURE SP_INICIAR_ATENCION (
    P_ID_USUARIO IN  USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA    IN  CITA.ID_CITA%TYPE,
    P_ID_ATENCION OUT ATENCION_MEDICA.ID_ATENCION%TYPE
)
IS
    V_ROL          ROL.NOMBRE%TYPE;
    V_DOCTOR       CITA.ID_DOCTOR%TYPE;
    V_FECHA        CITA.FECHA_CITA%TYPE;
    V_ESTADO       CITA.ESTADO%TYPE;
    V_CANTIDAD     NUMBER;
BEGIN
    P_ID_ATENCION := NULL;
    SAVEPOINT SV_INICIAR_ATENCION;

    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);

    IF V_ROL <> 'DOCTOR' THEN
        RAISE_APPLICATION_ERROR(-20309,
            'Solo el medico puede iniciar la atencion.');
    END IF;

    SELECT ID_DOCTOR, FECHA_CITA, ESTADO
    INTO V_DOCTOR, V_FECHA, V_ESTADO
    FROM CITA
    WHERE ID_CITA = P_ID_CITA
    FOR UPDATE;

    IF V_ESTADO <> 'EN_ATENCION' THEN
        RAISE_APPLICATION_ERROR(-20310,
            'La cita no registra el ingreso del paciente a consulta.');
    END IF;

    IF V_FECHA <> TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20311,
            'La atencion debe iniciarse el dia de la cita.');
    END IF;

    -- RN16: no puede iniciar la atencion otro doctor.
    SELECT COUNT(*) INTO V_CANTIDAD
    FROM DOCTOR
    WHERE ID_DOCTOR = V_DOCTOR
      AND ID_USUARIO = P_ID_USUARIO
      AND ESTADO = 'ACTIVO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20312,
            'El usuario no es el doctor activo asignado a esta cita.');
    END IF;

    -- RN24: recepcion debe haber registrado la asistencia.
    SELECT COUNT(*) INTO V_CANTIDAD
    FROM ASISTENCIA
    WHERE ID_CITA = P_ID_CITA
      AND ESTADO = 'PRESENTE';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20313,
            'No se puede iniciar la atencion sin asistencia registrada.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM ATENCION_MEDICA
    WHERE ID_CITA = P_ID_CITA;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20314,
            'La atencion de esta cita ya fue iniciada.');
    END IF;

    INSERT INTO ATENCION_MEDICA (
        ID_CITA, ID_DOCTOR, FECHA_INICIO, ESTADO
    ) VALUES (
        P_ID_CITA, V_DOCTOR, CAST(SYSTIMESTAMP AS TIMESTAMP), 'ABIERTA'
    ) RETURNING ID_ATENCION INTO P_ID_ATENCION;

    INSERT INTO AUDITORIA (
        ID_USUARIO, TABLA_AFECTADA, ID_REGISTRO, ACCION, DETALLE, ORIGEN
    ) VALUES (
        P_ID_USUARIO, 'ATENCION_MEDICA', P_ID_ATENCION,
        'INICIAR', 'Inicio de consulta medica', 'USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Atencion iniciada: ' || P_ID_ATENCION);
    DBMS_OUTPUT.PUT_LINE('Doctor asignado: ' || V_DOCTOR);
    DBMS_OUTPUT.PUT_LINE('Realice COMMIT si desea conservar los cambios.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_INICIAR_ATENCION;
        RAISE_APPLICATION_ERROR(-20315,
            'La cita indicada no existe.');
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK TO SV_INICIAR_ATENCION;
        RAISE_APPLICATION_ERROR(-20316,
            'La cita ya tiene una atencion medica.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_INICIAR_ATENCION;
        RAISE;
END SP_INICIAR_ATENCION;
/

