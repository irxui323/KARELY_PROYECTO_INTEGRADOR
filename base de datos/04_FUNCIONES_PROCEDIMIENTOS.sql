-----------------------------------
-- 22.2. TOMAR UNA NOTIFICACION PENDIENTE
-----------------------------------
-- El backend hace COMMIT tras reclamar, DESPUES envía
-- el correo y finalmente informa el resultado.
-- Una reserva de 10 minutos evita tomas simultaneas.
-- La entrega es "al menos una vez"; el servicio de correo
-- debe deduplicar usando CODIGO_EVENTO si es posible.
CREATE OR REPLACE PROCEDURE SP_TOMAR_NOTIFICACION (
    P_ID_USUARIO       IN  USUARIO.ID_USUARIO%TYPE,
    P_ID_NOTIFICACION  OUT NOTIFICACION_SALIENTE.ID_NOTIFICACION%TYPE,
    P_TIPO             OUT NOTIFICACION_SALIENTE.TIPO%TYPE,
    P_DESTINATARIO     OUT NOTIFICACION_SALIENTE.DESTINATARIO%TYPE,
    P_CODIGO_EVENTO    OUT NOTIFICACION_SALIENTE.CODIGO_EVENTO%TYPE,
    P_INTENTO          OUT NOTIFICACION_SALIENTE.INTENTOS%TYPE
)
IS
    V_ROL ROL.NOMBRE%TYPE;
    V_INTENTOS NOTIFICACION_SALIENTE.INTENTOS%TYPE;

    CURSOR C_PENDIENTE IS
        SELECT ID_NOTIFICACION, TIPO, DESTINATARIO,
               CODIGO_EVENTO, INTENTOS
          FROM NOTIFICACION_SALIENTE
         WHERE ESTADO IN ('PENDIENTE','FALLIDA')
           AND INTENTOS < 5
           AND DESTINATARIO IS NOT NULL
           AND FECHA_PROXIMO_INTENTO <= CAST(SYSTIMESTAMP AS TIMESTAMP)
         ORDER BY FECHA_PROXIMO_INTENTO, ID_NOTIFICACION
         FOR UPDATE SKIP LOCKED;
BEGIN
    P_ID_NOTIFICACION := NULL;
    P_TIPO := NULL;
    P_DESTINATARIO := NULL;
    P_CODIGO_EVENTO := NULL;
    P_INTENTO := NULL;
    SAVEPOINT SV_TOMAR_NOTIFICACION;

    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);
    IF V_ROL <> 'ADMINISTRADORA' THEN
        RAISE_APPLICATION_ERROR(-20709,
            'Solo la cuenta administrativa puede operar la cola en esta version.');
    END IF;

    OPEN C_PENDIENTE;
    FETCH C_PENDIENTE INTO P_ID_NOTIFICACION, P_TIPO,
                           P_DESTINATARIO, P_CODIGO_EVENTO, V_INTENTOS;
    IF C_PENDIENTE%NOTFOUND THEN
        CLOSE C_PENDIENTE;
        DBMS_OUTPUT.PUT_LINE('No hay notificaciones disponibles.');
        RETURN;
    END IF;

    P_INTENTO := V_INTENTOS + 1;
    UPDATE NOTIFICACION_SALIENTE
       SET ESTADO = 'PENDIENTE',
           INTENTOS = P_INTENTO,
           ULTIMO_ERROR = NULL,
           FECHA_PROXIMO_INTENTO = CAST(SYSTIMESTAMP AS TIMESTAMP)
                 + NUMTODSINTERVAL(10,'MINUTE')
     WHERE ID_NOTIFICACION = P_ID_NOTIFICACION;

    CLOSE C_PENDIENTE;
    DBMS_OUTPUT.PUT_LINE('Evento tomado: ' || P_CODIGO_EVENTO);
    DBMS_OUTPUT.PUT_LINE('COMMIT ANTES de pedir el envio externo.');
EXCEPTION
    WHEN OTHERS THEN
        IF C_PENDIENTE%ISOPEN THEN
            CLOSE C_PENDIENTE;
        END IF;
        ROLLBACK TO SV_TOMAR_NOTIFICACION;
        RAISE;
END SP_TOMAR_NOTIFICACION;
/
SHOW ERRORS PROCEDURE SP_TOMAR_NOTIFICACION;

