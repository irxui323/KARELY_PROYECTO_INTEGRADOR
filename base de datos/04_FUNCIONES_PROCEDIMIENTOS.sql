CREATE OR REPLACE PROCEDURE SP_CERRAR_ATENCION (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA IN CITA.ID_CITA%TYPE
)
IS
    V_ID_DOCTOR CITA.ID_DOCTOR%TYPE;
    V_ESTADO_CITA CITA.ESTADO%TYPE;
    V_ID_ATENCION ATENCION_MEDICA.ID_ATENCION%TYPE;
    V_ESTADO_ATENCION ATENCION_MEDICA.ESTADO%TYPE;
    V_DIAGNOSTICO ATENCION_MEDICA.DIAGNOSTICO%TYPE;
    V_CANTIDAD NUMBER;
    V_MONTO_TOTAL CITA.MONTO_TOTAL%TYPE;
    V_MONTO_DOCTOR NUMBER(12,2);
BEGIN
    SAVEPOINT SV_CERRAR_ATENCION;

    IF NVL(FN_ROL_USUARIO(P_ID_USUARIO),'SIN_ROL') <> 'DOCTOR' THEN
        RAISE_APPLICATION_ERROR(-20436,'Solo el doctor asignado puede cerrar atencion.');
    END IF;

    SELECT ID_DOCTOR,ESTADO,MONTO_TOTAL INTO V_ID_DOCTOR,V_ESTADO_CITA,V_MONTO_TOTAL
      FROM CITA WHERE ID_CITA=P_ID_CITA FOR UPDATE;
    IF V_ESTADO_CITA <> 'EN_ATENCION' THEN
        RAISE_APPLICATION_ERROR(-20437,'La cita no esta EN_ATENCION.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD FROM DOCTOR
     WHERE ID_DOCTOR=V_ID_DOCTOR AND ID_USUARIO=P_ID_USUARIO AND ESTADO='ACTIVO';
    IF V_CANTIDAD <> 1 THEN
        RAISE_APPLICATION_ERROR(-20438,'El usuario no es el doctor asignado.');
    END IF;

    SELECT ID_ATENCION,ESTADO,DIAGNOSTICO
      INTO V_ID_ATENCION,V_ESTADO_ATENCION,V_DIAGNOSTICO
      FROM ATENCION_MEDICA
     WHERE ID_CITA=P_ID_CITA AND ID_DOCTOR=V_ID_DOCTOR FOR UPDATE;

    IF V_ESTADO_ATENCION <> 'ABIERTA' THEN
        RAISE_APPLICATION_ERROR(-20439,'La atencion no esta abierta.');
    END IF;
    IF V_DIAGNOSTICO IS NULL
       OR NVL(DBMS_LOB.GETLENGTH(V_DIAGNOSTICO),0)=0
       OR TRIM(DBMS_LOB.SUBSTR(V_DIAGNOSTICO,4000,1)) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20440,'Registre el diagnostico antes de cerrar.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
      FROM RECETA R
     WHERE R.ID_ATENCION=V_ID_ATENCION
       AND TRIM(R.INDICACIONES) IS NOT NULL
       AND EXISTS (SELECT 1 FROM RECETA_DETALLE D WHERE D.ID_RECETA=R.ID_RECETA);
    IF V_CANTIDAD <> 1 THEN
        RAISE_APPLICATION_ERROR(-20441,'La receta debe tener indicaciones y medicamentos.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
      FROM RECIBO_HONORARIO H
     WHERE H.ID_CITA=P_ID_CITA AND H.ID_DOCTOR_EMISOR=V_ID_DOCTOR
       AND H.FECHA_ENTREGA IS NOT NULL AND H.MEDIO_ENTREGA IS NOT NULL
       AND H.ID_USUARIO_ENTREGA IS NOT NULL;
    IF V_CANTIDAD <> 1 THEN
        RAISE_APPLICATION_ERROR(-20442,'El recibo debe entregarse antes del cierre.');
    END IF;

    UPDATE ATENCION_MEDICA
       SET ESTADO='CERRADA',FECHA_CIERRE=SYSTIMESTAMP
     WHERE ID_ATENCION=V_ID_ATENCION;

    -- Guardar importes devengados una vez, no recalcular con comisiones futuras.
    V_MONTO_DOCTOR := FN_MONTO_DOCTOR(V_MONTO_TOTAL);
    UPDATE CITA SET ESTADO='ATENDIDA',
      MONTO_DOCTOR_DEVENGADO=V_MONTO_DOCTOR,
      MONTO_GESTORA_DEVENGADO=V_MONTO_TOTAL-V_MONTO_DOCTOR
    WHERE ID_CITA=P_ID_CITA;

    INSERT INTO AUDITORIA (
        ID_USUARIO,TABLA_AFECTADA,ID_REGISTRO,ACCION,DETALLE,
        ESTADO_ANTERIOR,ESTADO_NUEVO,ORIGEN
    ) VALUES (
        P_ID_USUARIO,'CITA',P_ID_CITA,'CERRAR',
        'Atencion y consulta cerradas', 'EN_ATENCION','ATENDIDA','USUARIO'
    );

    DBMS_OUTPUT.PUT_LINE('Atencion cerrada: '||V_ID_ATENCION);
    DBMS_OUTPUT.PUT_LINE('Cita '||P_ID_CITA||' registrada como ATENDIDA.');
    DBMS_OUTPUT.PUT_LINE('Realice COMMIT para conservar los cambios.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK TO SV_CERRAR_ATENCION;
        RAISE_APPLICATION_ERROR(-20443,'Cita o atencion medica no encontrada.');
    WHEN OTHERS THEN
        ROLLBACK TO SV_CERRAR_ATENCION;
        RAISE;
END SP_CERRAR_ATENCION;
/
