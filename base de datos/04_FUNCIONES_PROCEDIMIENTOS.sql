CREATE OR REPLACE PROCEDURE SP_VALIDAR_DOCUMENTACION (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_DOCTOR IN DOCTOR.ID_DOCTOR%TYPE
)
IS
    V_CANTIDAD NUMBER;
    V_ESTADO DOCTOR.ESTADO_DOCUMENTACION%TYPE;
BEGIN
    IF SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER') IS NULL
       OR SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_USUARIO) THEN
        RAISE_APPLICATION_ERROR(-20002, 'Identidad de sesion no coincide.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM USUARIO U
    JOIN ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.ID_USUARIO = P_ID_USUARIO
      AND U.ESTADO = 'ACTIVO'
      AND R.ESTADO = 'ACTIVO'
      AND R.NOMBRE = 'ADMINISTRADORA';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Solo la administradora puede validar documentos.');
    END IF;

    SELECT ESTADO_DOCUMENTACION INTO V_ESTADO
    FROM DOCTOR
    WHERE ID_DOCTOR = P_ID_DOCTOR
      AND ESTADO = 'ACTIVO'
    FOR UPDATE;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM (
        SELECT TIPO_DOCUMENTO, ESTADO, ARCHIVO,
               ROW_NUMBER() OVER (
                   PARTITION BY TIPO_DOCUMENTO
                   ORDER BY ID_DOCUMENTO DESC
               ) AS FILA
        FROM DOCUMENTO_DOCTOR
        WHERE ID_DOCTOR = P_ID_DOCTOR
          AND TIPO_DOCUMENTO IN ('DNI', 'TITULO')
    )
    WHERE FILA = 1
      AND ESTADO IN ('PENDIENTE', 'VALIDADO')
      AND DBMS_LOB.GETLENGTH(ARCHIVO) > 0;

    IF V_CANTIDAD <> 2 THEN
        RAISE_APPLICATION_ERROR(-20004, 'Falta DNI o titulo vigente, o un documento fue rechazado.');
    END IF;

    UPDATE DOCUMENTO_DOCTOR D
    SET ESTADO = 'VALIDADO',
        USUARIO_VALIDACION = P_ID_USUARIO,
        FECHA_VALIDACION = SYSTIMESTAMP
    WHERE D.ID_DOCTOR = P_ID_DOCTOR
      AND D.TIPO_DOCUMENTO IN ('DNI', 'TITULO')
      AND D.ESTADO = 'PENDIENTE'
      AND D.ID_DOCUMENTO = (
          SELECT MAX(D2.ID_DOCUMENTO)
          FROM DOCUMENTO_DOCTOR D2
          WHERE D2.ID_DOCTOR = D.ID_DOCTOR
            AND D2.TIPO_DOCUMENTO = D.TIPO_DOCUMENTO
      );

    UPDATE DOCTOR
    SET ESTADO_DOCUMENTACION = 'COMPLETO'
    WHERE ID_DOCTOR = P_ID_DOCTOR;

    DBMS_OUTPUT.PUT_LINE('Documentacion del doctor validada.');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20005, 'Doctor activo no encontrado.');
END SP_VALIDAR_DOCUMENTACION;
/

