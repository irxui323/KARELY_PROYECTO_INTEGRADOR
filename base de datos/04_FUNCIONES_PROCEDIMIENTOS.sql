-- 17.1. FUNCION: VERIFICAR ROL DEL USUARIO
-----------------------------------

CREATE OR REPLACE FUNCTION FN_ROL_USUARIO (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE
)
RETURN VARCHAR2
IS
    V_ROL ROL.NOMBRE%TYPE;
BEGIN
    IF P_ID_USUARIO IS NULL
       OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') IS NULL
       OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_USUARIO) THEN
        RAISE_APPLICATION_ERROR(-20200,'La identidad de sesion no coincide.');
    END IF;

    SELECT R.NOMBRE
    INTO V_ROL
    FROM USUARIO U
    JOIN ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.ID_USUARIO = P_ID_USUARIO
      AND U.ESTADO = 'ACTIVO'
      AND R.ESTADO = 'ACTIVO';

    RETURN V_ROL;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20201,'Usuario o rol inexistente o inactivo.');
END FN_ROL_USUARIO;
/

SHOW ERRORS FUNCTION FN_ROL_USUARIO;

-----------------------------------
-- 17.2. PROCEDIMIENTO: REPROGRAMAR CITA
-----------------------------------

CREATE OR REPLACE PROCEDURE SP_REPROGRAMAR_CITA (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA IN CITA.ID_CITA%TYPE,
    P_FECHA_NUEVA IN DATE,
    P_ID_FRANJA_NUEVA IN FRANJA_HORARIA.ID_FRANJA%TYPE,
    P_ID_CONSULTORIO_NUEVO IN CONSULTORIO.ID_CONSULTORIO%TYPE,
    P_MOTIVO IN REPROGRAMACION_CITA.MOTIVO%TYPE,
    P_ACEPTACION_PACIENTE IN CHAR
)
IS
    V_ROL VARCHAR2(40);
    V_CITA CITA%ROWTYPE;
    V_DOCTOR CITA.ID_DOCTOR%TYPE;
    V_CONSULTORIO_ANTERIOR CITA.ID_CONSULTORIO%TYPE;
    V_ESTADO_DOCUMENTACION DOCTOR.ESTADO_DOCUMENTACION%TYPE;
    V_CANTIDAD NUMBER;
    V_HORA_INICIO FRANJA_HORARIA.HORA_INICIO%TYPE;
    V_HORA_FIN FRANJA_HORARIA.HORA_FIN%TYPE;
    V_CONSULTORIO_VALIDO BOOLEAN := FALSE;
    V_AHORA TIMESTAMP := CAST(SYSTIMESTAMP AS TIMESTAMP);
BEGIN
    SAVEPOINT SV_REPROGRAMAR_CITA;
    V_ROL := FN_ROL_USUARIO(P_ID_USUARIO);

    IF V_ROL NOT IN ('ADMINISTRADORA','RECEPCIONISTA') THEN
        RAISE_APPLICATION_ERROR(-20202,'Solo recepcion o administracion puede reprogramar.');
    END IF;

    IF P_ACEPTACION_PACIENTE IS NULL
       OR UPPER(TRIM(P_ACEPTACION_PACIENTE)) <> 'S' THEN
        RAISE_APPLICATION_ERROR(-20203,'El paciente debe aceptar expresamente la nueva fecha.');
    END IF;

    IF TRIM(P_MOTIVO) IS NULL THEN
        RAISE_APPLICATION_ERROR(-20204,'El motivo de reprogramacion es obligatorio.');
    END IF;

    IF P_FECHA_NUEVA IS NULL OR P_FECHA_NUEVA <> TRUNC(P_FECHA_NUEVA) THEN
        RAISE_APPLICATION_ERROR(-20205,'La nueva fecha debe indicarse sin hora.');
    END IF;

    SELECT ID_DOCTOR, ID_CONSULTORIO
    INTO V_DOCTOR, V_CONSULTORIO_ANTERIOR
    FROM CITA
    WHERE ID_CITA = P_ID_CITA;

    -- Mantiene el orden de bloqueos compatible con los pasos 14 y 15.
    SELECT ESTADO_DOCUMENTACION
    INTO V_ESTADO_DOCUMENTACION
    FROM DOCTOR
    WHERE ID_DOCTOR = V_DOCTOR
      AND ESTADO = 'ACTIVO'
    FOR UPDATE;

    IF V_ESTADO_DOCUMENTACION <> 'COMPLETO' THEN
        RAISE_APPLICATION_ERROR(-20206,'El medico no tiene documentacion vigente.');
    END IF;

    -- Bloquear ambos consultorios siempre en el mismo orden.
    FOR X IN (
        SELECT ID_CONSULTORIO, ESTADO
        FROM CONSULTORIO
        WHERE ID_CONSULTORIO IN (V_CONSULTORIO_ANTERIOR,P_ID_CONSULTORIO_NUEVO)
        ORDER BY ID_CONSULTORIO
        FOR UPDATE
    ) LOOP
        IF X.ID_CONSULTORIO = P_ID_CONSULTORIO_NUEVO THEN
            IF X.ESTADO <> 'ACTIVO' THEN
                RAISE_APPLICATION_ERROR(-20207,'El consultorio nuevo esta inactivo.');
            END IF;
            V_CONSULTORIO_VALIDO := TRUE;
        END IF;
    END LOOP;

    IF NOT V_CONSULTORIO_VALIDO THEN
        RAISE_APPLICATION_ERROR(-20208,'No existe el consultorio nuevo.');
    END IF;

    SELECT * INTO V_CITA
    FROM CITA
    WHERE ID_CITA = P_ID_CITA
    FOR UPDATE;

    IF V_CITA.ID_DOCTOR <> V_DOCTOR
       OR V_CITA.ID_CONSULTORIO <> V_CONSULTORIO_ANTERIOR THEN
        RAISE_APPLICATION_ERROR(-20209,'La cita cambio durante la operacion. Reintente.');
    END IF;

    V_AHORA := CAST(SYSTIMESTAMP AS TIMESTAMP);

    IF V_CITA.ESTADO <> 'PROGRAMADA' OR V_CITA.REPROGRAMACIONES <> 0 THEN
        RAISE_APPLICATION_ERROR(-20210,'La cita no admite otra reprogramacion.');
    END IF;

    IF FN_INICIO_TURNO(V_CITA.FECHA_CITA,V_CITA.ID_FRANJA) <= V_AHORA THEN
        RAISE_APPLICATION_ERROR(-20211,'La reprogramacion debe solicitarse antes del turno original.');
    END IF;

    IF FN_INICIO_TURNO(P_FECHA_NUEVA,P_ID_FRANJA_NUEVA) <= V_AHORA THEN
        RAISE_APPLICATION_ERROR(-20212,'El turno nuevo debe comenzar en el futuro.');
    END IF;

    IF P_FECHA_NUEVA = V_CITA.FECHA_CITA
       AND P_ID_FRANJA_NUEVA = V_CITA.ID_FRANJA
       AND P_ID_CONSULTORIO_NUEVO = V_CITA.ID_CONSULTORIO THEN
        RAISE_APPLICATION_ERROR(-20213,'La cita no tiene cambios de fecha, turno ni consultorio.');
    END IF;

    SELECT HORA_INICIO, HORA_FIN
    INTO V_HORA_INICIO,V_HORA_FIN
    FROM FRANJA_HORARIA
    WHERE ID_FRANJA = P_ID_FRANJA_NUEVA
      AND ESTADO = 'ACTIVO';

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM DISPONIBILIDAD_DOCTOR
    WHERE ID_DOCTOR = V_CITA.ID_DOCTOR
      AND ID_FRANJA = P_ID_FRANJA_NUEVA
      AND FECHA_TURNO = P_FECHA_NUEVA
      AND ESTADO = 'ACTIVO';

    IF V_CANTIDAD = 0 THEN
        RAISE_APPLICATION_ERROR(-20214,'El doctor no ofrece ese nuevo turno.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM CITA C
    JOIN FRANJA_HORARIA F ON F.ID_FRANJA = C.ID_FRANJA
    WHERE C.ID_CITA <> P_ID_CITA
      AND C.FECHA_CITA = P_FECHA_NUEVA
      AND C.ESTADO IN ('PROGRAMADA','REPROGRAMADA','EN_ATENCION')
      AND (C.ID_DOCTOR = V_CITA.ID_DOCTOR
           OR C.ID_CONSULTORIO = P_ID_CONSULTORIO_NUEVO)
      AND F.HORA_INICIO < V_HORA_FIN
      AND V_HORA_INICIO < F.HORA_FIN;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20215,'La nueva fecha cruza una cita activa.');
    END IF;

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM PRE_RESERVA_CITA P
    JOIN FRANJA_HORARIA F ON F.ID_FRANJA = P.ID_FRANJA
    WHERE P.FECHA_CITA = P_FECHA_NUEVA
      AND P.ESTADO = 'BLOQUEADA'
      AND P.FECHA_EXPIRACION > CAST(SYSTIMESTAMP AS TIMESTAMP)
      AND (P.ID_DOCTOR = V_CITA.ID_DOCTOR
           OR P.ID_CONSULTORIO = P_ID_CONSULTORIO_NUEVO)
      AND F.HORA_INICIO < V_HORA_FIN
      AND V_HORA_INICIO < F.HORA_FIN;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20216,'La nueva fecha tiene una pre-reserva vigente.');
    END IF;

    INSERT INTO REPROGRAMACION_CITA (
        ID_CITA,FECHA_ORIGINAL,ID_FRANJA_ORIGINAL,ID_CONSULTORIO_ORIGINAL,
        FECHA_NUEVA,ID_FRANJA_NUEVA,ID_CONSULTORIO_NUEVO,
        MOTIVO,ACEPTACION_PACIENTE,ID_USUARIO_ACEPTACION
    ) VALUES (
        P_ID_CITA,V_CITA.FECHA_CITA,V_CITA.ID_FRANJA,V_CITA.ID_CONSULTORIO,
        P_FECHA_NUEVA,P_ID_FRANJA_NUEVA,P_ID_CONSULTORIO_NUEVO,
        TRIM(P_MOTIVO),'S',P_ID_USUARIO
    );

    UPDATE CITA
    SET FECHA_CITA = P_FECHA_NUEVA,
        ID_FRANJA = P_ID_FRANJA_NUEVA,
        ID_CONSULTORIO = P_ID_CONSULTORIO_NUEVO,
        REPROGRAMACIONES = 1,
        ESTADO = 'REPROGRAMADA'
    WHERE ID_CITA = P_ID_CITA;

    DBMS_OUTPUT.PUT_LINE('Cita reprogramada: ' || P_ID_CITA);
    DBMS_OUTPUT.PUT_LINE('Se conserva el pago de la cita original.');
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO SV_REPROGRAMAR_CITA;
        RAISE;
END SP_REPROGRAMAR_CITA;
/

