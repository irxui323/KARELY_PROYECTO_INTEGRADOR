-- 14.5. PROCEDIMIENTO: REGISTRAR DISPONIBILIDAD
-----------------------------------

CREATE OR REPLACE PROCEDURE SP_REGISTRAR_DISPONIBILIDAD (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_DOCTOR IN DOCTOR.ID_DOCTOR%TYPE,
    P_FECHA IN DATE,
    P_ID_FRANJA IN FRANJA_HORARIA.ID_FRANJA%TYPE,
    P_ID_DISPONIBILIDAD OUT DISPONIBILIDAD_DOCTOR.ID_DISPONIBILIDAD%TYPE
)
IS
    V_ROL ROL.NOMBRE%TYPE;
    V_USUARIO_DOCTOR DOCTOR.ID_USUARIO%TYPE;
    V_ESTADO DOCTOR.ESTADO_DOCUMENTACION%TYPE;
    V_CANTIDAD NUMBER;
    V_HORA_INICIO FRANJA_HORARIA.HORA_INICIO%TYPE;
    V_HORA_FIN FRANJA_HORARIA.HORA_FIN%TYPE;
BEGIN
    IF SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER') IS NULL
       OR SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_USUARIO) THEN
        RAISE_APPLICATION_ERROR(-20006, 'Identidad de sesion no coincide.');
    END IF;

    SELECT R.NOMBRE INTO V_ROL
    FROM USUARIO U
    JOIN ROL R ON R.ID_ROL = U.ID_ROL
    WHERE U.ID_USUARIO = P_ID_USUARIO
      AND U.ESTADO = 'ACTIVO'
      AND R.ESTADO = 'ACTIVO';

    IF V_ROL NOT IN ('ADMINISTRADORA', 'DOCTOR') THEN
        RAISE_APPLICATION_ERROR(-20007, 'Usuario sin permiso para registrar horarios.');
    END IF;

    SELECT ID_USUARIO, ESTADO_DOCUMENTACION
    INTO V_USUARIO_DOCTOR, V_ESTADO
    FROM DOCTOR
    WHERE ID_DOCTOR = P_ID_DOCTOR
      AND ESTADO = 'ACTIVO'
    FOR UPDATE;

    IF V_ROL = 'DOCTOR' AND
       (V_USUARIO_DOCTOR IS NULL OR V_USUARIO_DOCTOR <> P_ID_USUARIO) THEN
        RAISE_APPLICATION_ERROR(-20008, 'Un doctor solo puede registrar su propio horario.');
    END IF;

    IF V_ESTADO <> 'COMPLETO' THEN
        RAISE_APPLICATION_ERROR(-20009, 'El doctor requiere documentacion completa.');
    END IF;

    IF P_FECHA IS NULL
       OR P_FECHA <> TRUNC(P_FECHA)
       OR P_FECHA < TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20010, 'Fecha invalida o anterior a hoy.');
    END IF;

    SELECT HORA_INICIO, HORA_FIN
    INTO V_HORA_INICIO, V_HORA_FIN
    FROM FRANJA_HORARIA
    WHERE ID_FRANJA = P_ID_FRANJA
      AND ESTADO = 'ACTIVO';

    SELECT COUNT(*) INTO V_CANTIDAD
    FROM DISPONIBILIDAD_DOCTOR D
    JOIN FRANJA_HORARIA F ON F.ID_FRANJA = D.ID_FRANJA
    WHERE D.ID_DOCTOR = P_ID_DOCTOR
      AND D.FECHA_TURNO = P_FECHA
      AND D.ESTADO = 'ACTIVO'
      AND F.HORA_INICIO < V_HORA_FIN
      AND V_HORA_INICIO < F.HORA_FIN;

    IF V_CANTIDAD > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Horario duplicado o solapado.');
    END IF;

    INSERT INTO DISPONIBILIDAD_DOCTOR (
        ID_DOCTOR, ID_FRANJA, FECHA_TURNO
    ) VALUES (
        P_ID_DOCTOR, P_ID_FRANJA, P_FECHA
    ) RETURNING ID_DISPONIBILIDAD INTO P_ID_DISPONIBILIDAD;

    DBMS_OUTPUT.PUT_LINE('Disponibilidad registrada: ' || P_ID_DISPONIBILIDAD);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20012, 'Usuario, doctor o franja inexistente o inactivo.');
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20013, 'Disponibilidad ya registrada.');
END SP_REGISTRAR_DISPONIBILIDAD;
/

SHOW ERRORS PROCEDURE SP_REGISTRAR_DISPONIBILIDAD;

