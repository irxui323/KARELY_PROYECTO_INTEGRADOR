-- Excepcion RN27: no genera pago nuevo, el ingreso de gestora se deriva de CITA.
CREATE OR REPLACE PROCEDURE SP_CANCELAR_REPROGRAMADA (
    P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
    P_ID_CITA IN CITA.ID_CITA%TYPE,
    P_MOTIVO IN VARCHAR2
) IS
 V_ESTADO CITA.ESTADO%TYPE;
 V_REPROGRAMACIONES CITA.REPROGRAMACIONES%TYPE;
 V_ID_PAGO CITA.ID_PAGO%TYPE;
 V_CANTIDAD NUMBER;
BEGIN
 SAVEPOINT SV_CANCELAR_REPROGRAMADA;
 IF P_ID_USUARIO IS NULL OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') IS NULL
    OR SYS_CONTEXT('USERENV','CLIENT_IDENTIFIER') <> TO_CHAR(P_ID_USUARIO) THEN
  RAISE_APPLICATION_ERROR(-20508,'Identidad de sesion no coincide');
 END IF;
 IF NVL(FN_ROL_USUARIO(P_ID_USUARIO),'SIN_ROL') <> 'ADMINISTRADORA' THEN
  RAISE_APPLICATION_ERROR(-20517,'Solo administracion autoriza la excepcion');
 END IF;
 IF TRIM(P_MOTIVO) IS NULL THEN
  RAISE_APPLICATION_ERROR(-20518,'Motivo de cancelacion obligatorio');
 END IF;
 SELECT estado,reprogramaciones,id_pago
 INTO v_estado,v_reprogramaciones,v_id_pago FROM CITA
 WHERE id_cita=p_id_cita FOR UPDATE;
 IF v_estado<>'REPROGRAMADA' OR v_reprogramaciones<>1 THEN
  RAISE_APPLICATION_ERROR(-20519,'Solo cita reprogramada exactamente una vez');
 END IF;
 SELECT COUNT(*) INTO v_cantidad FROM REPROGRAMACION_CITA
 WHERE id_cita=p_id_cita;
 IF v_cantidad<>1 THEN
  RAISE_APPLICATION_ERROR(-20520,'No existe aceptacion de reprogramacion');
 END IF;
 SELECT COUNT(*) INTO v_cantidad FROM PAGO_CITA
 WHERE id_pago=v_id_pago AND estado='APROBADO';
 IF v_cantidad<>1 THEN
  RAISE_APPLICATION_ERROR(-20521,'No hay pago aprobado');
 END IF;
 SELECT COUNT(*) INTO v_cantidad FROM ASISTENCIA WHERE id_cita=p_id_cita;
 IF v_cantidad>0 THEN
  RAISE_APPLICATION_ERROR(-20522,'No se cancela una cita con asistencia');
 END IF;
 UPDATE CITA SET estado='CANCELADA' WHERE id_cita=p_id_cita;
 INSERT INTO AUDITORIA(id_usuario,tabla_afectada,id_registro,accion,detalle,
   estado_anterior,estado_nuevo,origen)
 VALUES (p_id_usuario,'CITA',p_id_cita,'CANCELAR',
   SUBSTR('Excepcion RN27. '||TRIM(p_motivo),1,500),
   'REPROGRAMADA','CANCELADA','USUARIO');
 DBMS_OUTPUT.PUT_LINE('Cancelada RN27; ingreso gestor derivado sin tabla adicional');
EXCEPTION
 WHEN NO_DATA_FOUND THEN ROLLBACK TO SV_CANCELAR_REPROGRAMADA;
  RAISE_APPLICATION_ERROR(-20524,'Cita inexistente');
 WHEN OTHERS THEN ROLLBACK TO SV_CANCELAR_REPROGRAMADA; RAISE;
END SP_CANCELAR_REPROGRAMADA;
/
