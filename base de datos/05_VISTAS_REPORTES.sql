-- 23.1. VISTA: AGENDA DE CITAS
-----------------------------------
-- UN REGISTRO POR CITA.
-- PERMITE CONSULTAR CITAS DE UN DOCTOR, DIA O ESTADO.
CREATE OR REPLACE VIEW VW_AGENDA_CITAS AS
SELECT
    C.ID_CITA,
    C.FECHA_CITA,
    F.HORA_INICIO,
    F.HORA_FIN,
    C.ID_DOCTOR,
    D.NOMBRES || ' ' || D.APELLIDOS AS NOMBRE_DOCTOR,
    C.ID_PACIENTE,
    P.NOMBRES || ' ' || P.APELLIDOS AS NOMBRE_PACIENTE,
    C.ID_ESPECIALIDAD,
    E.NOMBRE AS ESPECIALIDAD,
    C.ID_CONSULTORIO,
    CO.NOMBRE AS CONSULTORIO,
    C.ESTADO AS ESTADO_CITA,
    C.REPROGRAMACIONES,
    CASE
        WHEN A.ID_ASISTENCIA IS NULL THEN 'NO'
        ELSE 'SI'
    END AS ASISTENCIA_REGISTRADA,
    C.MONTO_TOTAL
FROM CITA C
JOIN DOCTOR D
    ON D.ID_DOCTOR = C.ID_DOCTOR
JOIN PACIENTE P
    ON P.ID_PACIENTE = C.ID_PACIENTE
JOIN ESPECIALIDAD E
    ON E.ID_ESPECIALIDAD = C.ID_ESPECIALIDAD
JOIN CONSULTORIO CO
    ON CO.ID_CONSULTORIO = C.ID_CONSULTORIO
JOIN FRANJA_HORARIA F
    ON F.ID_FRANJA = C.ID_FRANJA
LEFT JOIN ASISTENCIA A
    ON A.ID_CITA = C.ID_CITA;

-----------------------------------
-- 23.2. VISTA: RESUMEN DIARIO DE CITAS
-----------------------------------
-- UN REGISTRO POR FECHA Y DOCTOR.
-- MONTO_ATENDIDO ES VALOR DE CITAS ATENDIDAS:
-- NO EQUIVALE AL DINERO COBRADO NI A INGRESOS LIQUIDADOS.
CREATE OR REPLACE VIEW VW_RESUMEN_CITAS_DIARIAS AS
SELECT
    C.FECHA_CITA,
    C.ID_DOCTOR,
    D.NOMBRES || ' ' || D.APELLIDOS AS NOMBRE_DOCTOR,
    COUNT(*) AS TOTAL_CITAS,
    SUM(CASE WHEN C.ESTADO = 'PROGRAMADA' THEN 1 ELSE 0 END)
        AS TOTAL_PROGRAMADAS,
    SUM(CASE WHEN C.ESTADO = 'REPROGRAMADA' THEN 1 ELSE 0 END)
        AS TOTAL_REPROGRAMADAS,
    SUM(CASE WHEN C.ESTADO = 'EN_ATENCION' THEN 1 ELSE 0 END)
        AS TOTAL_EN_ATENCION,
    SUM(CASE WHEN C.ESTADO = 'ATENDIDA' THEN 1 ELSE 0 END)
        AS TOTAL_ATENDIDAS,
    SUM(CASE WHEN C.ESTADO = 'PERDIDA' THEN 1 ELSE 0 END)
        AS TOTAL_PERDIDAS,
    SUM(CASE WHEN C.ESTADO = 'CANCELADA' THEN 1 ELSE 0 END)
        AS TOTAL_CANCELADAS,
    SUM(CASE
        WHEN C.ESTADO = 'ATENDIDA' THEN C.MONTO_TOTAL
        ELSE 0
    END) AS MONTO_ATENDIDO
FROM CITA C
JOIN DOCTOR D
    ON D.ID_DOCTOR = C.ID_DOCTOR
GROUP BY
    C.FECHA_CITA,
    C.ID_DOCTOR,
    D.NOMBRES,
    D.APELLIDOS;

-----------------------------------
-- 23.3. VISTA: SALDOS DE LIQUIDACIONES
-----------------------------------
-- AGRUPAR LOS PAGOS ANTES DE UNIR PARA NO DUPLICAR
-- LOS TOTALES DE CADA LIQUIDACION.
-- UN REGISTRO POR LIQUIDACION.
-- Resumen por pago; saldo calculado con los devengos confirmados.
CREATE OR REPLACE VIEW VW_SALDOS_LIQUIDACIONES AS
SELECT l.id_liquidacion,l.id_doctor,
 d.nombres||' '||d.apellidos AS nombre_doctor,
 l.periodo_inicio,l.periodo_fin,l.monto AS monto_pagado,
 l.metodo_pago,l.numero_operacion,l.numero_boleta,l.fecha_pago,
 FN_SALDO_DOCTOR(l.id_doctor,l.periodo_fin) AS saldo_pendiente
FROM LIQUIDACION l JOIN DOCTOR d ON d.id_doctor=l.id_doctor;

-- Las ganancias de la gestora son derivadas, no movimientos duplicados.
CREATE OR REPLACE VIEW VW_INGRESOS_GESTORA AS
SELECT c.id_cita,c.id_doctor,c.fecha_cita,
 CAST('COMISION_ATENCION' AS VARCHAR2(35)) AS concepto,
 c.monto_gestora_devengado AS monto_ingreso
FROM CITA c WHERE c.estado='ATENDIDA' AND c.monto_gestora_devengado IS NOT NULL
UNION ALL
SELECT c.id_cita,c.id_doctor,c.fecha_cita,
 CAST('CANCELACION_REPROGRAMADA' AS VARCHAR2(35)) AS concepto,
 c.monto_total AS monto_ingreso
FROM CITA c WHERE c.estado='CANCELADA' AND c.reprogramaciones=1;

-- Pagos de pacientes con sus datos identificatorios.
CREATE OR REPLACE VIEW VW_PAGOS_CITA AS
SELECT pc.id_pago,pc.id_pre_reserva,pc.id_paciente,
 p.tipo_documento,p.numero_documento,p.nombres,p.apellidos,
 pc.fecha_pago,pc.monto,pc.metodo_pago,pc.referencia_pago,pc.estado
FROM PAGO_CITA pc JOIN PACIENTE p ON p.id_paciente=pc.id_paciente;

-----------------------------------
-- 23.5. VISTA: ESTADO DE NOTIFICACIONES
-----------------------------------
-- NO EXPONE DIRECCIONES DE CORREO EN EL REPORTE.
-- 'ENVIADA' SOLO SIGNIFICA QUE EL SISTEMA REGISTRO
-- LA CONFIRMACION DEL PROVEEDOR EXTERNO.
CREATE OR REPLACE VIEW VW_CONTROL_NOTIFICACIONES AS
SELECT
    ID_NOTIFICACION,
    CODIGO_EVENTO,
    TIPO,
    CANAL,
    ESTADO,
    INTENTOS,
    FECHA_CREACION,
    FECHA_PROXIMO_INTENTO,
    FECHA_ENVIO,
    ID_CITA,
    ID_LIQUIDACION
FROM NOTIFICACION_SALIENTE;

-----------------------------------
-- 23.6. VERIFICAR LAS 6 VISTAS
-----------------------------------
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM USER_OBJECTS
WHERE OBJECT_TYPE = 'VIEW'
  AND OBJECT_NAME IN (
      'VW_AGENDA_CITAS',
      'VW_RESUMEN_CITAS_DIARIAS',
      'VW_SALDOS_LIQUIDACIONES',
      'VW_INGRESOS_GESTORA',
      'VW_PAGOS_CITA',
      'VW_CONTROL_NOTIFICACIONES'
  )
ORDER BY OBJECT_NAME;

-----------------------------------
-- 23.7. VERIFICAR ERRORES DE COMPILACION
-----------------------------------
SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM USER_ERRORS
WHERE TYPE = 'VIEW'
  AND NAME IN (
      'VW_AGENDA_CITAS',
      'VW_RESUMEN_CITAS_DIARIAS',
      'VW_SALDOS_LIQUIDACIONES',
      'VW_INGRESOS_GESTORA',
      'VW_CONTROL_NOTIFICACIONES'
  )
ORDER BY NAME, SEQUENCE;

-----------------------------------
-- 23.8. REPORTE: AGENDA DE HOY Y LOS PROXIMOS 7 DIAS
-----------------------------------
SELECT
    FECHA_CITA, HORA_INICIO, HORA_FIN,
    NOMBRE_DOCTOR, NOMBRE_PACIENTE,
    ESPECIALIDAD, CONSULTORIO, ESTADO_CITA
FROM VW_AGENDA_CITAS
WHERE FECHA_CITA >= TRUNC(SYSDATE)
  AND FECHA_CITA < TRUNC(SYSDATE) + 7
ORDER BY FECHA_CITA, HORA_INICIO, NOMBRE_DOCTOR;

-----------------------------------
-- 23.9. REPORTE: ACTIVIDAD DE LOS ULTIMOS 30 DIAS
-----------------------------------
SELECT
    FECHA_CITA, NOMBRE_DOCTOR,
    TOTAL_CITAS, TOTAL_ATENDIDAS,
    TOTAL_PERDIDAS, TOTAL_CANCELADAS,
    MONTO_ATENDIDO
FROM VW_RESUMEN_CITAS_DIARIAS
WHERE FECHA_CITA >= TRUNC(SYSDATE) - 30
  AND FECHA_CITA <= TRUNC(SYSDATE)
ORDER BY FECHA_CITA DESC, NOMBRE_DOCTOR;

-----------------------------------
-- 23.10. REPORTE: SALDO PENDIENTE DE MEDICOS
-----------------------------------
SELECT
    ID_LIQUIDACION, NOMBRE_DOCTOR,
    PERIODO_INICIO, PERIODO_FIN,
    MONTO_PAGADO, METODO_PAGO, NUMERO_OPERACION,
    SALDO_PENDIENTE
FROM VW_SALDOS_LIQUIDACIONES
WHERE SALDO_PENDIENTE > 0
ORDER BY PERIODO_FIN, NOMBRE_DOCTOR;

-----------------------------------
-- 23.11. REPORTE: INGRESOS MENSUALES REGISTRADOS
-----------------------------------
SELECT
    TO_CHAR(FECHA_CITA,'YYYY-MM') AS PERIODO,
    CONCEPTO,
    COUNT(*) AS TOTAL_REGISTROS,
    SUM(MONTO_INGRESO) AS MONTO_TOTAL
FROM VW_INGRESOS_GESTORA
GROUP BY
    TO_CHAR(FECHA_CITA,'YYYY-MM'),
    CONCEPTO
ORDER BY PERIODO, CONCEPTO;

-----------------------------------
-- 23.12. REPORTE: ESTADO DE LA COLA DE NOTIFICACIONES
-----------------------------------
SELECT
    TIPO, ESTADO,
    COUNT(*) AS TOTAL,
    SUM(CASE WHEN INTENTOS >= 5 THEN 1 ELSE 0 END) AS CON_MAXIMO_INTENTOS
FROM VW_CONTROL_NOTIFICACIONES
GROUP BY TIPO, ESTADO
ORDER BY TIPO, ESTADO;

-----------------------------------
-- 23.13. CONSULTA DE CONTROL: TOTAL DE TABLAS
-----------------------------------
SELECT COUNT(*) AS TOTAL_TABLAS
FROM USER_TABLES;

-----------------------------------
-- 23.14. CONSULTA DE CONTROL: TOTAL DE VISTAS DEL PASO
-----------------------------------
SELECT COUNT(*) AS TOTAL_VISTAS_VALIDAS
FROM USER_OBJECTS
WHERE OBJECT_TYPE = 'VIEW'
  AND STATUS = 'VALID'
  AND OBJECT_NAME IN (
      'VW_AGENDA_CITAS',
      'VW_RESUMEN_CITAS_DIARIAS',
      'VW_SALDOS_LIQUIDACIONES',
      'VW_INGRESOS_GESTORA',
      'VW_PAGOS_CITA',
      'VW_CONTROL_NOTIFICACIONES'
  );

