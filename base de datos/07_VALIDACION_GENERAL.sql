SET DEFINE OFF
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE

-- TABLAS FINANCIERAS: exactamente estas tres. No COMPROBANTE_CITA.
SELECT TABLE_NAME FROM USER_TABLES
 WHERE TABLE_NAME IN ('PAGO_CITA','LIQUIDACION','PARAMETRO_SISTEMA')
 ORDER BY TABLE_NAME;
-- No deben existir tablas financieras heredadas.
SELECT TABLE_NAME FROM USER_TABLES
 WHERE TABLE_NAME IN ('COMPROBANTE_CITA','HISTORIAL_PARAMETRO','LIQUIDACION_DOCTOR',
  'LIQUIDACION_DETALLE','PAGO_DOCTOR','INGRESO_GESTORA');

-- ========================================================================
-- VALIDACION FINAL (despues de la creacion de objetos y particiones)
-- ========================================================================
DECLARE
 v_tab NUMBER; v_proc NUMBER; v_fn NUMBER; v_tr NUMBER;
 v_vistas NUMBER; v_part NUMBER; v_com NUMBER;
 v_legacy NUMBER; v_err NUMBER;
BEGIN
 SELECT COUNT(*) INTO v_tab FROM USER_TABLES;
 SELECT COUNT(*) INTO v_proc FROM USER_OBJECTS WHERE OBJECT_TYPE='PROCEDURE' AND STATUS='VALID';
 SELECT COUNT(*) INTO v_fn FROM USER_OBJECTS WHERE OBJECT_TYPE='FUNCTION' AND STATUS='VALID';
 SELECT COUNT(*) INTO v_tr FROM USER_OBJECTS WHERE OBJECT_TYPE='TRIGGER' AND STATUS='VALID';
 SELECT COUNT(*) INTO v_vistas FROM USER_OBJECTS WHERE OBJECT_TYPE='VIEW' AND STATUS='VALID';
 SELECT COUNT(*) INTO v_part FROM USER_TABLES WHERE PARTITIONED='YES';
 SELECT COUNT(*) INTO v_com FROM USER_TAB_COMMENTS
 WHERE TABLE_NAME IN (SELECT TABLE_NAME FROM USER_TABLES) AND COMMENTS IS NOT NULL;
 SELECT COUNT(*) INTO v_legacy FROM USER_TABLES WHERE TABLE_NAME IN
 ('LIQUIDACION_DOCTOR','LIQUIDACION_DETALLE','PAGO_DOCTOR','INGRESO_GESTORA','HISTORIAL_PARAMETRO','COMPROBANTE_CITA');
 SELECT COUNT(*) INTO v_err FROM USER_OBJECTS WHERE STATUS='INVALID'
 AND OBJECT_TYPE IN ('PROCEDURE','FUNCTION','TRIGGER','VIEW');
 DBMS_OUTPUT.PUT_LINE('Tablas='||v_tab||', Proc='||v_proc||', Func='||v_fn
 ||', Triggers='||v_tr||', Vistas='||v_vistas
 ||', Particionadas='||v_part||', Comentarios='||v_com||', Legado='||v_legacy
 ||', Objetos invalidos='||v_err);
 IF v_tab<>24 OR v_proc<>28 OR v_fn<>6 OR v_tr<>8 OR
    v_vistas<>6 OR v_part<>24 OR v_com<>24 OR
    v_legacy<>0 OR v_err<>0 THEN
  RAISE_APPLICATION_ERROR(-20913,'Inventario incompleto; revisar USER_ERRORS y los scripts');
 END IF;
END;
/
SELECT NAME,TYPE,LINE,POSITION,TEXT FROM USER_ERRORS ORDER BY NAME,SEQUENCE;
SELECT TABLE_NAME,PARTITIONED FROM USER_TABLES
 ORDER BY TABLE_NAME;
SELECT OBJECT_NAME,OBJECT_TYPE,STATUS FROM USER_OBJECTS
 WHERE OBJECT_TYPE IN ('FUNCTION','PROCEDURE','VIEW','TRIGGER')
 ORDER BY OBJECT_TYPE,OBJECT_NAME;


