-- KARELY'S - BD2 SESIONES 6 Y 7 / CREAR TABLESPACES Y USUARIO
-- CONEXION: SYSTEM / SERVICIO FREEPDB1, NO CDB$ROOT
-- EJECUTAR F5 EN SQL DEVELOPER, SOLO UNA VEZ.
-- NO DROP. NO PRIVILEGIOS ANY/DBA. NO CONTRASENAS GUARDADAS.
-- ============================================================================
SET SERVEROUTPUT ON
SET DEFINE ON
SET VERIFY OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE

-- 1. VERIFICAR LA PDB Y LAS UBICACIONES REALES DE SUS ARCHIVOS
SELECT SYS_CONTEXT('USERENV','CON_NAME') AS PDB_ACTUAL FROM DUAL;
SELECT TABLESPACE_NAME, FILE_NAME FROM DBA_DATA_FILES
WHERE TABLESPACE_NAME IN ('SYSTEM','SYSAUX','USERS')
ORDER BY TABLESPACE_NAME, FILE_NAME;
SELECT TABLESPACE_NAME, FILE_NAME FROM DBA_TEMP_FILES
ORDER BY TABLESPACE_NAME, FILE_NAME;

-- 2. COMPROBAR QUE EL USUARIO Y LOS TABLESPACES NO EXISTAN
SELECT USERNAME FROM DBA_USERS WHERE USERNAME='KARELY_BD2';
SELECT TABLESPACE_NAME FROM DBA_TABLESPACES
WHERE TABLESPACE_NAME IN ('TBS_KARELY_BD2','TMP_KARELY_BD2');

DECLARE
BEGIN
 IF USER <> 'SYSTEM' OR SYS_CONTEXT('USERENV','CON_NAME') <> 'FREEPDB1' THEN
  RAISE_APPLICATION_ERROR(-20901,'Ejecutar como SYSTEM en FREEPDB1');
 END IF;
END;
/

-- 3. CREATE TABLESPACE - SESION 6
-- Escriba DOS RUTAS NUEVAS de archivos dentro del directorio real de la PDB
-- consultado arriba. Nunca reutilice los archivos existentes.
ACCEPT KARELY_DATAFILE CHAR PROMPT 'Nuevo archivo DATAFILE .dbf (ruta completa): '
CREATE TABLESPACE TBS_KARELY_BD2
DATAFILE '&KARELY_DATAFILE' SIZE 250M
AUTOEXTEND ON NEXT 50M MAXSIZE 4G;
UNDEFINE KARELY_DATAFILE

-- 4. CREATE TEMPORARY TABLESPACE - SESION 6
ACCEPT KARELY_TEMPFILE CHAR PROMPT 'Nuevo archivo TEMPFILE .dbf (ruta completa): '
CREATE TEMPORARY TABLESPACE TMP_KARELY_BD2
TEMPFILE '&KARELY_TEMPFILE' SIZE 100M
AUTOEXTEND ON NEXT 25M MAXSIZE 2G;
UNDEFINE KARELY_TEMPFILE

-- 5. CREATE USER - SESION 7
ACCEPT KARELY_PWD CHAR PROMPT 'Contrasena NUEVA para KARELY_BD2: ' HIDE
CREATE USER KARELY_BD2 IDENTIFIED BY "&KARELY_PWD"
DEFAULT TABLESPACE TBS_KARELY_BD2
TEMPORARY TABLESPACE TMP_KARELY_BD2
ACCOUNT UNLOCK;
UNDEFINE KARELY_PWD

-- 6. ALTER USER / PRIVILEGIOS NECESARIOS - SESION 7
ALTER USER KARELY_BD2 QUOTA 3G ON TBS_KARELY_BD2;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW,
      CREATE PROCEDURE, CREATE TRIGGER TO KARELY_BD2;

-- 7. VERIFICACION - SESIONES 6 Y 7
SELECT USERNAME, ACCOUNT_STATUS, DEFAULT_TABLESPACE, TEMPORARY_TABLESPACE
FROM DBA_USERS WHERE USERNAME='KARELY_BD2';
SELECT TABLESPACE_NAME, CONTENTS FROM DBA_TABLESPACES
WHERE TABLESPACE_NAME IN ('TBS_KARELY_BD2','TMP_KARELY_BD2');
SELECT TABLESPACE_NAME, FILE_NAME FROM DBA_DATA_FILES
WHERE TABLESPACE_NAME='TBS_KARELY_BD2';
SELECT TABLESPACE_NAME, FILE_NAME FROM DBA_TEMP_FILES
WHERE TABLESPACE_NAME='TMP_KARELY_BD2';
SELECT GRANTEE, PRIVILEGE FROM DBA_SYS_PRIVS
WHERE GRANTEE='KARELY_BD2' ORDER BY PRIVILEGE;
SELECT USERNAME, TABLESPACE_NAME, MAX_BYTES FROM DBA_TS_QUOTAS
WHERE USERNAME='KARELY_BD2';
