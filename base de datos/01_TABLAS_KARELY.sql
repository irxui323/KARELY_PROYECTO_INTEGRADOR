CREATE TABLE NOTIFICACION_SALIENTE (
 id_notificacion NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 tipo VARCHAR2(30) NOT NULL CHECK(tipo IN ('PAGO_DOCTOR','PAGO_CITA','RECIBO_HONORARIO')),
 canal VARCHAR2(12) DEFAULT 'EMAIL' NOT NULL CHECK(canal IN ('EMAIL')),
 destinatario VARCHAR2(200),
 id_cita NUMBER REFERENCES CITA(id_cita),
 id_liquidacion NUMBER REFERENCES LIQUIDACION(id_liquidacion),
 id_usuario_creacion NUMBER REFERENCES USUARIO(id_usuario),
 codigo_evento VARCHAR2(120) NOT NULL UNIQUE,
 estado VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL CHECK(estado IN ('PENDIENTE','ENVIADA','FALLIDA')),
 intentos NUMBER(2) DEFAULT 0 NOT NULL CHECK(intentos BETWEEN 0 AND 5),
 fecha_creacion TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 fecha_proximo_intento TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 fecha_envio TIMESTAMP,
 ultimo_error VARCHAR2(500),
 CONSTRAINT ck_notif_referencia CHECK(id_cita IS NOT NULL OR id_liquidacion IS NOT NULL),
 CONSTRAINT ck_notif_estado_envio CHECK(estado <> 'ENVIADA' OR fecha_envio IS NOT NULL)
)
PARTITION BY HASH (id_notificacion)
PARTITIONS 4;

